/* Отчёт агента bots — сборка страницы из report.json.
 *
 * Почему данные приходят файлом, а не зашиты в страницу
 * ------------------------------------------------------
 * Числа в отчёте измерены скриптом `tmp/measure_report.py` в момент
 * сбора и лежат в `report.json`. Зашивать их в разметку значило бы
 * заставить страницу врать: через час цифры устареют, а менять
 * придётся руками, и рано или поздно в отчёте окажется правдоподобное
 * неправдивое число.
 *
 * Здесь нет ни одной константы с фактом. Всё, что видно, пришло
 * из файла; чего в файле нет — не показано вовсе.
 */

