async function загрузить() {
  try {
    const ответ = await fetch(`${ДАННЫЕ}?t=${Date.now()}`, { cache: "no-store" });
    if (!ответ.ok) throw new Error(`HTTP ${ответ.status}`);
    отчёт = await ответ.json();
  } catch (ошибка) {
    поле("когда-собрано").textContent =
      `отчёт не загрузился: ${ошибка.message}. Обновите страницу.`;
    return;
  }

  поле("когда-собрано").textContent =
    `замеры сняты ${время(отчёт.собрано)}`;
  поле("машина").textContent =
    (отчёт.машина && отчёт.машина.имя) || "—";

  // Деки: честная сводка одним взглядом.
  const деки = поле("шапка-деки");
  const боты = отчёт.боты_живые || {};
  const запущено = Object.values(боты).filter((b) => b.опрашивает).length;
  const всего = Object.keys(боты).length;
  деки.append(дека(запущено ? "хорошо" : "плохо",
    `ботов запущено <b>${запущено} из ${всего}</b>`));
  const pa = отчёт.pythonanywhere || {};
  // Отвечает ли PythonAnywhere — выводится из того, удалось ли снять
  // квоту. Не из отдельного флага: флаг можно забыть обновить, а
  // запрос либо прошёл, либо нет.
  const жив = Boolean(pa.квота);
  деки.append(дека(жив ? "хорошо" : "плохо",
    жив ? "PythonAnywhere <b>отвечает</b>"
        : "PythonAnywhere <b>не отвечает</b>"));
  const почта = отчёт.почта || {};
  деки.append(дека((почта.send_balance || 0) > 0 ? "хорошо" : "плохо",
    "почта <b>не отправляет</b>"));

  нарисоватьСводку();
  нарисоватьРаботы();
  нарисоватьПоломки();
  нарисоватьАдреса();
  нарисоватьГрабли();
  нарисоватьПроверки();
}

