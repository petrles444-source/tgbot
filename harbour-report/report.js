/* ------------------------------------------------------------- формат */

function время(iso) {
  if (!iso) return "—";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString("ru-RU", {
    day: "2-digit", month: "2-digit",
    hour: "2-digit", minute: "2-digit",
  }) + " UTC";
}

function узел(тег, класс, текст) {
  const n = document.createElement(тег);
  if (класс) n.className = класс;
  if (текст !== undefined && текст !== null) n.textContent = String(текст);
  return n;
}

/* ---------------------------------------------------------- деки */

function дека(статус, текст) {
  const d = узел("div", `дека дека--${статус}`);
  d.append(узел("span", "дека-значок"));
  d.append(узел("span", "дека-текст", текст));
  return d;
}

/* --------------------------------------------------------- сводка */

function плитка(число, подпись, тон) {
  const d = узел("div", "плитка");
  d.append(узел("div", `плитка-число ${тон || "обычно"}`, число));
  d.append(узел("div", "плитка-подпись", подпись));
  return d;
}

function нарисоватьСводку() {
  const п = поле("плитки");
  п.textContent = "";

  const боты = отчёт.боты_живые || {};
  const запущено = Object.values(боты).filter((b) => b.опрашивает).length;
  const всего = Object.keys(боты).length || 0;

  п.append(плитка(`${запущено} / ${всего}`,
    "ботов запущено сейчас", запущено ? "хорошо" : "плохо"));
  п.append(плитка(`${Object.values(боты).filter((b) => b.токен).length} / ${всего}`,
    "токенов рабочих", "обычно"));

  const pa = отчёт.pythonanywhere || {};
  if (pa.квота) {
    const использовано = pa.квота.использовано;
    const лимит = pa.квота.лимит || 0;
    const доля = лимит ? Math.round(100 * использовано / лимит) : 0;
    п.append(плитка(`${использовано} с`, `квота CPU из ${лимит} (${доля}%)`,
      доля > 80 ? "плохо" : доля > 50 ? "внимание" : "обычно"));
  }

  if (pa.боты_на_сервере) {
    п.append(плитка(pa.боты_на_сервере.знания || 0,
      "файлов базы знаний на сервере", "обычно"));
  }

  const ftp = отчёт.ftp || {};
  if (ftp.аварийный_канал) {
    п.append(плитка(ftp.аварийный_канал.inbox || 0,
      "писем в аварийном канале", "обычно"));
  }
  if (ftp.лендинг) {
    п.append(плитка(ftp.лендинг.файлов || 0,
      "файлов на лендинге", "обычно"));
  }

  const почта = отчёт.почта || {};
  if (почта.address) {
    п.append(плитка(`${почта.send_balance ?? 0}`,
      "баланс отправки писем",
      (почта.send_balance || 0) > 0 ? "хорошо" : "плохо"));
  }

  поле("сноска-меры").textContent =
    `Замеры сняты ${время(отчёт.собрано)}. ` +
    `Проверка ботов идёт запросом getUpdates к Telegram: ` +
    `если бот запущен, приходит 409 Conflict — это проверка поведения, ` +
    `а не чтения конфига.`;
}

