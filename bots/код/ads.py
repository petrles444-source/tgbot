#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Редкая реклама VPN — голосом того бота, который её произносит.

ЗАЧЕМ ТАК СЛОЖНО, А НЕ ПРОСТО ВСТАВИТЬ ССЫЛКУ
----------------------------------------------
Заказ: «редкая, очень реклама нашего впн». Слово «очень» читаю как
«очень аккуратная», а не «очень частая». Человек получает от бота
десятки ответов, и реклама в каждом втором превратила бы бота в
рекламную рассылку — после этого его перестанут читать.

Поэтому частота низкая и есть жёсткое ограничение за всё время работы:
один раз на бота. Не «каждые двадцать сообщений», а «один раз за всё
время». Человек заметит это один раз, и это сработает как
рекомендация, а не как давление.

ПОЧЕМУ ТЕКСТ РАЗНЫЙ У КАЖДОГО БОТА
----------------------------------
Ада — тёплая и живая. Анатолий — сухой и по делу. Effy — про тексты.
Одна и та же фраза из трёх ботов выдала бы генерацию шаблона мгновенно:
человек читает «настройте VPN на своём сервере» трижды за вечер и
понимает, что это реклама, а не разговор.

ЧТО ИМЕННО ГОВОРИТСЯ
--------------------
Короткий курс бесплатный и на своём сервере: это главное отличие от
всех прочих VPN и единственное, ради чего стоит сказать. Без этого
реклама не отличается от любой другой.

ПОЧЕМУ НЕТ ССЫЛКИ В САМОМ ТЕКСТЕ
--------------------------------
Ссылка в сообщении от бота выглядит как спам и портит всё впечатление.
Адрес отдаётся по запросу: человек спросил — бот ответил. Так человек
сам проявил интерес, и это уже не реклама, а ответ на вопрос.
"""

from __future__ import annotations

import random
import sys
from typing import Any

#: Шанс на попытку за одно сообщение. Низкий сам по себе, но главное
#: ограничение ниже — «один раз за всё время».
ШАНС_ЗА_СООБЩЕНИЕ = 0.02

#: Адрес курса. Отдаётся только по запросу, не вставляется в текст.
КУРС = "https://petrles444-source.github.io/SORA/"

#: Ключи для счётчика — по имени бота.
_ОТДАНО: set[str] = set()


def _фразы(имя_бота: str) -> list[str]:
    """Тексты по ролям. Один источник правды — не дублировать."""
    речи: dict[str, list[str]] = {
        "ada": [
            "Слушай, если захочешь настоящий VPN, а не общий — есть "
            "бесплатный курс, там всё по шагам и сервер свой.",
            "Кстати. Если замучают общие адреса — есть штука получше, "
            "свой сервер и свой адрес. Курс бесплатный, я скину.",
        ],
        "anatoly": [
            "Отдельно по теме. Общий VPN-адрес — это одна точка отказа, "
            "и трафик всех видно сразу. Свой сервер это убирает. Курс "
            "бесплатный, дам адрес.",
            "Практика: поднять VPN на своём сервере проще, чем кажется, "
            "есть пошаговый курс. Без ограничений по чужим лимитам.",
        ],
        "effy": [
            "Текстово: «свой VPN» читается честнее, чем «защищённый "
            "VPN». И есть бесплатный курс, где это расписано.",
            "Отступление, но по делу. Общий адрес — общий риск. Свой "
            "сервер снимает вопрос, есть бесплатная инструкция.",
        ],
    }
    ключ = str(имя_бота or "").strip().lower()
    for известный in речи:
        if известный in ключ:
            return речи[известный]
    return речи["ada"]


def _название_бота(имя_бота: str) -> str:
    """Человеческое имя для текста рекламы."""
    ключ = str(имя_бота or "").strip().lower()
    if "anatol" in ключ:
        return "Анатолий"
    if "effy" in ключ:
        return "Effy"
    return "Ада"


def показать(имя_бота: str, история: Any = None) -> str | None:
    """Редкая реклама. None — сейчас не время.

    Ограничение «один раз за всё время» хранится в памяти процесса.
    Если бот перезапустится, счётчик обнулится: это осознанный размен
    между точностью и простотой. Хранить его на диске ради одной
    строчки смысла нет — при перезапуске человек всё равно получит
    заново, а вот лишний файл в /var/lib он бы засорол.
    """
    ключ = str(имя_бота or "").lower()
    if ключ in _ОТДАНО:
        return None
    if random.random() >= ШАНС_ЗА_СООБЩЕНИЕ:
        return None
    _ОТДАНО.add(ключ)
    варианты = _фразы(имя_бота)
    return random.choice(варианты)


def добавить_хвост(имя_бота: str, текст: str) -> str:
    """Дописывает рекламу к ответу, если она полагается."""
    реклама = показать(имя_бота)
    if not реклама or not текст.strip():
        return текст
    return f"{текст}\n\n{реклама}"


def ссылка() -> str:
    """Адрес курса. Отдаётся по запросу, а не вставляется сам."""
    return КУРС


def сбросить() -> None:
    """Только для самопроверки."""
    _ОТДАНО.clear()


# ─── Самопроверка ───────────────────────────────────────────────────────────

def самопроверка() -> bool:
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА рекламы ===")

    # тексты
    for бот in ("ada", "anatoly", "effy"):
        чек(f"у {бот} есть фразы", len(_фразы(бот)) >= 2)
    чек("неизвестный бот не ломает", len(_фразы("кто-то")) >= 2)
    чек("фразы у ботов разные",
        _фразы("ada") != _фразы("anatoly") != _фразы("effy"))

    # человеческие имена
    чек("Анатолий узнан по части имени", _название_бота("anatoly") == "Анатолий")
    чек("Effy узнана", _название_бота("effy") == "Effy")
    чек("неизвестный -> Ада", _название_бота("xyz") == "Ада")

    # ограничение «один раз»
    сбросить()
    выдано = 0
    for _ in range(3000):
        if показать("ada") is not None:
            выдано += 1
    чек("за 3000 попыток выдано не больше одного раза", выдано <= 1,
        f"выдано {выдано}")

    сбросить()
    for _ in range(3000):
        показать("ada")
    чек("после срабатывания больше не выдаётся",
        показать("ada") is None)

    # каждый бот живёт своим счётчиком
    сбросить()
    random.seed(1)
    показать("ada")
    чек("у Ады счётчик сработал, у Анатолия нет",
        показать("ada") is None)

    # вероятность правдоподобна
    сбросить()
    попаданий = 0
    for _ in range(20000):
        if random.random() < ШАНС_ЗА_СООБЩЕНИЕ:
            попаданий += 1
    чек("вероятность около 2%", 300 < попаданий < 500,
        f"из 20000 попаданий {попаданий}")

    # хвост
    # Шанс 2 %, поэтому на живом шансе хвост мог бы и не сработать,
    # и проверка прошла бы вхолостую. Поднимаем шанс до 100 % на
    # время проверки: проверяем мы сам хвост, а не его везение.
    старый_шанс = ШАНС_ЗА_СООБЩЕНИЕ
    globals()["ШАНС_ЗА_СООБЩЕНИЕ"] = 1.0
    try:
        # Сбрасываем перед каждой проверкой: счётчик «один раз» общий
        # на бота, и первая же проверка расходовала единственную
        # разрешённую рекламу — вторая её уже не получала.
        сбросить()
        чек("пустой ответ не меняется", добавить_хвост("ada", "") == "")
        original = "Текст ответа"
        сбросить()
        вывод = добавить_хвост("ada", original)
        чек("ответ сохранён целиком", вывод.startswith(original))
        чек("реклама добавлена через пустую строку", "\n\n" in вывод,
            repr(вывод[:60]))
        чек("ссылки в тексте рекламы нет", КУРС not in вывод)
        чек("реклама не пустая", len(вывод) > len(original) + 10)
        чек("второй раз хвост не добавляется",
            добавить_хвост("ada", original) == original)
        # У каждого бота свой счётчик: реклама Ады не тратит запас
        # Анатолия, иначе второй бот молчал бы всю жизнь.
        сбросить()
        чек("у анатолия своя реклама",
            добавить_хвост("anatoly", original) != original)
    finally:
        globals()["ШАНС_ЗА_СООБЩЕНИЕ"] = старый_шанс

    # ссылка отдаётся отдельно
    чек("адрес курса есть", КУРС.startswith("https://"))

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(0 if самопроверка() else 2)