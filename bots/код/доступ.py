#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Белый список: кому вообще можно пользоваться секретным ботом.

ЗАЧЕМ
-----
Владелец потребовал: доклады видят только его два аккаунта и
сотрудники студии, остальным — закрытый доступ. И сам бот не должен
быть заметен.

ПОЧЕМУ ЧУЖОМУ МОЛЧИМ, А НЕ ГОВОРИМ «ДОСТУП ЗАКРЫТ»
---------------------------------------------------
Два ответа выглядят одинаково снаружи, но говорят разное:

    «Доступ закрыт»       — бот существует, он живой, есть хозяин.
                              Человек узнаёт, что канал связи есть,
                              и будет искать, кому принадлежит.
    молчание              — бот либо удалён, либо никогда не работал.
                              Ничего не узнаётся и искать нечего.

Поэтому чужие получают полное молчание. Попытка не теряется: она
пишется в журнал с отпечатком номера человека, чтобы владелец мог
увидеть, кто стучался.

ЧТО ТОЖЕ НЕДЕЛАЕМ
------------------
    Не показываем чужим ни приветствия, ни списка команд, ни отказа.
    Если человек успел нажать /start до включения белого списка, он
    не должен получать ничего — иначе он поймёт, что его отфильтровали.

ГДЕ БЕЛЫЙ СПИСОК
-----------------
    /etc/sora/секретный-доступ.json

    По умолчанию там пусто, и это важно: **пока список пуст, бот не
    отвечает никому** — ни включая владельца. Так сделано намеренно.
    Молчащий отладочный бот опаснее говорящего: иначе первая же
    опечатка в списке закрывает канал связи целиком, и заметить это
    можно будет только потому, что владелец позвонил и не дождался.
    Пустой список виден сразу и честно.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

СПИСОК = Path("/etc/sora/секретный-доступ.json")
ЖУРНАЛ_ОТКАЗОВ = Path("/var/log/bots/секретный-доступ.log")


def отпечаток(значение: Any) -> str:
    """Номер человека в неразворотном виде."""
    return hashlib.sha256(str(значение).encode("utf-8")).hexdigest()[:12]


def _прочитать() -> dict[str, Any]:
    if not СПИСОК.exists():
        return {"owners": [], "staff": []}
    try:
        данные = json.loads(СПИСОК.read_text(encoding="utf-8"))
        if isinstance(данные, dict):
            return {
                "owners": [str(x).lower().lstrip("@")
                           for x in данные.get("owners") or []],
                "staff": [str(x).lower().lstrip("@")
                          for x in данные.get("staff") or []],
            }
    except (ValueError, OSError):
        pass
    return {"owners": [], "staff": []}


def список() -> dict[str, list[str]]:
    return _прочитать()


def добавить(имя: str, роль: str) -> bool:
    """Добавляет имя в белый список. Роль: owners или staff."""
    роль = str(роль or "").lower()
    if роль not in ("owners", "staff"):
        return False
    данные = _прочитать()
    имя = str(имя or "").lower().lstrip("@")
    if not имя:
        return False
    if имя not in данные[роль]:
        данные[роль].append(имя)
    СПИСОК.parent.mkdir(parents=True, exist_ok=True)
    СПИСОК.write_text(json.dumps({
        "owners": sorted(set(данные["owners"])),
        "staff": sorted(set(данные["staff"])),
        "_что-это": (
            "Белый список секретного бота. owners — владелец, "
            "staff — сотрудники студии. Чужим бот не отвечает вовсе. "
            "Пустой список означает, что не отвечает никому."),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return True


def удалить(имя: str) -> bool:
    имя = str(имя or "").lower().lstrip("@")
    данные = _прочитать()
    было = имя in данные["owners"] or имя in данные["staff"]
    данные["owners"] = [x for x in данные["owners"] if x != имя]
    данные["staff"] = [x for x in данные["staff"] if x != имя]
    СПИСОК.write_text(json.dumps({
        "owners": sorted(данные["owners"]),
        "staff": sorted(данные["staff"]),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return было


def роль(юзернейм: str | None, номер: Any = None) -> str:
    """Роль человека: owners, staff, никто, или «список пуст»."""
    данные = список()
    if not данные["owners"] and not данные["staff"]:
        return "закрыт"
    имя = str(юзернейм or "").lower().lstrip("@")
    if имя and имя in данные["owners"]:
        return "owners"
    if имя and имя in данные["staff"]:
        return "staff"
    # Номер без юзернейма тоже сверяем: человек мог скрыть имя.
    if номер is not None and номер != "":
        отп = отпечаток(номер)
        for запись in _номера():
            if запись.get("отпечаток") == отп:
                if запись.get("роль") == "owners":
                    return "owners"
                if запись.get("роль") == "staff":
                    return "staff"
    return "никто"


_НОМЕРА = Path("/var/lib/sdc/разрешённые.json")


def _номера() -> list[dict[str, Any]]:
    """Номера тех, кто подтвердил себя. Заполняются при входе."""
    if not _НОМЕРА.exists():
        return []
    try:
        данные = json.loads(_НОМЕРА.read_text(encoding="utf-8"))
        return данные if isinstance(данные, list) else []
    except (ValueError, OSError):
        return []


def запомнить_номер(номер: Any, роль_человека: str, юзернейм: str) -> None:
    """Запоминает номер человека, чтобы пускать и без юзернейма."""
    записи = [з for з in _номера()
              if з.get("отпечаток") != отпечаток(номер)]
    записи.append({
        "отпечаток": отпечаток(номер),
        "роль": роль_человека,
        "юзернейм": юзернейм or None,
        "когда": __import__("datetime").datetime.now().isoformat(timespec="seconds"),
    })
    _НОМЕРА.parent.mkdir(parents=True, exist_ok=True)
    _НОМЕРА.write_text(json.dumps(записи, ensure_ascii=False, indent=2),
                       encoding="utf-8")


def записать_отказ(юзернейм: str | None, номер: Any, текст_реплики: str) -> None:
    """Попытка чужого. Текст реплики не сохраняется — достаточно факта."""
    строка = (f"{__import__('datetime').datetime.now():%Y-%m-%d %H:%M:%S}  "
              f"ОТКАЗ отпечаток={отпечаток(номер)} "
              f"юзернейм={юзернейм or 'нет'} "
              f"длина_реплики={len(текст_реплики or '')}")
    try:
        ЖУРНАЛ_ОТКАЗОВ.parent.mkdir(parents=True, exist_ok=True)
        with open(ЖУРНАЛ_ОТКАЗОВ, "a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except OSError:
        pass


def пуст() -> bool:
    """Список пуст — значит бот не отвечает никому."""
    данные = список()
    return not данные["owners"] and not данные["staff"]


# ─── Самопроверка ───────────────────────────────────────────────────────────

def самопроверка() -> bool:
    import shutil
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА белого списка ===")

    основа = Path(__file__).resolve().parent / ".проверка-доступа"
    shutil.rmtree(основа, ignore_errors=True)
    основа.mkdir(parents=True, exist_ok=True)
    старый_список = globals()["СПИСОК"]
    старый_номера = globals()["_НОМЕРА"]
    старый_журнал = globals()["ЖУРНАЛ_ОТКАЗОВ"]
    globals()["СПИСОК"] = основа / "доступ.json"
    globals()["_НОМЕРА"] = основа / "номера.json"
    globals()["ЖУРНАЛ_ОТКАЗОВ"] = основа / "отказы.log"
    try:
        _тело(чек)
    finally:
        globals()["СПИСОК"] = старый_список
        globals()["_НОМЕРА"] = старый_номера
        globals()["ЖУРНАЛ_ОТКАЗОВ"] = старый_журнал
        shutil.rmtree(основа, ignore_errors=True)

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


def _тело(чек) -> None:
    # пустой список — бот молчит всем
    чек("без файла список пуст", пуст() is True)
    чек("без файла роль = закрыт", роль("кто-угодно", 1) == "закрыт")
    чек("без файла владелец тоже не пущен", роль("@lastats", 1) == "закрыт")

    # добавление
    чек("владелец добавлен", добавить("lastats", "owners"))
    чек("второй владелец добавлен", добавить("holylie88", "owners"))
    чек("сотрудник добавлен", добавить("maria", "staff"))
    чек("неверная роль отвергнута", добавить("x", "директор") is False)
    чек("пустое имя отвергнуто", добавить("", "owners") is False)
    чек("список больше не пуст", пуст() is False)

    # роли
    чек("владелец по юзернейму", роль("@lastats", 1) == "owners")
    чек("владелец без @", роль("lastats", 1) == "owners")
    чек("владелец в верхнем регистре", роль("LASTATS", 1) == "owners")
    чек("второй владелец пущен", роль("@holylie88", 2) == "owners")
    чек("сотрудник пущен", роль("@maria", 3) == "staff")
    чек("чужой не пущен", роль("@someone", 4) == "никто")
    чек("пустой юзернейм не пускает", роль(None, 5) == "никто")
    чек("чужой юзернейм с @", роль("@stranger", 6) == "никто")

    # по номеру без юзернейма
    запомнить_номер(777, "owners", "lastats")
    чек("владелец пущен по номеру без юзернейма",
        роль(None, 777) == "owners")
    чек("но чужой номер не пущен", роль(None, 778) == "никто")

    # отказ пишется, текст не пишется
    до = len(ЖУРНАЛ_ОТКАЗОВ.read_text(encoding="utf-8")) \
        if ЖУРНАЛ_ОТКАЗОВ.exists() else 0
    записать_отказ("@stranger", 999, "очень секретный текст")
    после = ЖУРНАЛ_ОТКАЗОВ.read_text(encoding="utf-8")
    чек("отказ записан", len(после) > до)
    чек("текст реплики НЕ сохранён", "очень секретный текст" not in после)
    чек("отпечаток в журнале есть", отпечаток(999) in после)

    # удаление
    чек("владелец удалён", удалить("holylie88") is True)
    чек("после удаления не пущен", роль("@holylie88", 2) == "никто")
    чек("остальные не тронуты", роль("@lastats", 1) == "owners")
    чек("удаление отсутствующего — False", удалить("нет-такого") is False)

    # битой файл
    СПИСОК.write_text("не json", encoding="utf-8")
    чек("битый файл не ломает и не пускает всех", пуст() is True)
    чек("битый файл = закрыт", роль("@lastats", 1) == "закрыт")

    # отпечаток
    чек("отпечаток стабилен", отпечаток(1) == отпечаток(1))
    чек("отпечатки разные", отпечаток(1) != отпечаток(2))
    чек("номер не в отпечатке", "12345" not in отпечаток(12345))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ok = самопроверка()
    sys.exit(0 if ok else 2)