r"""Приветствия: своё у каждого бота и никогда два одинаковых подряд.

Зачем этот файл
---------------
Раньше приветствия жили в `chars.py` как `lambda` с одним зашитым
текстом, и все боты говорили одно и то же: «Привет. Ну как ты?
Рассказывай.» На скриншоте это видно — два одинаковых ответа
подряд.

Здесь две вещи, которых раньше не было:

1. **Своё приветствие у каждого бота.** Ада здоровается иначе,
   чем Анатолий и Кети: не только другими словами, но и по
   характеру. Иначе в беседе, где сидят все трое, разговор
   выглядит так, будто говорит один человек.

2. **Никогда два одинаковых подряд.** Случайность сама по себе
   повторяется: при пяти вариантах совпадение подряд — дело
   времени. Повтор исключается явно.

Почему не в `chars.py`
---------------------
Там лежит логика: что считать кодом, а что отдавать модели.
Приветствия — это тексты конкретных ботов, и держать их рядом с
логикой оказалось неудобно: править надо одно, а страдает
другое.

Почему без ключа бота, а по персоне
----------------------------------
`chars.builtin_answer` знает только `char_key`. Этого хватает и
здесь: у каждого бота своя персона, а значит свой набор строк.
"""

from __future__ import annotations

import random

#: Приветствия по персонам.
#:
#: Ключ — `char_key`, то есть тот же, что и в `bots.json`.
#: Фразы короткие и разные по интонации: Ада здоровается тепло,
#: Анатолий — по-деловому, Effy — тепло и с предупреждениями. Если написать всем одно
#: и то же с разными словами в конце, разница не читается.
GREETINGS: dict[str, list[str]] = {
    "ada": [
        "Привет. Ну как ты?",
        "О, привет. Как оно?",
        "Здарова. Что у тебя?",
        "Привет-привет. На чём остановились?",
        "Ой, ты привет. Рассказывай, что нового.",
        "Привет! Я тут, если что.",
    ],
    "anatoly": [
        "Привет. Что сломалось?",
        "Здравствуйте. Готов разбираться.",
        "О, привет. Показывайте, что не работает.",
        "Привет. С чего начнём?",
        "Здравствуйте. Что будем чинить?",
        "Привет! Слушаю вас.",
    ],
    "effy": [
        "Привет! Что напишем?",
        "О, привет. Идеи уже есть?",
        "Привет-привет. С чего начнём?",
        "Здравствуйте. Что будем делать?",
        "Привет. Я готова, давай.",
        "О, ты привет! Что будем делать?",
    ],
}

#: Для персон, которых нет в списке. Нужен, чтобы новый бот
#: заговорил сразу, а не молчал до правки этого файла.
DEFAULT = [
    "Привет. Я тут.",
    "Здравствуйте. Что нужно?",
    "Привет! Слушаю.",
    "О, привет. Рассказывай.",
]

#: Что было сказано в прошлый раз, по персонам. Без этого
#: случайность рано или поздно выдаст тот же вариант дважды.
_LAST: dict[str, str] = {}


def pick(char_key: str) -> str:
    """Приветствие для бота, не повторяя предыдущее.

    Повтор исключаем явно: если выпал тот же вариант, берём
    следующий по кругу. На трёх вариантах это даёт гарантию, что
    два соседних приветствия всегда разные.
    """
    variants = GREETINGS.get(char_key) or DEFAULT
    if len(variants) == 1:
        return variants[0]
    choice = random.choice(variants)
    if choice == _LAST.get(char_key):
        index = variants.index(choice)
        choice = variants[(index + 1) % len(variants)]
    _LAST[char_key] = choice
    return choice


def short_greeting(char_key: str) -> str:
    """Короткая строка для `/start`: кто я, в одну-две строки.

    Отдельно от `pick()`, потому что у него другая задача: не
    разнообразие, а узнаваемость. Человек открывает чат с тремя
    ботами и должен за одну секунду понять, кто отвечает.
    """
    names = {
        "ada": "Я Ада. Спрашивай что угодно — отвечу по-русски.",
        "anatoly": "Я Анатолий. Присылай код или текст ошибки — "
                   "разберёмся.",
        "effy": "Я Effy. Пишу, перевожу и объясняю — как удобнее.",
    }
    return names.get(char_key, "Я бот. Спрашивай — отвечу по-русски.")