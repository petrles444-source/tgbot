def чат() -> int:
    try:
        return int(json.loads(ПОДПИСЧИК.read_text(encoding="utf-8"))
                   .get("chat_id") or 0)
    except (ValueError, OSError, TypeError):
        return 0


def отправить(токен: str, куда: int, текст: str) -> dict:
    запрос = urllib.request.Request(
        f"https://api.telegram.org/bot{токен}/sendMessage",
        data=json.dumps({"chat_id": куда, "text": текст}).encode("utf-8"),
        headers={"Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(запрос, timeout=60) as ответ:
        return json.loads(ответ.read().decode("utf-8"))


def главная() -> int:
    if not ТОКЕН.exists():
        print("нет токена бота", file=sys.stderr)
        return 1
    токен = ТОКЕН.read_text(encoding="utf-8").strip()
    куда = чат()
    if not куда:
        print("подписчик ещё не написал боту", file=sys.stderr)
        return 1
    for номер, текст in enumerate(ПИСЬМА, 1):
        д = отправить(токен, куда, текст)
        print(f"  часть {номер}: ok={д.get('ok')} "
              f"id={д.get('result', {}).get('message_id')} "
              f"символов={len(текст)}")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(главная())