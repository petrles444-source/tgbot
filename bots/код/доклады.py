def самопроверка() -> bool:
    """Все проверки — во временной папке, живая очередь не трогается."""
    import shutil
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА докладов ===")

    основа = Path(__file__).resolve().parent / ".проверка-докладов"
    shutil.rmtree(основа, ignore_errors=True)
    основа.mkdir(parents=True, exist_ok=True)
    старые = {имя: globals()[имя] for имя in ("ДАННЫЕ", "ОЧЕРЕДЬ", "ГОТОВЫ",
                                            "ЖУРНАЛ")}
    globals()["ДАННЫЕ"] = основа
    globals()["ОЧЕРЕДЬ"] = основа / "очередь"
    globals()["ГОТОВЫ"] = основа / "отправлено"
    globals()["ЖУРНАЛ"] = основа / "журнал.jsonl"
    try:
        _тело(чек)
    finally:
        globals().update(старые)
        shutil.rmtree(основа, ignore_errors=True)

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


