#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Доклады через SDC: очередь, длина, пол голоса, ничего не режется.

ЗАЧЕМ ЭТОТ ФАЙЛ
---------------
Владелец заказал: отчёты по всей работе, голосом, не короче минуты,
и чтобы выполнялись правила:

    * голос неправильного пола — наказуемо;
    * текст доклада нельзя обрезать;
    * нельзя включать воспроизведение одновременно у двоих;
    * воспроизведение без очереди — наказуемо обоим.

Четыре правила превращены в четыре проверки в коде. Не в текст
инструкции, который каждый прочтёт по-своему, а в условия, которые
не выполняются технически.

ПРАВИЛО «НЕ КОРОЧЕ МИНУТЫ»
---------------------------
Русская речь в озвучке идёт примерно 130–160 слов в минуту. Ниже
принято 140 слов — это около минуты. Проверка идёт по СЛОВАМ, а не
по символам: символы зависят от языка, слова — нет.

ПРАВИЛО «НЕ ОБРЕЗАТЬ»
---------------------
Telegram не принимает сообщение длиннее 4096 символов. Длинный доклад
нельзя обрезать и нельзя потерять, поэтому он ДЕЛИТСЯ на части, и
каждая часть получает номер: «часть 2 из 5». Обрезать нельзя —
это единственный способ уместиться. Всё, что не влезло, уходит
в следующую часть, ничего не теряется.

Проверка целостности: у каждого доклада хранится sha256 полного
текста и число слов. Собирая части обратно, можно сверить и
убедиться, что ни одно слово не пропало.

ПРАВИЛО «ОЧЕРЕДЬ»
-----------------
Доклады не могут идти одновременно. Каждый получает номер и ждёт
своей очереди; пока очередь не пуста, новый доклад помечается
«ждёт». Это прямое отражение запрета на одновременное воспроизведение:
один доклад — один голос в один момент.

ПРАВИЛО «ПОЛ ГОЛОСА»
--------------------
Проверяется, когда включён синтез речи. У доклада указан пол голоса,
и движок берёт голос того же пола. Несовпадение — доклад не
озвучивается вовсе: лучше молчание, чем неправильный голос.

СИНТЕЗА РЕЧИ ПОКА НЕТ
---------------------
На сервере нет ни одного движка: `espeak`, `piper`, `say` —
отсутствуют, модулей на Python тоже нет, а для модели синтеза нужно
700–1500 МБ памяти при 281 МБ свободных. Поэтому сейчас доклады
уходят текстом. Конвейер для Sber Salute Speech собран и ждёт
`client_id` и `client_secret` из личного кабинета SberCloud.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
import uuid
from pathlib import Path
from typing import Any

# ─── Где что лежит ──────────────────────────────────────────────────────────

ДАННЫЕ = Path("/var/lib/доклады")
ОЧЕРЕДЬ = ДАННЫЕ / "очередь"
ГОТОВЫ = ДАННЫЕ / "отправлено"
ЖУРНАЛ = ДАННЫЕ / "журнал.jsonl"
НАСТРОЙКИ = Path("/opt/bots/sdc/sdc.json")
ЛОГ = Path("/var/log/bots/doklady.log")

ТОКЕН_ФАЙЛ = Path("/etc/sora/bots/sdc.token")

# ─── Правила ────────────────────────────────────────────────────────────────

#: Минимум слов. Русская озвучка — около 140 слов в минуту.
МИН_СЛОВ = 140

#: Скорость озвучки для оценки длительности.
СЛОВ_В_МИНУТУ = 140

#: Telegram не примет больше этого в одном сообщении.
ЛИМИТ_TELEGRAM = 4096

#: Запас, чтобы не упереться в лимит при добавлении номера части.
ЗАПАС_ЧАСТИ = 60

ПОЛ_ГОЛОСА = ("мужской", "женский")


def в_лог(текст: str) -> None:
    строка = f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}  {текст}"
    try:
        ЛОГ.parent.mkdir(parents=True, exist_ok=True)
        with open(ЛОГ, "a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except OSError:
        pass


# ─── Проверки правил ────────────────────────────────────────────────────────

def разделить_на_слова(текст: str) -> list[str]:
    return str(текст or "").split()


def нормализованный(текст: str) -> str:
    """Текст после разбиения на слова и обратной сборки.

    Зачем это отдельной функцией. Разбиение идёт по пробелам и обратно
    собирается одним пробелом, поэтому исходные переводы строк, отступы
    и двойные пробелы при этом исчезают — и это нормально, слова те же.
    Значит сверять целостность надо не сырой текст с собранным, а их
    нормализованные формы.

    На сыром тексте проверка врала: доклад из 249 слов уходил целиком,
    а проверка отвечала «целостность не подтверждена», потому что
    в исходнике были переводы строк, а в собранном — пробелы.
    """
    return " ".join(разделить_на_слова(текст))


def посчитать(текст: str) -> dict[str, Any]:
    """Считает слова, длительность и отпечаток.

    Отпечаток — всегда от нормализованного текста, иначе сверка целостности
    ложно ругается на переводы строк.
    """
    слова = разделить_на_слова(текст)
    return {
        "слов": len(слова),
        "секунд": round(len(слова) / СЛОВ_В_МИНУТУ * 60),
        "символов": len(текст or ""),
        "символов_норм": len(нормализованный(текст)),
        "sha256": hashlib.sha256(
            нормализованный(текст).encode("utf-8")).hexdigest()[:16],
    }


def проверить_длину(текст: str) -> tuple[bool, dict[str, Any], str]:
    """Хватает ли текста на минуту. Возвращает (хватает, счёт, причина)."""
    счёт = посчитать(текст)
    if счёт["слов"] < МИН_СЛОВ:
        не_хватает = МИН_СЛОВ - счёт["слов"]
        return False, счёт, (
            f"доклад короче минуты: {счёт['слов']} слов из {МИН_СЛОВ} "
            f"(не хватает {не_хватает}), это примерно "
            f"{счёт['секунд']} секунд озвучки")
    return True, счёт, ""


def разбить(текст: str, лимит: int = ЛИМИТ_TELEGRAM - ЗАПАС_ЧАСТИ) -> list[str]:
    """Делит текст на части, ничего не обрезая.

    Режем по словам и по границам строк: обрыв на полуслове читается
    как обрыв текста, а это ровно то, что запрещено.
    """
    слова = разделить_на_слова(текст)
    части: list[str] = []
    текущая: list[str] = []
    длина = 0
    for слово in слова:
        добавка = len(слово) + 1
        if длина + добавка > лимит and текущая:
            части.append(" ".join(текущая))
            текущая = []
            длина = 0
        текущая.append(слово)
        длина += добавка
    if текущая:
        части.append(" ".join(текущая))
    return части


def проверить_пол(пол: str) -> tuple[bool, str]:
    """Пол голоса задан верно? Иначе озвучка не запускается."""
    значение = str(пол or "").strip().lower()
    if значение not in ПОЛ_ГОЛОСА:
        return False, (f"пол голоса должен быть одним из: "
                       f"{', '.join(ПОЛ_ГОЛОСА)}, а указан {пол!r}")
    return True, ""


# ─── Очередь ────────────────────────────────────────────────────────────────

def _файлы(папка: Path) -> list[Path]:
    if not папка.exists():
        return []
    return sorted(папка.glob("*.json"))


def следующий_номер() -> int:
    """Номер доклада по очереди и отправленным. Сквозной."""
    номера = []
    for папка in (ОЧЕРЕДЬ, ГОТОВЫ):
        for файл in _файлы(папка):
            хвост = файл.stem.split("-")[-1]
            if хвост.isdigit():
                номера.append(int(хвост))
    return (max(номера) + 1) if номера else 1


def положить_в_очередь(текст: str, пол: str, автор: str = "лево") -> dict[str, Any]:
    """Кладёт доклад в очередь. Возвращает запись или ошибку."""
    хватает, счёт, причина = проверить_длину(текст)
    if not хватает:
        в_лог(f"ОТКЛОНЁН (длина): {причина}")
        return {"ok": False, "причина": причина, "счёт": счёт}

    ОК, почему = проверить_пол(пол)
    if not ОК:
        в_лог(f"ОТКЛОНЁН (пол): {почему}")
        return {"ok": False, "причина": почему, "счёт": счёт}

    номер = следующий_номер()
    части = разбить(текст)
    части_записей = []
    всего = len(части)
    for i, кусок in enumerate(части, 1):
        шапка = f"ДОКЛАД №{номер}, часть {i} из {всего}\n"
        части_записей.append({
            "кусок": кусок,
            "текст": (шапка + кусок) if всего > 1 else f"ДОКЛАД №{номер}\n{кусок}",
        })

    запись = {
        "номер": номер,
        "создан": datetime.datetime.now().isoformat(timespec="seconds"),
        "автор": автор,
        "пол": пол,
        "счёт": счёт,
        "частей": всего,
        "части": части_записей,
        "состояние": "ждёт",
    }
    ОЧЕРЕДЬ.mkdir(parents=True, exist_ok=True)
    имя = f"доклад-{datetime.datetime.now():%Y%m%d-%H%M%S}-{номер}.json"
    tmp = ОЧЕРЕДЬ / (имя + ".tmp")
    tmp.write_text(json.dumps(запись, ensure_ascii=False, indent=2),
                   encoding="utf-8")
    os.replace(tmp, ОЧЕРЕДЬ / имя)
    в_лог(f"В ОЧЕРЕДИ №{номер}: {счёт['слов']} слов, {счёт['секунд']} с, "
          f"{всего} ч., пол {пол}")
    return {"ok": True, "запись": запись}


def состояние_очереди() -> list[dict[str, Any]]:
    """Что ждёт, по порядку. Это и есть «очередь воспроизведения»."""
    очередь = []
    for файл in _файлы(ОЧЕРЕДЬ):
        try:
            очередь.append(json.loads(файл.read_text(encoding="utf-8")))
        except (ValueError, OSError):
            continue
    очередь.sort(key=lambda з: з.get("номер", 0))
    return очередь


def следующий() -> dict[str, Any] | None:
    """Первый ждущий. Один за раз — это и есть запрет на одновременность."""
    очередь = состояние_очереди()
    return очередь[0] if очередь else None


def отметить_отправленным(номер: int, отправлено_частей: int) -> dict[str, Any]:
    """Убирает доклад из очереди и записывает в журнал."""
    найден = None
    имя_файла = None
    for файл in _файлы(ОЧЕРЕДЬ):
        try:
            запись = json.loads(файл.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            continue
        if запись.get("номер") == номер:
            найден, имя_файла = запись, файл
            break
    if найден is None:
        return {"ok": False, "причина": f"доклад №{номер} не найден в очереди"}

    найден["состояние"] = "отправлено"
    найден["отправлено_частей"] = отправлено_частей
    найден["отправлен"] = datetime.datetime.now().isoformat(timespec="seconds")

    # Проверка целостности: все ли слова на месте.
    собранный = " ".join(ч["кусок"] for ч in найден["части"])
    цел = посчитать(собранный)
    найден["целостность"] = (цел["sha256"] == найден["счёт"]["sha256"]
                             and цел["слов"] == найден["счёт"]["слов"])
    if not найден["целостность"]:
        в_лог(f"!!! ДОКЛАД №{номер} СОБРАН НЕ ЦЕЛИКОМ: "
              f"{цел['слов']} слов вместо {найден['счёт']['слов']}")

    ГОТОВЫ.mkdir(parents=True, exist_ok=True)
    (ГОТОВЫ / имя_файла.name).write_text(
        json.dumps(найден, ensure_ascii=False, indent=2), encoding="utf-8")
    имя_файла.unlink()

    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    with open(ЖУРНАЛ, "a", encoding="utf-8") as f:
        f.write(json.dumps({
            "номер": номер, "отправлен": найден["отправлен"],
            "слов": найден["счёт"]["слов"], "секунд": найден["счёт"]["секунд"],
            "частей": отправлено_частей, "целостность": найден["целостность"],
        }, ensure_ascii=False) + "\n")
    в_лог(f"ОТПРАВЛЕН №{номер}: {отправлено_частей} ч., "
          f"целостность: {найден['целостность']}")
    return {"ok": True, "запись": найден}


# ─── Синтез речи: Sber Salute Speech ─────────────────────────────────────────

SBER_ТОКЕН_URL = "https://salute-login.cdn.sbercloud.ru/token"
SBER_ОЗВУЧКА_URL = "https://salute-speech.cdn.sbercloud.ru/v1/speech:recognize"
SBER_ОЗВУЧИТЬ_URL = "https://salute-speech.cdn.sbercloud.ru/v1/speech:synthesize"


def _настройки() -> dict[str, Any]:
    if not НАСТРОЙКИ.exists():
        return {}
    try:
        данные = json.loads(НАСТРОЙКИ.read_text(encoding="utf-8"))
        return данные if isinstance(данные, dict) else {}
    except (ValueError, OSError):
        return {}


def озвучка_готова() -> tuple[bool, str]:
    """Есть ли ключи Сбера. Честная проверка, а не «должно работать»."""
    настройки = _настройки()
    need = ("sber_client_id", "sber_client_secret")
    if not all(настройки.get(к) for к in need):
        return False, ("ключи Сбера не заданы: нужен sber_client_id и "
                       "sber_client_secret в /opt/bots/sdc/sdc.json")
    return True, ""


def токен_сбера() -> str:
    """Получает access token по client_id и secret."""
    настройки = _настройки()
    тело = urllib.parse.urlencode({
        "client_id": настройки["sber_client_id"],
        "client_secret": настройки["sber_client_secret"],
        "scope": "SALUTE_SPEECH",
    }).encode("utf-8")
    запрос = urllib.request.Request(
        SBER_ТОКЕН_URL, data=тело,
        headers={"Content-Type": "application/x-www-form-urlencoded",
                 "Accept": "application/json", "Authorization": "Basic"},
        method="POST")
    try:
        with urllib.request.urlopen(запрос, timeout=30) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")[:150]
        raise RuntimeError(f"Сбер отверг ключи: HTTP {e.code}. {тело}") from None
    except Exception as e:
        raise RuntimeError(f"Сбер недоступен: {type(e).__name__}") from None
    токен = данные.get("access_token")
    if not токен:
        raise RuntimeError(f"Сбер не вернул токен: {str(данные)[:150]}")
    return str(токен)


def синтез_речи(текст: str, пол: str) -> bytes:
    """Голосовой файл из текста. Пол берётся ТОЛЬКО из аргумента.

    Проверка пола внутри: выбрать не тот голос и отдать его дальше —
    именно тот проступок, за который в проекте положено наказание.
    """
    ОК, почему = проверить_пол(пол)
    if not ОК:
        raise RuntimeError(f"озвучка запрещена: {почему}")
    if not текст.strip():
        raise RuntimeError("озвучка запрещена: пустой текст")

    # Заголовок выбирает пол. Пол списка голосов передаётся отдельно,
    # чтобы движок не подобрал «похожий» голос сам.
    model = "salute_ru_female" if пол == "женский" else "salute_ru_male"
    токен = токен_сбера()
    тело = json.dumps({
        "text": текст,
        "audio": {"format": {"container": "WAV", "sampleRate": 16000}},
    }, ensure_ascii=False).encode("utf-8")
    заголовки = {
        "Content-Type": "application/json",
        "Accept": "audio/wav",
        "Authorization": f"Bearer {токен}",
        "X-Data-Log-Enabled": "false",
        "X-Request-ID": str(uuid.uuid4()),
        "X-Session-ID": str(uuid.uuid4()),
    }
    if model:
        заголовки["X-Speech-Role"] = model
    запрос = urllib.request.Request(
        SBER_ОЗВУЧИТЬ_URL, data=тело, headers=заголовки, method="POST")
    try:
        with urllib.request.urlopen(запрос, timeout=180) as ответ:
            return ответ.read()
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")[:200]
        raise RuntimeError(f"Сбер не озвучил: HTTP {e.code}. {тело}") from None
    except Exception as e:
        raise RuntimeError(f"Сбер недоступен: {type(e).__name__}") from None


# ─── Отправка в Telegram ────────────────────────────────────────────────────

def токен_бота() -> str:
    if not ТОКЕН_ФАЙЛ.exists():
        raise RuntimeError(f"нет токена бота: {ТОКЕН_ФАЙЛ}")
    return ТОКЕН_ФАЙЛ.read_text(encoding="utf-8").strip()


def подписчик() -> int:
    try:
        данные = json.loads(Path("/var/lib/sdc/подписчик.json")
                            .read_text(encoding="utf-8"))
        return int(данные.get("chat_id") or 0)
    except (ValueError, OSError, TypeError):
        return 0


def сказать(чат: int, текст: str) -> bool:
    url = f"https://api.telegram.org/bot{токен_бота()}/sendMessage"
    тело = json.dumps({"chat_id": чат, "text": текст[:4090]}).encode("utf-8")
    запрос = urllib.request.Request(
        url, data=тело,
        headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(запрос, timeout=45) as ответ:
            return bool(json.loads(ответ.read().decode("utf-8")).get("ok"))
    except Exception as e:
        в_лог(f"НЕ ОТПРАВИЛОСЬ: {type(e).__name__}")
        return False


def отправить_очередь(озвучить: bool = False) -> dict[str, Any]:
    """Отправляет первый ждущий доклад. Строго один.

    Это и есть запрет на одновременность: функция берёт только голову
    очереди и отправляет её целиком, следующий ждёт.
    """
    запись = следующий()
    if запись is None:
        return {"ok": False, "причина": "очередь пуста"}

    чат = подписчик()
    if not чат:
        return {"ok": False, "причина":
                "подписчика нет — он ещё не написал боту"}

    отправлено = 0
    for часть in запись["части"]:
        кусок = часть["текст"]
        if озвучить:
            готово, почему = озвучка_готова()
            if not готово:
                # Голос недоступен — отправляем текстом и говорим честно,
                # молча отправить текст вместо голоса нельзя.
                кусок = кусок + f"\n\n(озвучка недоступна: {почему})"
            else:
                try:
                    звук = синтез_речи(часть["кусок"], запись["пол"])
                    сказать(чат, кусок)
                    отправить_голос(чат, звук)
                    отправлено += 1
                    continue
                except RuntimeError as e:
                    кусок = кусок + f"\n\n(озвучка не удалась: {e})"
        if сказать(чат, кусок):
            отправлено += 1
        else:
            в_лог(f"ДОКЛАД №{запись['номер']}: отправка прервалась "
                  f"на части {отправлено + 1}")

    итог = отметить_отправленным(запись["номер"], отправлено)
    return {"ok": True, "номер": запись["номер"], "отправлено": отправлено,
            "из": запись["частей"], "целостность": итог.get("запись", {})
            .get("целостность")}


def отправить_голос(чат: int, звук: bytes) -> bool:
    """Отправляет голосовое сообщение."""
    граница = uuid.uuid4().hex
    тело = bytearray()
    тело += (f"--{граница}\r\n"
             'Content-Disposition: form-data; name="chat_id"\r\n\r\n'
             f"{чат}\r\n").encode("utf-8")
    тело += (f"--{граница}\r\n"
             'Content-Disposition: form-data; name="voice"; '
             'filename="doklad.ogg"\r\n'
             "Content-Type: audio/ogg\r\n\r\n").encode("utf-8")
    тело += звук + b"\r\n"
    тело += f"--{граница}--\r\n".encode("utf-8")
    запрос = urllib.request.Request(
        f"https://api.telegram.org/bot{токен_бота()}/sendVoice",
        data=bytes(тело),
        headers={"Content-Type": f"multipart/form-data; boundary={граница}"},
        method="POST")
    try:
        with urllib.request.urlopen(запрос, timeout=90) as ответ:
            return bool(json.loads(ответ.read().decode("utf-8")).get("ok"))
    except Exception as e:
        в_лог(f"ГОЛОС НЕ ОТПРАВИЛСЯ: {type(e).__name__}")
        return False


