def показать() -> str:
    очередь = состояние_очереди()
    строки = ["=== ОЧЕРЕДЬ ДОКЛАДОВ ==="]
    if not очередь:
        строки.append("  очередь пуста")
    else:
        for поз in очередь:
            строки.append(
                f"  №{поз['номер']}  ждёт  {поз['счёт']['слов']} слов  "
                f"≈{поз['счёт']['секунд']} с  {поз['частей']} ч.  "
                f"пол {поз['пол']}  от {поз['автор']}")
        строки.append(f"  всего в очереди: {len(очередь)}")
        строки.append("  отправляется первый по порядку, по одному")
    готово, почему = озвучка_готова()
    строки.append(f"  озвучка: {'готова' if готово else 'недоступна — ' + почему}")
    отправлено = _файлы(ГОТОВЫ)
    строки.append(f"  отправлено всего: {len(отправлено)}")
    return "\n".join(строки)


def главная() -> int:
    ap = argparse.ArgumentParser(description="доклады через SDC")
    ap.add_argument("текст", nargs="?", help="текст доклада")
    ap.add_argument("-ф", "--файл", help="взять текст из файла ('-' — ввод)")
    ap.add_argument("--пол", default="мужской",
                    help="пол голоса: мужской или женский")
    ap.add_argument("--автор", default="лево")
    ap.add_argument("--отправить", action="store_true",
                    help="отправить первый ждущий доклад")
    ap.add_argument("--озвучить", action="store_true",
                    help="озвучить, а не просто отправить текстом")
    ap.add_argument("--очередь", action="store_true", help="показать очередь")
    ap.add_argument("--проверка", action="store_true")
    args = ap.parse_args()

    if args.проверка:
        return 0 if самопроверка() else 2

    if args.очередь or (not args.текст and not args.файл
                        and not args.отправить):
        print(показать())
        return 0

    if args.отправить:
        результат = отправить_очередь(озвучить=args.озвучить)
        if not результат.get("ok"):
            print(f"не отправлено: {результат.get('причина')}",
                  file=sys.stderr)
            return 1
        print(f"отправлен доклад №{результат['номер']}: "
              f"{результат['отправлено']} из {результат['из']} ч., "
              f"целостность: {результат['целостность']}")
        return 0

    текст = args.текст
    if args.файл:
        if args.файл == "-":
            текст = sys.stdin.read()
        else:
            try:
                текст = Path(args.файл).read_text(encoding="utf-8")
            except OSError as e:
                print(f"не прочитал файл: {e}", file=sys.stderr)
                return 1

    if not текст:
        print("пусто — доклад нечего отправлять", file=sys.stderr)
        return 1

    результат = положить_в_очередь(текст, args.пол, args.автор)
    if not результат["ok"]:
        print(f"отклонено: {результат['причина']}", file=sys.stderr)
        return 1
    з = результат["запись"]
    print(f"в очередь №{з['номер']}: {з['счёт']['слов']} слов, "
          f"≈{з['счёт']['секунд']} с озвучки, {з['частей']} ч., "
          f"пол {з['пол']}")
    print("отправить: доклад --отправить")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(главная())
