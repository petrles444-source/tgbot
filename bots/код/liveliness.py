# ─── выбор ответа ──────────────────────────────────────────────────────────

def стоит_ли_скрипт(живость: int, повтор: int = 0) -> bool:
    """Брать заготовку или звать модель.

    `повтор` — номер попытки в этой же реплике. С каждой попыткой шанс
    на заготовку падает вдвое: если модель дважды выдала повтор, лучше
    ответить заготовкой, чем мучить человека третьим одинаковым текстом.
    """
    шанс = доля_скрипта(живость) // (2 ** max(0, повтор))
    return random.randint(1, 100) <= шанс


def ответ(имя_бота: str, живость: int, история: list[str],
          спросить_модель) -> tuple[str, str]:
    """Главная точка входа: что бот ответит и откуда.

    Возвращает (текст, источник), где источник — «скрипт» или «модель».
    Порядок именно такой, чтобы правило повторов работало всегда:

        1. не повторяемся — проверяем модель, пока не выйдет новый ответ
        2. если повторы всё же пошли — заготовка
        3. заготовки кончились — модель, даже если живость высокая

    Третий пункт важен: заготовок восемь на бот, а разговор может быть
    длинным. Молчать там, где есть вопрос, — хуже, чем ответить хуже.
    """
    # 1. заготовка, если велела живость
    if стоит_ли_скрипт(живость):
        готово = взять_заготовку(имя_бота, история)
        if готово:
            записать_ответ(история, готово)
            return готово, "скрипт"

    # 2. модель, но с проверкой на повтор
    for попытка in range(ПОПЫТОК_НА_ПОВТОР + 1):
        текст = спросить_модель(попытка)
        if not текст:
            continue
        if not повторяется(текст, история):
            записать_ответ(история, текст)
            return текст, "модель"

    # 3. повторы не прекратились — заготовка любой ценой
    готово = взять_заготовку(имя_бота, история) or взять_заготовку(имя_бота, ())
    if готово:
        записать_ответ(история, готово)
        return готово, "скрипт"
    return "", "ничего"


# ─── самопроверка ──────────────────────────────────────────────────────────

def самопроверка() -> bool:
    """Проверки без сети и без Telegram. True — всё сошлось."""
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
