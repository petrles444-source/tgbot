#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Живость: сколько говорит бот сам, сколькоdelegарует модели.

ЗАЧЕМ ЭТОТ ФАЙЛ

    Три бота должны быть болтунами, а не справочниками. Болтун
    отвечает быстро, часто и без пауз — и для этого не нужна модель.
    Модель нужна там, где человек спросил что-то настоящее.

    Отсюда одна настройка от 0 до 100, которую меняет сам человек:

        0   — почти всё говорит модель. Медленнее, зато отвечает по делу.
        100 — почти всё бот говорит сам, заготовками. Мгновенно и бесплатно.

    «Ада, активнее»   → +10   (больше заготовок, бот болтает)
    «Ада, не спамь»   → −10   (меньше заготовок, больше настоящих ответов)

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СЧИТАТЬ ПРОЦЕНТ

    Первая версия считала шанс скрипта от интенсивности напрямую, и при
    100 она давала 100 — то есть модель не звали вообще. Человек всё
    равно звал бота по имени и по делу, а получал отмазку. Поэтому
    шанс ограничен потолком: даже на 100 модель зовётся, просто редко.

ПОЧЕМУ СКРИПТЫ, А НЕ ПРОСТО ПУСТЫЕ ОТВЕТЫ

    Бот, который молчит, кажется сломанным. Бот, который шутит, кажется
    живым. Заготовки читаются как общение, даже если человек говорит
    о серьёзном — и именно это отличает развлекательного бота от
    серьёзного помощника на сайтах.

ЗАЧЕМ НИЖНИЙ ПРОМТ («БУТЕРБРОД»)

    Модель читает всё, но последнее перед ответом помнит лучше всего.
    Поэтому характер задаётся дважды: сверху (кто она) и снизу
    (кем оставаться до конца ответа). Нижний работает сильнее верхнего
    именно потому, что он последний.

СКолько слов сравнивать, чтобы ловить повторы

    Сначала брали семь первых слов. На практике это оказалось почти
    бесполезно: к шестому слову тексты уже расходятся («с этой» против
    «с другой»), и совпадение терялось. Ловит повтор именно короткая
    зачи��ка в начале — «Ну давайте разберёмся…» — поэтому берём пять
    слов и требуем, чтобы они совпали целиком.
"""

from __future__ import annotations

import random
import re
import sys
from typing import Any, Iterable

# ─── границы ────────────────────────────────────────────────────────────────

МИНИМУМ = 0
МАКСИМУМ = 100
ШАГ = 10

# Потолок доли заготовок. Ниже этого модель зовётся всегда: человек
# позвал бота по имени — значит, у него есть вопрос.
ПОТОЛОК_СКРИПТА = 70

# Сколько последних ответов помним, чтобы не повторяться.
ГЛУБИНА_ИСТОРИИ = 6

# Зачином считается не фиксированное число слов, а общий префикс по
# словам: сколько слов совпало до первого различия. Считать ровно N
# слов не вышло — на семи тексты расходятся слишком рано, а на пяти
# зачин «ну давайте разберёмся с этой» упирался в «этой»/«другой»
# и переставал ловить настоящий повтор.
#
# Четыре слова, а не три: на трёх ловилось слишком много лишнего.
# Ответы «настоящий ответ модели 1» и «настоящий ответ модели 2» —
# разные, но первые три слова совпадали, и бот считал их повтором,
# звал модель по второму и третьему разу, а потом отдавал заготовку.
# Человек получал не свой ответ, а болтовню, и заплатил за лишний вызов.
МИН_СЛОВ_В_ЗАЧИНЕ = 4

# Короче этой длины зачинка не считается: «Ну ладно» — это слова, а не
# зачин, и такой повтор человек не заметит.
МИН_ДЛИНА_ЗАЧИНКА = 20

# Сколько раз пробуем другой ответ, если пришёл повтор.
ПОПЫТОК_НА_ПОВТОР = 2

# ─── команды ───────────────────────────────────────────────────────────────

ВВЕРХ = (
    "активнее", "активнее пожалуйста", "говори больше", "болтай больше",
    "больше болтовни", "веселее", "веселее пожалуйста", "шути",
    "рассказывай", "не скупись",
)

ВНИЗ = (
    "не спамь", "поменьше болтовни", "не болтай", "меньше заготовок",
    "серьёзнее", "серьезнее", "по делу", "поменьше шуток",
)

_ПРОБЕЛЫ = re.compile(r"\s+")


def нормализовать(текст: str) -> str:
    """Приводит ответ к виду, по которому сравнивают повторы.

    Регистр и знаки препинания не должны считаться различием: «Привет!»
    и «привет» для человека — один и тот же ответ.
    """
    понижен = str(текст or "").lower().replace("ё", "е")
    без_знаков = re.sub(r"[^\w\s]", " ", понижен)
    return _ПРОБЕЛЫ.sub(" ", без_знаков).strip()


# Живость нового чата. 50 — наполовину: бот болтает, но на настоящие
# вопросы отвечает моделью. Тесты выставляют 0 (см. conftest), потому
# что иначе проверки «модель позвалась» падали бы случайно.
ЖИВОСТЬ_ПО_УМОЛЧАНИЮ = 50

# ─── сама настройка ─────────────────────────────────────────────────────────

def получить(состояние: dict[str, Any] | None) -> int:
    """Текущая живость из состояния чата. Всегда число в границах."""
    значение = (состояние or {}).get("живость", ЖИВОСТЬ_ПО_УМОЛЧАНИЮ)
    try:
        значение = int(значение)
    except (TypeError, ValueError):
        значение = ЖИВОСТЬ_ПО_УМОЛЧАНИЮ
    return max(МИНИМУМ, min(МАКСИМУМ, значение))


def поставить(состояние: dict[str, Any] | None, значение: int) -> int:
    """Записывает живость в границы. Возвращает итоговое значение."""
    итог = max(МИНИМУМ, min(МАКСИМУМ, int(значение)))
    if состояние is not None:
        состояние["живость"] = итог
    return итог


def сдвинуть(состояние: dict[str, Any] | None, дельта: int) -> tuple[int, bool]:
    """Сдвигает живость. Возвращает (новое значение, обрезалось ли)."""
    было = получить(состояние)
    стало = было + int(дельта)
    обрезалось = стало < МИНИМУМ or стало > МАКСИМУМ
    return поставить(состояние, стало), обрезалось


def разобрать_команду(текст: str, имя: str) -> tuple[str, int] | None:
    """Ищет в реплике команду смены живости.

    Возвращает («вверх»|«вниз», дельта) либо None, если команды нет.
    Имя бота необязательно: «активнее» без обращения тоже работает.
    """
    фраза = нормализовать(текст)
    if not фраза:
        return None
    имя_н = нормализовать(имя)
    # Отбрасываем само обращение, чтобы «а давай активнее» не ловило
    # первую букву имени как команду.
    if имя_н and фраза.startswith(имя_н):
        фраза = фраза[len(имя_н):].strip()

    for слово in ВВЕРХ:
        if слово in фраза:
            return "вверх", ШАГ
    for слово in ВНИЗ:
        if слово in фраза:
            return "вниз", -ШАГ
    return None


def доля_скрипта(живость: int) -> int:
    """Шанс ответить заготовкой, в процентах.

    Линейно до 70, дальше потолок. На живости 0 шанс нулевой: модель
    зовётся всегда.
    """
    ж = max(МИНИМУМ, min(МАКСИМУМ, int(живость)))
    return int(ж * ПОТОЛОК_СКРИПТА / МАКСИМУМ)


