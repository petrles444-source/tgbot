def _math_answer(text: str) -> str | None:
    """Посчитать выражение. Считает кодом, а не моделью.

    Точность здесь важнее скорости: модель посчитает «17*23» с
    вероятностью опечатки, а `eval` в ограниченном окружении —
    нет. Поэтому арифметика обрабатывается до обращения к модели.
    """
    allowed = set("0123456789+-*/().  ")
    expr = text.strip().strip("посчитайПосчитайЧто сколько =:? ")
    expr = re.sub(r"\s", "", expr)
    if not expr or len(expr) > 60:
        return None
    if not set(expr) <= allowed:
        return None
    if not any(ch.isdigit() for ch in expr):
        return None
    #: `eval` с пустым пространством имён: внутри доступны только
    #: арифметические операции, никаких имён и вызовов. Плюс проверка
    #: символов выше — вместе это отсекает всё, кроме калькулятора.
    try:
        value = eval(expr, {"__builtins__": {}}, {})  # noqa: S307
    except Exception:
        return None
    if isinstance(value, (int, float)):
        nice = int(value) if float(value).is_integer() else round(value, 6)
        return f"{expr} = {nice}"
    return None


def _time_answer(_: str) -> str:
    """Время и дата. Часы точнее некуда."""
    now = time.localtime()
    months = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
              "августа", "сентября", "октября", "ноября", "декабря")
    return (f"Сейчас {now.tm_hour:02d}:{now.tm_min:02d}, "
            f"{now.tm_mday} {months[now.tm_mon - 1]} {now.tm_year}.")


def _length_answer(text: str) -> str | None:
    """Сколько символов и слов в присланном тексте."""
    body = text.strip()
    for prefix in ("сколько символов", "сколько знаков", "длина",
                   "сколько слов", "посчитай слова"):
        body = re.sub(rf"^{prefix}\s*", "", body, flags=re.IGNORECASE)
    body = body.strip(" ?!.：")
    if not body:
        return None
    return (f"Символов: {len(body)}. Слов: "
            f"{len([w for w in body.split() if w])}.")


#: Первичная логика: ответы без модели.
