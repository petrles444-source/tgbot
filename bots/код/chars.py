#: Длина, за которой сообщение считается разговором, а не приветствием.
#: Подобрана на глаз по живому общению: «привет, как дела» — это всё
#: ещё приветствие, а «привет, ада, слушай, у меня тут вопрос по
#: архитектуре» — уже разговор, и его надо вести модели.
SHORT_LIMIT = 28


def builtin_answer(char_key: str, text: str) -> str | None:
    """Ответ без модели, если такой случай есть.

    Возвращает `None`, когда ответа нет — тогда зовётся модель.

    Порядок проверки длинный к короткому: иначе «сколько символов»
    попало бы под «сколько».

    Про вторую, запасную проверку — почему она такая узкая. Сначала
    здесь стояло «если слово есть где-нибудь в тексте», и это
    отнимало у модели всё подряд: на «Ада, привет, я хочу спросить
    про код» срабатывало приветствие, и вопрос про код до модели
    не доходил вовсе. Первичная логика должна закрывать короткие
    случаи и не мешать разговору.
    """
    low = text.strip().lower().rstrip("!.?")
    is_short = len(low) <= SHORT_LIMIT

    # Сначала то, что осмысленно в любом месте фразы: вычисления,
    # время, длина текста.
    for probe, handler, anywhere in BUILTIN.get(char_key, []):
        if anywhere and probe in low:
            return handler(text)

    # Приветствия и «кто ты» — только когда фраза короткая.
    for probe, handler, anywhere in BUILTIN.get(char_key, []):
        if anywhere or not is_short:
            continue
        if probe in low:
            return handler(text)
    return None


# ------------------------------------------- настройка характера в чате

HELP_TMPL = (
    "Мой характер настроен так:\n"
    "{traits}\n"
    "Меняется прямо здесь, в чате:\n"
    "• /характер {example} — переключить\n"
    "• /характер — показать это сообщение снова\n"
    "• /характер сброс — вернуть исходный\n"
    "\n"
    "Настройки твои личные: в группе я буду другой с другим человеком.\n"
    "Имя у меня всегда прежнее — я {name}."
)


def char_command_text(char_key: str, chat_id: int,
                      store: dict[str, Any] | None = None) -> str:
    """Справка по настройке характера: что сейчас и как менять."""
    char = char_for(char_key)
    traits = traits_for(char_key, chat_id, store)
    help_map = char["trait_help"]
    lines = []
    for name, value in traits.items():
        mark = "включено" if value else "выключено"
        lines.append(f"• {name} ({mark}) — {help_map.get(name, '')}")
    example = next(iter(traits), "веселее")
    return HELP_TMPL.format(traits="\n".join(lines), example=example,
                            name=char["name"])


def char_command(char_key: str, chat_id: int,
                 argument: str) -> tuple[str, bool]:
    """Обработать `/характер ...`. Возвращает (ответ, это настройка).

    Флаг нужен, чтобы вызывающий знал: настройка это или обычная
    команда, и стоит ли показывать справку.
    """
    store = load_store()
    traits = traits_for(char_key, chat_id, store)
    word = SET_SPLIT.split(argument.strip())[0].lower() if argument else ""
    char = char_for(char_key)

    if not word:
        return char_command_text(char_key, chat_id, store), False

    if word in ("сброс", "сбросить", "reset"):
        remember(char_key, chat_id, dict(char["traits"]))
        return ("Вернула исходный характер.\n\n"
                + char_command_text(char_key, chat_id), True)

    #: Признак ищется по общему началу слова, а не по точному имени.
    #: Человек пишет «веселее», а в коде «веселая» — и эти слова
    #: расходятся уже на шестой букве: «веселее» против «веселая».
    #: Сравнение по началу строки такую пару не находило вовсе, и
    #: команда отвечала «нет такого признака» на существующий.
    #:
    #: Поэтому сравнивается длина общего начала: пять совпавших букв
    #: подряд («весел») означают, что человек назвал именно этот
    #: признак, пусть и другим окончанием.
    for name in traits:
        if not _trait_matches(word, name):
            continue
        traits[name] = not traits[name]
        remember(char_key, chat_id, traits)
        mark = "включено" if traits[name] else "выключено"
        return f"{name} теперь {mark}.\n\n" + char_command_text(
            char_key, chat_id), True

    known = ", ".join(traits) or "—"
    return (f"Нет такого признака. Есть: {known}.\n\n"
            + char_command_text(char_key, chat_id, store)), True


def consume_one_shot(char_key: str, chat_id: int) -> None:
    """Погасить одноразовый признак после того, как он отработал.

    Признак «максимум» означает «дай один раз максимально полный
    ответ, потом вернись к обычному». Если не гасить, следующий вопрос
    снова получит простыню, а человек этого не просил: он просил один
    раз, а дальше работает `/сброс` или просто следующая реплика.

    Гасится только у Анатолия: у Ады и Кети одноразовых признаков нет,
    и сбрасывать им нечего.
    """
    if char_key != "anatoly":
        return
    store = load_store()
    traits = traits_for(char_key, chat_id, store)
    if not traits.get("максимум"):
        return
    traits["максимум"] = False
    remember(char_key, chat_id, traits)


def _trait_matches(word: str, name: str) -> bool:
    """Назвал ли человек этот признак, пусть и другим окончанием.

    Один признак может состоять из нескольких слов («простыми
    словами»), поэтому сравнивается только первое: на «простыми
    словами» человек пишет обычно одно слово.
    """
    first = name.split("_")[0]
    if not word:
        return False

    #: Общая длина начала. Пять букв подряд — уже однозначно:
    #: столько не совпадёт случайно с другим признаком.
    same = 0
    for a, b in zip(word, first):
        if a != b:
            break
        same += 1

    if same >= min(5, len(first)):
        return True
    #: Короткие признаки вроде «коротко» не наберут пяти букв по
    #: морфологии — принимаем, если человек назвал слово целиком.
    return word == first or first.startswith(word) and len(word) >= 4


