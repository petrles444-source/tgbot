r"""Характеры ботов: кто есть кто и как настраивается прямо в чате.

Зачем этот файл
---------------
Раньше характер задавался одной строкой `face['role']` плюс общий
`STYLE`, который был одинаков для всех ботов. Из-за этого Ада,
Анатолий и Кети звучали одинаково — просто с разными именами.

Здесь на каждый характер сразу четыре вещи:

* `system` — что бот о себе думает и как говорит. Это видит модель.
* `rules` — что бот делает сам, без модели. Первичная логика.
* `trailing` — что дописать в конце ответа (словарь, сноска).
* `traits` — переключатели характера, которые человек меняет командой.

Первичная логика — зачем она, если есть модель
----------------------------------------------
Модель отвечает хорошо, но медленно, за деньги и не всегда. Поэтому у
каждого характера есть собственные заготовки: время, математика,
счётчик символов, комплимент. Эти случаи бот закрывает сам, мгновенно
и бесплатно, а к модели идёт только то, что действительно требует
размышления. Если ключ модели недоступен или сеть моргнула, бот
остаётся полезным, а не превращается в извиняющуюся заглушку.

Как настраивается характер
---------------------------
Человек пишет в чат:

    /характер              — показать текущий и список переключателей
    /характер веселее      — переключить признак
    /характер сброс        — вернуть исходный

Признаки хранятся по `chat_id`, поэтому у каждого собеседника свой
характер: в группе Ада может быть весёлой с одним и сдержанной с
другим. Состояние живёт в памяти процесса и переживает перезапуск,
потому что сохраняется на диск рядом с ботом.

Почему характер хранится на диске, а не в config.json
-----------------------------------------------------
`config.json` — общий для всех ботов: там модель. Если писать
настройки характера туда же, пришлось бы держать отдельный конфиг на
каждого бота и на каждого собеседника. Файл `chars.json` создан один
и переживает перезапуск процесса.
"""

