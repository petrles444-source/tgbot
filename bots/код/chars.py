def char_for(key: str) -> dict[str, Any]:
    """Характер по ключу. Неизвестный ключ — Ада.

    Откат сюда, а не к исключению: сервер должен продолжать работать,
    если в `bots.json` опечатка. Бот без настроек лучше, чем бот,
    который не запустился.
    """
    return CHARS.get(key) or CHARS["ada"]


def is_bot(char_key: str, *words: str) -> bool:
    """Относится ли просьба к этому боту.

    Проверяется по корню: «характер», «настрой», «сделай веселее» —
    человек не обязан помнить, чей это бот и как он называется.
    """
    return any(word in char_key.lower() for word in words)


# ------------------------------------------------------------- хранение

def load_store() -> dict[str, Any]:
    """Настройки характеров, что накопились на диске."""
    if not CHARS_PATH.is_file():
        return {}
    try:
        data = json.loads(CHARS_PATH.read_text(encoding="utf-8"))
    except ValueError:
        # Битый файл — не повод не запускаться. Старые настройки
        # потеряются, но бот будет работать.
        return {}
    return data if isinstance(data, dict) else {}


def save_store(store: dict[str, Any]) -> None:
    """Записать настройки, убрав старые."""
    now = time.time()
    fresh = {cid: value for cid, value in store.items()
             if now - float(value.get("at") or 0) < FORGET_AFTER_S}
    try:
        CHARS_PATH.write_text(
            json.dumps(fresh, ensure_ascii=False, indent=1), encoding="utf-8")
    except OSError:
        # Настройки характера не настолько важны, чтобы ронять из-за
        # них бота. Терь они просто не переживут перезапуск.
        pass


def traits_for(char_key: str, chat_id: int,
               store: dict[str, Any] | None = None) -> dict[str, bool]:
    """Признаки характера для этого собеседника.

    Сначала исходные, потом наложенные настройки. Важно, что исходные
    каждый раз берутся свежими: если добавить новый признак в коде,
    он сразу заработает, а не спрячется под старым сохранённым.
    """
    base = dict(char_for(char_key)["traits"])
    saved = (store or load_store()).get(str(chat_id)) or {}
    if str(saved.get("char")) != char_key:
        return base
    for name, value in (saved.get("traits") or {}).items():
        if name in base:
            base[name] = bool(value)
    return base


def remember(char_key: str, chat_id: int,
             traits: dict[str, bool]) -> None:
    """Сохранить признаки для этого собеседника."""
    store = load_store()
    store[str(chat_id)] = {
        "char": char_key,
        "traits": {k: bool(v) for k, v in traits.items()},
        "at": time.time(),
    }
    save_store(store)


