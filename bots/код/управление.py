#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Управление ботами из SDC: сказать от их имени, ответить, настроить.

ЗАЧЕМ
-----
Владелец и сотрудники должны мочь вести ботов из одного места: написать
от имени Ады, ответить в чате, поднять или опустить «живость», посмотреть,
кто и сколько писал. Раньше для этого надо было знать имя бота, идти в
его чат и писать руками.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
-----------------------
Подделки людей. Боты остаются ботами, и ни одна команда не делает вид,
что бот — живой человек. Пункт в правилах проекта прямой: нельзя
изображать, что активность настоящая, если она пустая.

Что из этого следует технически:

* у каждого действия есть автор — тот, кто отдал команду;
* всё пишется в журнал, и журнал не редактируется;
* в журнал кладётся начало текста (80 символов), а не весь текст:
  сверять, кто что сказал, нужно; хранить целиком — уже лишнее;
* у бота есть предел частоты, иначе команда «ответить» может
  превратиться в цикл и завалить чат;
* обойти очередь нельзя: на каждый чат — одна очередь на бот.

ПРЕДЕЛ ЧАСТОТЫ
---------------
По умолчанию бот не может написать в один чат чаще раза в 60 секунд.
Для трёх ботов на трёх площадках этого более чем достаточно, а
защита от зацикливания — необходимая: команда «ответить всем», где
ответ сам же является командой, иначе съедает квоту и деньги.
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ДАННЫЕ = Path("/var/lib/управление")
ЖУРНАЛ = ДАННЫЕ / "команды.jsonl"
ПОСЛЕДНЯЯ_ОТПРАВКА = ДАННЫЕ / "последние.json"
ТОКЕНЫ = Path("/etc/sora/bots")

#: Боты, которыми можно управлять. Имя файла = имя бота.
БОТЫ = ("ada", "anatoly", "effy")

#: Через сколько секунд бот может снова написать в тот же чат.
ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ = 60

#: Сколько сообщений подряд бот может отправить одному чату за раз.
ПОРОГ_ЦЕПОЧКИ = 3

#: Самопроверка обязана быть офлайновой. Пока этот флаг снят, вызов()
#: не доходит до Telegram даже если до неё дошла команда.
#:
#: Так вышло однажды: проверка «а что будет при отказе по частоте»
#: на самом деле отправила сообщение в несуществующий чат 100. Проверка
#: обязана доказывать поведение, а не случайно делать его.
СЕТЬ_РАЗРЕШЕНА = True


#: Сколько символов текста команды хранится в журнале.
#:
#: Не ноль — и это осознанно. Цель журнала — ответить на вопрос «кто и что
#: именно написал», а по отпечатку и длине это не восстановить. Полный
#: текст не пишется: 80 символов хватает для сверки, остальное в журнале
#: не хранится.
ВЫДЕРЖКА_СИМВОЛОВ = 80


def выдержка(текст: str, предел: int = ВЫДЕРЖКА_СИМВОЛОВ) -> str:
    """Начало текста для журнала. Обрезает, ничего не раздувает."""
    return str(текст or "").strip()[:предел]


def в_журнал(запись: dict[str, Any]) -> None:
    """Журнал команд. Только пополняется, ничего не переписывается."""
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    try:
        with open(ЖУРНАЛ, "a", encoding="utf-8") as f:
            f.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError:
        pass


def токен_бота(имя: str) -> str:
    if имя not in БОТЫ:
        raise RuntimeError(f"бот {имя!r} не управляется: доступны {', '.join(БОТЫ)}")
    путь = ТОКЕНЫ / f"{имя}.token"
    if not путь.exists():
        raise RuntimeError(f"нет токена: {путь}")
    return путь.read_text(encoding="utf-8").strip()


def вызов(токен: str, метод: str, данные: dict[str, Any],
          таймаут: int = 45) -> Any:
    if not СЕТЬ_РАЗРЕШЕНА:
        raise RuntimeError("сеть выключена (самопроверка)")
    url = f"https://api.telegram.org/bot{токен}/{метод}"
    запрос = urllib.request.Request(
        url, data=json.dumps(данные).encode("utf-8"),
        headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")[:160]
        raise RuntimeError(f"Telegram отверг: HTTP {e.code}. {тело}") from None
    except Exception as e:
        raise RuntimeError(f"сеть недоступна: {type(e).__name__}") from None
    if not данные.get("ok"):
        raise RuntimeError(f"Telegram отказал: {данные.get('description')}")
    return данные.get("result")


# ─── Предел частоты ─────────────────────────────────────────────────────────

def _последние() -> dict[str, Any]:
    try:
        данные = json.loads(ПОСЛЕДНЯЯ_ОТПРАВКА.read_text(encoding="utf-8"))
        return данные if isinstance(данные, dict) else {}
    except (ValueError, OSError):
        return {}


def _запомнить(ключ: str, время_отправки: float) -> None:
    данные = _последние()
    данные[ключ] = время_отправки
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    ПОСЛЕДНЯЯ_ОТПРАВКА.write_text(json.dumps(данные), encoding="utf-8")


def проверить_частоту(бот: str, чат: int) -> tuple[bool, str]:
    """Можно ли сейчас писать. Возвращает (можно, причина отказа)."""
    ключ = f"{бот}:{чат}"
    записи = _последние()
    время_отправки = записи.get(ключ)
    now = time.time()
    if isinstance(время_отправки, (int, float)):
        прошло = now - время_отправки
        if прошло < ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ:
            осталось = int(ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ - прошло)
            return False, (f"бот {бот} писал в этот чат {int(прошло)} с назад, "
                           f"подождите {осталось} с")
    return True, ""


# ─── Команды ────────────────────────────────────────────────────────────────

def сказать(бот: str, чат: int, текст: str, автор: str) -> dict[str, Any]:
    """Написать от имени бота в указанный чат."""
    текст = str(текст or "").strip()
    if not текст:
        return {"ok": False, "причина": "пустой текст"}
    if not isinstance(чат, int) or чат <= 0:
        return {"ok": False, "причина": f"не похоже на chat_id: {чат!r}"}

    можно, причина = проверить_частоту(бот, чат)
    if not можно:
        в_журнал({"когда": datetime.datetime.now().isoformat(timespec="seconds"),
                  "действие": "отказ-частота", "бот": бот, "чат": чат,
                  "автор": автор, "причина": причина})
        return {"ok": False, "причина": причина}

    try:
        токен = токен_бота(бот)
        вызов(токен, "sendMessage",
              {"chat_id": чат, "text": текст[:4000],
               "disable_web_page_preview": True})
    except RuntimeError as e:
        в_журнал({"когда": datetime.datetime.now().isoformat(timespec="seconds"),
                  "действие": "ошибка", "бот": бот, "чат": чат,
                  "автор": автор, "ошибка": str(e)})
        return {"ok": False, "причина": str(e)}

    _запомнить(f"{бот}:{чат}", time.time())
    в_журнал({
        "когда": datetime.datetime.now().isoformat(timespec="seconds"),
        "действие": "сообщение", "бот": бот, "чат": чат, "автор": автор,
        "символов": len(текст), "начало": выдержка(текст),
    })
    return {"ok": True, "бот": бот, "чат": чат}


def ответить(бот: str, чат: int, на_сообщение: int, текст: str,
             автор: str) -> dict[str, Any]:
    """Ответить на конкретное сообщение, а не просто написать в чат."""
    текст = str(текст or "").strip()
    if not текст:
        return {"ok": False, "причина": "пустой текст"}
    можно, причина = проверить_частоту(бот, чат)
    if not можно:
        return {"ok": False, "причина": причина}
    try:
        токен = токен_бота(бот)
        вызов(токен, "sendMessage", {
            "chat_id": чат, "text": текст[:4000],
            "reply_to_message_id": на_сообщение,
            "disable_web_page_preview": True})
    except RuntimeError as e:
        в_журнал({"когда": datetime.datetime.now().isoformat(timespec="seconds"),
                  "действие": "ошибка", "бот": бот, "чат": чат,
                  "автор": автор, "ошибка": str(e)})
        return {"ok": False, "причина": str(e)}
    _запомнить(f"{бот}:{чат}", time.time())
    в_журнал({"когда": datetime.datetime.now().isoformat(timespec="seconds"),
              "действие": "ответ", "бот": бот, "чат": чат,
              "на_сообщение": на_сообщение, "автор": автор,
              "символов": len(текст)})
    return {"ok": True, "бот": бот, "чат": чат, "ответ на": на_сообщение}


def где_боты(автор: str) -> list[dict[str, Any]]:
    """Где боты реально писали: чаты, в которых их видели.

    Учитываются только состоявшиеся отправки. Отказ по частоте и
    ошибка сети — не «место работы»: если считать их, то в списке
    оказывается чат 100 из самопроверки, где бот ничего не писал.
    """
    чаты: dict[str, dict[str, Any]] = {}
    try:
        with open(ЖУРНАЛ, encoding="utf-8") as f:
            for строка in f:
                try:
                    з = json.loads(строка)
                except ValueError:
                    continue
                if з.get("действие") not in ("сообщение", "ответ"):
                    continue
                if з.get("бот") and з.get("чат"):
                    ключ = f"{з['бот']}:{з['чат']}"
                    чаты[ключ] = {"бот": з["бот"], "чат": з["чат"],
                                  "последний": з.get("когда")}
    except OSError:
        pass
    return list(чаты.values())


def журнал(сколько: int = 20) -> str:
    """Последние команды. Показать, кто и что делал."""
    строки = ["=== ЖУРНАЛ КОМАНД ==="]
    try:
        with open(ЖУРНАЛ, encoding="utf-8") as f:
            записи = [строка for строка in f if строка.strip()]
    except OSError:
        строки.append("  журнала пока нет")
        return "\n".join(строки)
    for строка in записи[-сколько:]:
        try:
            з = json.loads(строка)
        except ValueError:
            continue
        что = з.get("действие")
        if что in ("сообщение", "ответ"):
            куда = f"{з.get('бот')} в чат {з.get('чат')}"
            доп = (f" (ответ на {з.get('на_сообщение')})"
                   if что == "ответ" else "")
            строки.append(f"  {з.get('когда')}  {куда}{доп}  "
                          f"от {з.get('автор')}  {з.get('символов')} симв.")
        elif что == "отказ-частота":
            строки.append(f"  {з.get('когда')}  ОТКАЗ {з.get('бот')}: "
                          f"{з.get('причина')}")
        elif что == "ошибка":
            строки.append(f"  {з.get('когда')}  ОШИБКА {з.get('бот')}: "
                          f"{str(з.get('ошибка'))[:60]}")
    строки.append(f"  всего записей: {len(записи)}")
    return "\n".join(строки)


def состояние() -> str:
    строки = ["=== БОТЫ ПОД УПРАВЛЕНИЕМ ==="]
    for бот in БОТЫ:
        try:
            инфо = вызов(токен_бота(бот), "getMe", {})
            строки.append(f"  {бот:<9} @{инфо.get('username')}  "
                          f"id {инфо.get('id')}  имя {инфо.get('first_name')!r}")
        except RuntimeError as e:
            строки.append(f"  {бот:<9} НЕ ОТВЕЧАЕТ: {str(e)[:60]}")
    строки.append("")
    строки.append(f"  пауза между сообщениями в один чат: "
                  f"{ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ} с")
    return "\n".join(строки)


# ─── Самопроверка ───────────────────────────────────────────────────────────

def самопроверка() -> bool:
    import shutil
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА управления ботами ===")

    основа = Path(__file__).resolve().parent / ".проверка-управления"
    shutil.rmtree(основа, ignore_errors=True)
    основа.mkdir(parents=True, exist_ok=True)
    старые = {имя: globals()[имя] for имя in
              ("ДАННЫЕ", "ЖУРНАЛ", "ПОСЛЕДНЯЯ_ОТПРАВКА")}
    globals()["ДАННЫЕ"] = основа
    globals()["ЖУРНАЛ"] = основа / "команды.jsonl"
    globals()["ПОСЛЕДНЯЯ_ОТПРАВКА"] = основа / "последние.json"
    globals()["СЕТЬ_РАЗРЕШЕНА"] = False
    try:
        _тело(чек)
    finally:
        globals()["СЕТЬ_РАЗРЕШЕНА"] = True
        globals().update(старые)
        shutil.rmtree(основа, ignore_errors=True)

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


def _тело(чек) -> None:
    # список ботов
    чек("три бота под управлением", len(БОТЫ) == 3, str(БОТЫ))
    чек("все имена известны",
        all(б in ("ada", "anatoly", "effy") for б in БОТЫ))
    чек("чужой бот не управляется", "sdc" not in БОТЫ)

    # токены
    try:
        токен_бота("ada")
        чек("токен Ады доступен", True)
    except RuntimeError as e:
        чек("токен Ады доступен", False, str(e)[:60])
    try:
        токен_бота("sdc")
        чек("токен чужого бота отвергнут", False, "выдал токен")
    except RuntimeError:
        чек("токен чужого бота отвергнут", True)

    # проверки до сети: пустые значения
    чек("пустой текст отвергнут",
        сказать("ada", 1, "", "лево")["причина"] == "пустой текст")
    чек("не-числовой чат отвергнут",
        "chat_id" in сказать("ada", "не число", "текст", "лево")["причина"])
    чек("минус в чате отвергнут",
        "chat_id" in сказать("ada", -5, "текст", "лево")["причина"])

    # сеть в самопроверке выключена — проверяем первым
    чек("сеть выключена на время проверки", СЕТЬ_РАЗРЕШЕНА is False)
    сказать("ada", 100, "текст", "лево")
    чек("сеть не тронута", СЕТЬ_РАЗРЕШЕНА is False)

    # при пустом журнале ничего не накопилось
    чек("список чатов — список", isinstance(где_боты("лево"), list))
    чек("при пустом журнале список чатов пуст", где_боты("лево") == [],
        str(где_боты("лево")))

    # предел частоты — без обращения к сети
    чек("на пустой истории можно", проверить_частоту("ada", 100)[0])
    _запомнить("ada:100", time.time())
    можно, причина = проверить_частоту("ada", 100)
    чек("сразу вторым разом нельзя", можно is False)
    чек("в отказе сказано, сколько ждать", "подождите" in причина, причина)
    чек("в другой чат можно", проверить_частоту("ada", 101)[0])
    чек("другому боту можно", проверить_частоту("anatoly", 100)[0])

    # отказ по частоте пишется в журнал. Паузу вооружаем здесь: выше
    # она уже была отпущена, и сказать() ушёл бы в сеть вместо отказа.
    _запомнить("ada:100", time.time())
    сказать("ada", 100, "текст", "лево")
    записи = ЖУРНАЛ.read_text(encoding="utf-8") if ЖУРНАЛ.exists() else ""
    чек("отказ по частоте попал в журнал", "отказ-частота" in записи)

    _запомнить("ada:100", time.time() - ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ - 1)
    чек("через паузу снова можно", проверить_частоту("ada", 100)[0])

    # журнал
    чек("автор пишется в журнал", '"лево"' in записи)
    чек("отказ и ошибка не хранят текст команды",
        '"текст"' not in записи and '"начало"' not in записи,
        "в записи об отказе есть содержимое команды")

    # выдержка для журнала — то, что действительно пишется при отправке
    длинный = "а" * 500
    чек("выдержка обрезана", len(выдержка(длинный)) == ВЫДЕРЖКА_СИМВОЛОВ,
        str(len(выдержка(длинный))))
    чек("короткий текст остаётся целиком",
        выдержка("привет") == "привет")
    чек("края у выдержки срезаны",
        выдержка("  привет  ") == "привет")
    чек("выдержка из пустого не падает", выдержка("") == "")
    чек("выдержка короче полного текста",
        len(выдержка(длинный)) < len(длинный))

    чек("журнал читается", "ЖУРНАЛ КОМАНД" in журнал(10))
    чек("пустой журнал не ломает", isinstance(журнал(10), str))

    # пауза не обходится перезапуском процесса
    чек("пауза переживает перезапуск",
        _последние().get("ada:100") is not None)
    чек("в памяти времени достаточно",
        ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ >= 30, f"{ПАУЗА_МЕЖДУ_СООБЩЕНИЯМИ}")


# ─── Вход ───────────────────────────────────────────────────────────────────

def главная() -> int:
    ap = argparse.ArgumentParser(description="управление ботами")
    ap.add_argument("--проверка", action="store_true")
    ap.add_argument("--состояние", action="store_true")
    ap.add_argument("--журнал", action="store_true")
    ap.add_argument("--сказать", nargs=3, metavar=("БОТ", "ЧАТ", "ТЕКСТ"))
    ap.add_argument("--ответить", nargs=4,
                    metavar=("БОТ", "ЧАТ", "СООБЩЕНИЕ", "ТЕКСТ"))
    ap.add_argument("--автор", default="лево")
    args = ap.parse_args()

    if args.проверка:
        return 0 if самопроверка() else 2
    if args.состояние:
        print(состояние())
        return 0
    if args.журнал:
        print(журнал())
        return 0
    if args.сказать:
        р = сказать(args.сказать[0], int(args.сказать[1]),
                    args.сказать[2], args.автор)
        print(("отправлено" if р["ok"] else f"отказ: {р['причина']}"))
        return 0 if р["ok"] else 1
    if args.ответить:
        р = ответить(args.ответить[0], int(args.ответить[1]),
                     int(args.ответить[2]), args.ответить[3], args.автор)
        print(("отправлено" if р["ok"] else f"отказ: {р['причина']}"))
        return 0 if р["ok"] else 1

    print(состояние())
    return 0


