#!/usr/bin/env python3
r"""Что бот умеет для человека: команды, память о чате и его настройки.

Зачем этот файл
---------------
У Ады и Линды одинаковая часть поведения: команды, отвечающие без
модели, и работа с состоянием чата. Держать это в общем месте нужно,
потому что иначе через месяц команды в двух ботах разъедутся, а
человек увидит, что один бот помнит сказанное, а другой — нет.

Команды
-------
* `/start` — кто я и как со мной говорить.
* `/help` — то же, но со списком всех команд.
* `/status` — время работы, модель, сколько чатов помню.
* `/whoami` — ваш `chat_id`, нужен для настройки пульса.
* `/forget` — забыть этот разговор. Нужно, когда бот перепутал тему
  или человек просто поменял разговор.
* `/name` — какое сейчас имя у бота и откуда оно взято.

Почему `/forget` важнее, чем кажется
------------------------------------
Контекст хранится в памяти процесса и живёт, пока жив бот. Через
несколько часов молчания переписки буфер забивается старым разговором,
и модель начинает отвечать не на то. Сброс — единственный способ это
прекратить, не перезапуская бота.
"""
from __future__ import annotations

from typing import Any


def commands_help(face: dict[str, Any]) -> str:
    """Справка со всеми командами.

    Пишется списком, а не абзацем: человек ищет команду, а не читает
    вдохновляющий текст. Каждая строка — одна команда и что она
    делает, в том порядке, в котором их чаще спрашивают.
    """
    return "\n".join([
        f"{face['name']} — {face['role']}.",
        "",
        "Команды:",
        "• /start — это сообщение",
        "• /help — список команд",
        "• /status — время работы и модель",
        "• /whoami — ваш chat_id",
        "• /forget — забыть этот разговор",
        "• /name — моё имя сейчас",
        "",
        "Как говорить:",
        f"• позовите по имени — {face['name'].lower()} — вместе с вопросом, "
        "и я отвечу сразу",
        "• можно позвать отдельно, а вопрос задать следующим сообщением",
        "• в беседе я вмешиваюсь в каждое десятое сообщение, "
        "чтобы не превращать чат в монолог",
        "• в личном чате отвечаю на всё",
    ])


def start_text(face: dict[str, Any]) -> str:
    """Первое сообщение в личном чате."""
    return "\n".join([
        f"Привет. Я {face['name']}, {face['role']}.",
        "",
        "Спросите что угодно — отвечу по-русски, разберу по существу.",
        "В конце каждого ответа дам пару английских слов, которые сам "
        "использовал, с переводом.",
        "",
        f"Позвать меня можно по имени: «{face['name']}» или «{face['name'].lower()}».",
        "Все команды — /help.",
    ])


def name_text(face: dict[str, Any]) -> str:
    """Какое имя сейчас и почему именно такое."""
    return "\n".join([
        f"Сейчас я — {face['name']}.",
        f"Роль: {face['role']}.",
        f"Говорю {face['voice']}.",
        "",
        "Имена меняются от запуска к запуску: чтобы «Ада» не превратилась "
        "в подпись, а оставалась именем.",
    ])


def forget_text(face: dict[str, Any]) -> str:
    """Подтверждение сброса контекста."""
    return "Забыла этот разговор. Спрашивайте заново — начну с чистого листа."


def status_lines(config: dict[str, Any], uptime_text: str,
                 chat_count: int) -> list[str]:
    """Строки статуса. Список, а не одна строка: его читают по строкам."""
    face = config["face"]
    providers = config["providers"]
    lines = [
        f"{face['name']} на связи — {face['role']}.",
        "",
        f"работаю: {uptime_text}",
        f"чатов помню: {chat_count}",
    ]
    detail = config.get("detail_level")
    if detail:
        lines.append(f"детализация {detail}, строгость "
                     f"{config.get('science_level')}")
    if providers:
        active = providers[config["active"]]
        ready = "ключ есть" if active.get("api_key") else "нет ключа"
        lines.append(f"модель: {active.get('name', '?')} "
                     f"({active.get('model') or '?'}, {ready})")
    else:
        lines.append("Модели не настроены на сервере.")
    return lines