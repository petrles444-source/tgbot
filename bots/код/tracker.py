#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Счётчик аудитории: кто и сколько раз писал ботам.

ЗАЧЕМ
-----
Владелец хочет знать, велика ли аудитория у ботов. Для этого нужно
посчитать, сколько разных людей писало, и сколько сообщений каждый
принёс. Больше ничего не нужно.

ПРО IP — ЧЕСТНО
---------------
Заказ звучал так: «новые айпи пишут». Так не выйдет. **Telegram не
отдаёт боту адрес писателя.** В объекте Message нет поля `ip` — ни
сверху, ни внутри `from`, ни внутри `chat`. Это не ограничение
токена, а сознательное решение Telegram: иначе любой бот был бы
следилкой.

Что доступно вместо адреса:
    `from.id` — уникальный номер человека. Он не меняется никогда:
    ни при смене имени, ни при смене юзернейма. Для подсчёта разных
    людей это даже лучше адреса: человек мог сменить Wi-Fi или телефон,
    а номер остался бы тем же и он не «раздвоился» бы.
    `username` — может измениться или исчезнуть, поэтому он только
    справочный, сверка по нему — вторая линия, а не основная.

Поэтому считаем по `from.id`, а сверяем по юзернейму. Если Telegram
когда-нибудь отдаст адрес, `проверить_схему()` это покажет: он один
раз выведет ключи настоящего сообщения.

ЧТО НЕ ЗАПИСЫВАЕТСЯ
-------------------
    Текст сообщений. Никак. Это чужие слова, и хранить их незачем:
    вопрос «сколько людей» текста не требует.
    Таймстемпы сообщений по секундам — тоже не нужны, хватает даты.

ЧТО ИМЕННО ЗАПИСЫВАЕТСЯ
------------------------
    дата, имя бота, хеш номера человека, юзернейм, имя,
    сколько всего сообщений от него за всё время.

ИМЕНА ВЛАДЕЛЬЦА НЕ ПИШУТСЯ
--------------------------
Владелец исключается дважды: по номеру и по юзернейму. Исключения
задаётся либо файлом, либо командой `/владелец` прямо в чате — это
надёжнее, чем угадывать по первому написавшему.

ГДЕ ЛЕЖИТ
---------
    /var/lib/аудитория/посетители.jsonl  — по строке на человека
    /etc/sora/аудитория-исключения.json  — кого не считать

    Оба вне git. Журнал растёт медленно: примерно 200 байт на
    человека, то есть 1000 человек — это 200 КБ за всё время.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any

# ─── Пути ───────────────────────────────────────────────────────────────────

ДАННЫЕ = Path("/var/lib/аудитория")
ЖУРНАЛ = ДАННЫЕ / "посетители.jsonl"
ИСКЛЮЧЕНИЯ = Path("/etc/sora/аудитория-исключения.json")
ДУМП_СХЕМЫ = ДАННЫЕ / "схема-сообщения.txt"

#: Разбор чата в хеш. Номер человека — тоже идентификатор, хоть и не
#: секрет, но хранить его открытым незачем: для подсчёта хватает
#: неразворотного отпечатка, а по нему уже нельзя написать человеку.
ОТРЕЗОК_ХЕША = 16

#: Когда журнал дорос — сжимаем. 2 МБ на сотни людей это очень много.
ПОРОГ_БАЙТ = 2 * 1024 * 1024

#: Сколько сжатых копий держим. Каждая — вся история на момент сжатия.
КОПИЙ = 5


# ─── Исключения ─────────────────────────────────────────────────────────────

def _прочитать(path: Path, по_умолчанию: dict) -> dict:
    try:
        данные = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(данные, dict):
            return {
                "chat_id": [str(x) for x in данные.get("chat_id") or []],
                "username": [str(x).lower().lstrip("@")
                             for x in данные.get("username") or []],
            }
    except (ValueError, OSError):
        pass
    return dict(по_умолчанию)


def исключения() -> dict[str, set[str]]:
    """Кого не считать: номера и юзернеймы."""
    данные = _прочитать(ИСКЛЮЧЕНИЯ, {"chat_id": [], "username": []})
    return {
        "chat_id": set(данные["chat_id"]),
        "username": set(данные["username"]),
    }


def добавить_исключение(chat_id: int, username: str | None) -> None:
    """Помечает чат как «владелец», чтобы не считать его аудиторией."""
    данные = _прочитать(ИСКЛЮЧЕНИЯ, {"chat_id": [], "username": []})
    список = sorted(set(данные["chat_id"]) | {str(chat_id)})
    if username:
        имя = username.lower().lstrip("@")
        юзеры = sorted(set(данные["username"]) | {имя})
    else:
        юзеры = sorted(set(данные["username"]))
    ИСКЛЮЧЕНИЯ.parent.mkdir(parents=True, exist_ok=True)
    tmp = ИСКЛЮЧЕНИЯ.with_suffix(".tmp")
    tmp.write_text(json.dumps({"chat_id": список, "username": юзеры},
                              ensure_ascii=False, indent=2),
                   encoding="utf-8")
    os.replace(tmp, ИСКЛЮЧЕНИЯ)
    os.chmod(ИСКЛЮЧЕНИЯ, 0o600)


# ─── Хеш ────────────────────────────────────────────────────────────────────

def отпечаток(значение: Any) -> str:
    """Неразворотный отпечаток номера человека."""
    return hashlib.sha256(str(значение).encode("utf-8")).hexdigest()[:ОТРЕЗОК_ХЕША]


# ─── Журнал ─────────────────────────────────────────────────────────────────

def _прочитать_журнал() -> dict[str, dict[str, Any]]:
    """Читает журнал в память. Битый хвост не ломает чтение целиком."""
    люди: dict[str, dict[str, Any]] = {}
    if not ЖУРНАЛ.exists():
        return люди
    with open(ЖУРНАЛ, encoding="utf-8") as f:
        for строка in f:
            строка = строка.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except ValueError:
                continue
            ключ = str(запись.get("человек") or "")
            if not ключ:
                continue
            прежняя = люди.get(ключ)
            запись["сообщений"] = int(запись.get("сообщений") or 0) + int(
                (прежняя or {}).get("сообщений") or 0)
            люди[ключ] = запись
    return люди


def _записать_журнал(люди: dict[str, dict[str, Any]]) -> None:
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    строки = [json.dumps(з, ensure_ascii=False) for з in люди.values()]
    текст = "\n".join(строки) + ("\n" if строки else "")
    tmp = ЖУРНАЛ.with_suffix(".tmp")
    tmp.write_text(текст, encoding="utf-8")
    os.replace(tmp, ЖУРНАЛ)


def заметить(имя_бота: str, сообщение: dict[str, Any]) -> str:
    """Учитывает сообщение. Возвращает что сделано, для журнала бота.

    Возможные ответы: «новый», «ещё раз», «исключён», «пусто».
    """
    автор = сообщение.get("from") or {}
    chat = сообщение.get("chat") or {}
    номер = автор.get("id") or chat.get("id")
    if not isinstance(номер, int):
        return "пусто"

    правила = исключения()
    юзернейм = str(автор.get("username") or "").lower().lstrip("@")
    if str(номер) in правила["chat_id"] or (юзернейм and юзернейм in правила["username"]):
        return "исключён"

    ключ = отпечаток(номер)
    люди = _прочитать_журнал()
    запись = люди.get(ключ)
    новый = запись is None
    now = datetime.datetime.now()

    if новый:
        запись = {
            "дата": now.strftime("%Y-%m-%d"),
            "человек": ключ,
            "боты": [],
            "юзернейм": юзернейм or None,
            "имя": автор.get("first_name") or None,
            "сообщений": 0,
        }
        люди[ключ] = запись

    запись["сообщений"] = int(запись.get("сообщений") or 0) + 1
    if имя_бота and имя_бота not in запись.setdefault("боты", []):
        запись["боты"].append(имя_бота)
    # Юзернейм человек мог сменить — обновляем, чтобы сверка была живой.
    if юзернейм:
        запись["юзернейм"] = юзернейм

    _записать_журнал(люди)
    _проверить_схему(сообщение)
    _сжать_если_пора()
    return "новый" if новый else "ещё раз"


# ─── Однократная проверка: есть ли в сообщении адрес ─────────────────────────

_схему_проверили = False


def _проверить_схему(сообщение: dict[str, Any]) -> None:
    """Один раз выписывает все ключи настоящего сообщения.

    Нужно, чтобы не гадать. Заказ был «новые айпи пишут» — если поле
    всё же существует, этот дамп покажет его, и трекер можно будет
    дополнить. Проверка делается один раз за всё время работы.
    """
    global _схему_проверили
    if _схему_проверили or ДУМП_СХЕМЫ.exists():
        return
    _схему_проверили = True
    ключи: list[str] = []

    def обойти(узел: Any, путь: str = "") -> None:
        if isinstance(узел, dict):
            for к, з in узел.items():
                здесь = f"{путь}.{к}" if путь else str(к)
                ключи.append(здесь)
                if isinstance(з, (dict, list)) and len(ключи) < 120:
                    обойти(з, здесь)
        elif isinstance(узел, list):
            for i, з in enumerate(узел[:3]):
                обойти(з, f"{путь}[{i}]")

    обойти(сообщение)
    есть_ip = [k for k in ключи if "ip" in k.lower() or "addr" in k.lower()]
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    ДУМП_СХЕМЫ.write_text(
        f"проверено: {datetime.datetime.now():%Y-%m-%d %H:%M:%S}\n"
        f"всего полей: {len(ключи)}\n"
        f"полей с ip или addr: {len(есть_ip)}\n"
        f"если список ниже пуст — адреса в сообщении нет, и считать надо\n"
        f"по from.id, что и делает трекер\n\n"
        + "\n".join(sorted(set(ключи))) + "\n",
        encoding="utf-8")


# ─── Сжатие ─────────────────────────────────────────────────────────────────

def _убрать_лишние_копии() -> None:
    """Оставляет последние КОПИЙ архивов, остальные удаляет."""
    копии = sorted(ДАННЫЕ.glob("посетители-*.gz")) if ДАННЫЕ.exists() else []
    for лишний in (копии[:-КОПИЙ] if КОПИЙ else копии):
        try:
            лишний.unlink()
        except OSError:
            pass


def _сжать_если_пора() -> None:
    """Когда журнал дорос — сжимаем. Старые копии убираем ВСЕГДА.

    Раньше функция начиналась с `if not ЖУРНАЛ.exists(): return`, и
    старые архивы поэтому никогда не перебирались: после первого
    сжатия журнала уже нет, дальше вызов выходил сразу, и копии
    копились месяцами. Теперь чистка архивов идёт всегда, а само
    сжатие — только когда есть что сжимать.
    """
    _убрать_лишние_копии()
    if not ЖУРНАЛ.exists():
        return
    if ЖУРНАЛ.stat().st_size < ПОРОГ_БАЙТ:
        return

    import gzip
    import shutil
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    имя = ДАННЫЕ / f"посетители-{datetime.datetime.now():%Y%m%d-%H%M%S}.gz"
    with open(ЖУРНАЛ, "rb") as вход, gzip.open(имя, "wb") as выход:
        shutil.copyfileobj(вход, выход)
    ЖУРНАЛ.unlink()
    _убрать_лишние_копии()


# ─── Статистика ─────────────────────────────────────────────────────────────

def статистика() -> dict[str, Any]:
    """Считает по журналу. Владелец в счёт не входит."""
    люди = _прочитать_журнал()
    по_ботам: dict[str, int] = {}
    всего_сообщений = 0
    for запись in люди.values():
        всего_сообщений += int(запись.get("сообщений") or 0)
        for бот in запись.get("боты") or []:
            по_ботам[бот] = по_ботам.get(бот, 0) + 1
    return {
        "людей": len(люди),
        "сообщений": всего_сообщений,
        "по_ботам": по_ботам,
        "люди": _люди(),
    }


def _люди() -> list[dict[str, Any]]:
    """Список людей по убыванию числа сообщений."""
    все = _прочитать_журнал()
    return sorted(все.values(),
                  key=lambda з: (-int(з.get("сообщений") or 0),
                                 str(з.get("имя") or "")))


def показать(подробно: bool) -> str:
    данные = статистика()
    строки = [
        "=== АУДИТОРИЯ БОТОВ ===",
        f"  разных людей:     {данные['людей']}",
        f"  всего сообщений:  {данные['сообщений']}",
    ]
    if данные["по_ботам"]:
        строки.append("  по ботам:")
        for бот, n in sorted(данные["по_ботам"].items(), key=lambda x: -x[1]):
            строки.append(f"      {бот:<12} {n}")
    правила = исключения()
    строки.append(f"  исключено (владелец): {len(правила['chat_id'])} номеров, "
                  f"{len(правила['username'])} юзернеймов")
    место = 0
    if ЖУРНАЛ.exists():
        место = ЖУРНАЛ.stat().st_size
    копии = list(ДАННЫЕ.glob("посетители-*.gz"))
    сжато = sum(k.stat().st_size for k in копии)
    строки.append(f"  журнал: {место} Б, сжатых копий: {len(копии)} ({сжато} Б)")
    if подробно:
        строки.append("  --- кто писал ---")
        for з in _люди():
            кто = з.get("юзернейм") or з.get("имя") or "без имени"
            строки.append(f"      @{кто:<20} {з.get('сообщений')} сообщ.  "
                          f"боты: {','.join(з.get('боты') or [])}  "
                          f"с {з.get('дата')}")
    return "\n".join(строки)


# ─── Самопроверка ───────────────────────────────────────────────────────────

def самопроверка() -> bool:
    """Всё делается во временной папке: настоящий журнал не трогаем."""
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА трекера аудитории ===")

    import shutil
    # Папку для проверки берём рядом со скриптом, а не через tempfile:
    # системный каталог временных файлов на этой машине бывает
    # недоступен, и проверка падала бы не по своей причине.
    черновик = Path(__file__).resolve().parent / ".проверка-аудитории"
    shutil.rmtree(черновик, ignore_errors=True)
    черновик.mkdir(parents=True, exist_ok=True)
    старые = {имя: globals()[имя] for имя in ("ДАННЫЕ", "ЖУРНАЛ", "ИСКЛЮЧЕНИЯ",
                                             "ДУМП_СХЕМЫ")}
    globals()["ДАННЫЕ"] = черновик
    globals()["ЖУРНАЛ"] = черновик / "посетители.jsonl"
    globals()["ИСКЛЮЧЕНИЯ"] = черновик / "исключения.json"
    globals()["ДУМП_СХЕМЫ"] = черновик / "схема.txt"
    try:
        _тело(чек)
    finally:
        globals().update(старые)
        shutil.rmtree(черновик, ignore_errors=True)

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


def _тело(чек) -> None:
    # хеш
    чек("хеш стабилен", отпечаток(12345) == отпечаток(12345))
    чек("хеш разный у разных людей", отпечаток(1) != отпечаток(2))
    чек("хеш длиной 16", len(отпечаток(999)) == ОТРЕЗОК_ХЕША)
    чек("номер не утекает в открытом виде",
        str(12345) not in отпечаток(12345))

    # исключения
    чек("без исключений пусто", исключения() == {"chat_id": set(),
                                                  "username": set()})
    добавить_исключение(777, "Лев")
    правила = исключения()
    чек("исключение по номеру добавлено", "777" in правила["chat_id"])
    чек("исключение по юзернейму добавлено", "лев" in правила["username"])
    чек("юзернейм без @ и в нижнем регистре",
        "лев" in исключения()["username"])

    def сообщение(номер: int, юзернейм: str | None = "ivan",
                  имя: str = "Иван") -> dict[str, Any]:
        автор: dict[str, Any] = {"id": номер, "is_bot": False,
                                 "first_name": имя}
        if юзернейм:
            автор["username"] = юзернейм
        return {"message_id": номер, "from": автор,
                "chat": {"id": номер, "type": "private"}, "text": "привет"}

    # владелец не считается
    чек("владелец по номеру исключён",
        заметить("ada", сообщение(777, "someone")) == "исключён")
    чек("владелец по юзернейму исключён",
        заметить("ada", сообщение(888, "Лев")) == "исключён")
    чек("владелец по юзернейму БЕЗ @ и в другом регистре исключён",
        заметить("ada", сообщение(889, "@ЛЕВ")) == "исключён")

    # новые и повторные
    чек("новый человек помечен новым",
        заметить("ada", сообщение(1, "ivan")) == "новый")
    чек("повторное сообщение — ещё раз",
        заметить("ada", сообщение(1, "ivan")) == "ещё раз")
    чек("второй человек — новый",
        заметить("anatoly", сообщение(2, "petr")) == "новый")

    # статистика
    данные = статистика()
    чек("в статистике ровно 2 человека", данные["людей"] == 2,
        f"получено {данные['людей']}")
    чек("сообщений посчитано 3", данные["сообщений"] == 3,
        f"получено {данные['сообщений']}")
    чек("по ботам: ada 1, anatoly 1",
        данные["по_ботам"].get("ada") == 1
        and данные["по_ботам"].get("anatoly") == 1,
        f"получено {данные['по_ботам']}")

    # один человек у нескольких ботов
    заметить("effy", сообщение(1, "ivan"))
    чек("один человек у двух ботов считается один раз",
        статистика()["людей"] == 2, f"получено {статистика()['людей']}")
    чек("боты у человека записаны оба",
        set(_люди()[0]["боты"]) >= {"ada", "effy"},
        f"получено {_люди()[0]['боты']}")

    # смена юзернейма не плодит нового человека
    заметить("ada", сообщение(1, "ivan_new"))
    чек("смена юзернейма не делает нового человека",
        статистика()["людей"] == 2, f"получено {статистика()['людей']}")

    # без юзернейма — считается
    чек("человек без юзернейма считается",
        заметить("ada", сообщение(3, None, "БезНика")) == "новый")

    # текст не пишется
    текст_журнала = ЖУРНАЛ.read_text(encoding="utf-8") if ЖУРНАЛ.exists() else ""
    чек("текст сообщений НЕ сохраняется", "привет" not in текст_журнала,
        "журнал содержит чужие слова")
    чек("номер в открытом виде не сохраняется",
        '"12345"' not in текст_журнала)

    # проверка схемы
    чек("дамп схемы создан", ДУМП_СХЕМЫ.exists())
    if ДУМП_СХЕМЫ.exists():
        дамп = ДУМП_СХЕМЫ.read_text(encoding="utf-8")
        чек("в дампе есть from.id", "from.id" in дамп)
        чек("в дампе честно сказано про ip",
            "ip или addr" in дамп)

    # битый журнал не ломает чтение
    ЖУРНАЛ.write_text("это не json\n{\"человек\":\"x\",\"сообщений\":1}\n",
                      encoding="utf-8")
    чек("битая строка не ломает чтение",
        isinstance(статистика()["люди"], list),
        f"получено {type(статистика()['люди']).__name__}")
    чек("люди в статистике это список, а не функция",
        all(isinstance(з, dict) for з in статистика()["люди"]))

    # битый файл исключений
    ИСКЛЮЧЕНИЯ.write_text("не json", encoding="utf-8")
    чек("битый файл исключений не ломает",
        исключения() == {"chat_id": set(), "username": set()})

    # сжатие
    чек("до порога не сжимаем", _сжать_если_пора() is None
        and not list(ДАННЫЕ.glob("*.gz")))
    ЖУРНАЛ.write_text("x" * (ПОРОГ_БАЙТ + 100), encoding="utf-8")
    _сжать_если_пора()
    копии = sorted(ДАННЫЕ.glob("посетители-*.gz"))
    чек("после порога журнал сжат", len(копии) == 1, f"копий {len(копии)}")
    чек("сжатое меньше исходного",
        копии and копии[0].stat().st_size < ПОРОГ_БАЙТ // 2,
        f"{копии[0].stat().st_size if копии else '?'} Б")
    чек("исходный файл убран", not ЖУРНАЛ.exists())

    # много копий — лишние убираются
    for i in range(КОПИЙ + 3):
        (ДАННЫЕ / f"посетители-2020010{i}-000000.gz").write_bytes(b"x")
    _сжать_если_пора()
    чек("лишние копии убраны",
        len(list(ДАННЫЕ.glob("посетители-*.gz"))) <= КОПИЙ + 1,
        f"осталось {len(list(ДАННЫЕ.glob('посетители-*.gz')))}")

    # без номера — не считаем
    чек("сообщение без номера игнорируется",
        заметить("ada", {"from": {}, "chat": {}}) == "пусто")


