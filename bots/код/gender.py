r"""Пол и язык ответа: Ада и Effy говорят как женщины, по-русски.

Зачем отдельный модуль
----------------------
Правило «говори в женском роде» должно стоять в трёх местах: в
подсказке модели, в проверке готового ответа и в тестах. Если каждое
место хранит свою формулировку, они со временем разъедутся, и через
месяц будет непонятно, какая из них главная. Здесь — один источник
правды, остальное его читает.

Почему правила в подсказке недостаточно
---------------------------------------
Одной инструкции в начале подсказки хватает не всегда. Модель —
это статистика, а не переключатель: за тысячу ответов она пару раз
промахнётся, особенно в длинных текстах и в цитатах. Поэтому правило
дублируется: в начале — чтобы задать роль, в самом конце — чтобы
оно было последним, что модель прочитала перед ответом. Конец
подсказки влияет сильнее начала.

Что делает проверка ответа
--------------------------
Ничего умного. Находит слова мужского рода, которыми бот говорит о
себе, и заменяет их на женские. Это не грамматический разбор: за
таблицей стоит не «понять», а «не отправить». Ошибка на «я сделал»
заметна человеку, и она ломает весь купленный эффект живого
собеседника.

Почему только Ада и Effy
------------------------
Анатолий — мужчина по характеру, и требование обратное. Правило одно
и то же, но значение разное, поэтому у каждого бота своя запись.

Про язык
--------
Ответ должен быть на русском. Модель переключается на английский
не из-за просьбы человека, а когда в вопросе много технических
слов. Правило стоит рядом с правилом пола: обе задачи — «в каком
виде меня видят», и решаются вместе.
"""

from __future__ import annotations

import re

#: Кто говорит в каком роде. Ключ — как в `bots.json` и `chars.py`.
GENDER = {
    "ada": "женский",
    "effy": "женский",
    "anatoly": "мужской",
}

#: На каком языке отвечает каждый. Сейчас это одинаково, но списком:
#: захочется другой язык — правится здесь, а не по всему коду.
LANGUAGE = {
    "ada": "русский",
    "effy": "русский",
    "anatoly": "русский",
}


def род(char_key: str) -> str:
    """В каком роде говорит этот бот."""
    return GENDER.get(char_key, "мужской")


def правило_пола(char_key: str) -> str:
    """Строгий блок про род. Ставится в конец подсказки.

    Формулировка намеренно жёсткая и с примерами. Модель лучше
    выполняет конкретное «говори так», чем абстрактное «учитывай
    род», поэтому здесь перечислены настоящие слова, а не общее
    пожелание.
    """
    if род(char_key) == "мужской":
        return (
            "ТЫ МУЖЧИНА. Говори о себе в мужском роде: «я сделал», "
            "«я подумал», «я решил», «я могу». Никогда, ни одного слова "
            "о себе в женском роде."
        )
    return (
        "ТЫ ЖЕНЩИНА. Это главное правило твоего ответа.\n"
        "• Обо всём, что касается тебя, говори ТОЛЬКО в женском роде: "
        "«я сделала», «я подумала», «я решила», «я могу», «я знаю», "
        "«я попробовала», «я написала», «я объясню».\n"
        "• Мужского рода про себя не пиши НИГДЕ: не «я готов», не "
        "«я уверен», не «я дерзнул», не «я сам».\n"
        "• Это касается и длинных ответов, и цитат, и списков, и "
        "подписей к коду. Везде, где есть «я», — женский род.\n"
        "• Настоящий мужчина, которого ты упоминаешь, говорит о себе "
        "в мужском роде — но за него говоришь ты, и «я» остаётся "
        "твоим."
    )


def правило_языка(char_key: str) -> str:
    """Правило про язык ответа."""
    язык = LANGUAGE.get(char_key, "русский")
    if язык != "русский":
        return f"Отвечай на {язык} языке."
    return (
        "Отвечай на русском языке. Даже если вопрос смешанный, даже "
        "если в нём много английских терминов и кода: объясняй "
        "по-русски, английские слова оставляй только там, где они "
        "названия команд, функций и ключей. Ответ целиком на "
        "английском — ошибка."
    )


#: Замена слов мужского рода на женский.
#:
#: Слова оставлены в нижнем регистре и с учётом регистра при замене:
#: иначе «Я сделал» превратится в «я сделала» и потеряет заглавную.
_MASCULINE = {
    "сделал": "сделала", "сделала": "сделала",
    "подумал": "подумала", "решил": "решила",
    "попробовал": "попробовала", "написал": "написала",
    "объяснил": "объяснила", "сказал": "сказала",
    "ответил": "ответила", "спросил": "спросила",
    "помог": "помогла", "смог": "смогла", "смогла": "смогла",
    "умею": "умею", "знаю": "знаю",
    "готов": "готова", "уверен": "уверена",
    "прав": "права", "правда": "правда",
    "рад": "рада", "горжусь": "горжусь",
    "выбрал": "выбрала", "найду": "найду",
    "придумал": "придумала", "составил": "составила",
    "проверил": "проверила", "исправил": "исправила",
    "перевёл": "перевела", "перевела": "перевела",
    "добавил": "добавила", "убрал": "убрала",
    "занимаюсь": "занимаюсь", "работаю": "работаю",
    "хочу": "хочу", "буду": "буду",
    # «должен» здесь нет намеренно. Согласование у него составное:
    # «я должен был» превратился бы в «я должна был». Править такую
    # конструкцию без разбора остальных слов нельзя, а наша задача
    # — не ломать текст, а чинить род. Промахнётся модель в слове
    # «должен» один раз на тысячу ответов, и это честнее, чем
    # грамматическая ошибка от нашей замены.
    "готовлю": "готовлю", "думаю": "думаю",
    "держу": "держу", "клянусь": "клянусь",
    "был": "была", "была": "была",
    "пришёл": "пришла", "ушёл": "ушла",
    "нашёл": "нашла", "понял": "поняла",
    "заметил": "заметила", "оставил": "оставила",
    "возьму": "возьму", "покажу": "покажу",
}

#: Слова, которые не трогаем ни при каких условиях.
#:
#: Тут важна осторожность. «был» внутри «было» или «были» менять
#: нельзя, а «прав» — это и «правда», и «право», и «права». Ошибка
#: тут видна человеку, поэтому любое сомнительное слово просто не
#: трогаем: лишняя пара «готова» вместо «готов» хуже неправильного
#: ответа модели.
_НЕ_ТРОГАТЬ = re.compile(
    r"\b(было|были|был[ао]?сь|левый|правый|прав[ао]?|право|"
    r"готовность|довел|доводить|готовлюсь|готовит|"
    r"начал|начала|начать|начаться|"
    r"стал|стала|стать|стали|остал[ао]?сь|"
    r"взял|взяла|взять|принял|приняла|принять|"
    r"сказал[ао]?сь|закрыл|открыл|открыла|закрыла)\b",
    re.IGNORECASE,
)


def _заменить_одно(слово: str) -> str:
    """Одно слово с сохранением регистра."""
    if слово in _MASCULINE:
        замена = _MASCULINE[слово]
    else:
        # Регистр слова мог измениться при поиске.
        нижний = слово.lower()
        if нижний not in _MASCULINE:
            return слово
        замена = _MASCULINE[нижний]

    if слово.isupper():
        return замена.upper()
    if слово[:1].isupper():
        return замена[:1].upper() + замена[1:]
    return замена


def поправить_род(текст: str, char_key: str) -> tuple[str, int]:
    """Поправить род в готовом ответе. Возвращает текст и число правок.

    Что именно ищется
    -----------------
    Только слова мужского рода, перед которыми стоит «я» — сам, ты,
    мы — или форма прошедшего времени с «я». Без этого фильтра
    пришлось бы трогать каждого третьего: «я объяснил» правим, а
    «он объяснил» — это человек в цитате, и его пол здесь не наш.

    Почему так грубо
    ---------------
    Это не грамматический разбор. За кодом стоит не «понять язык»,
    а «не отправить промах». Промах заметен, а грубая проверка
    безопасна: лишнее слово она не трогает, потому что фильтр по
    «я» довольно узкий.
    """
    if род(char_key) != "женский" or not текст:
        return текст, 0

    правок = 0

    # Только первое лицо — «я» и «мне».
    #
    # «ты» и «вы» здесь не трогаем: это уже не бот, а собеседник.
    # Правило идёт от пола бота, и «Ты должен решить сам» — это
    # обращение к человеку. Превратившееся в «Ты должна решить
    # сама», оно меняет то, что человек сказал сам себе, и это
    # хуже оставшегося мужского рода в речи бота.
    def первое_лицо(совпадение: re.Match) -> str:
        nonlocal правок
        подлежащее = совпадение.group(1)
        глагол = совпадение.group(2)
        новое = _заменить_одно(глагол)
        if новое == глагол:
            return совпадение.group(0)
        правок += 1
        return подлежащее + новое

    текст = re.sub(
        r"(\b(?:я|мне)\s+)(\w+)",
        первое_лицо,
        текст, flags=re.IGNORECASE)

    return текст, правок


def проверить_род(текст: str, char_key: str) -> list[str]:
    """Какие мужские слова о себе остались в ответе.

    Нужно для проверок и для отладки: видно, что именно модель
    протащила, и можно понять, менять таблицу или подсказку.
    """
    if род(char_key) != "женский" or not текст:
        return []

    плохие: list[str] = []
    # Ищем «я <глагол>» с учётом того, что между ними может стоять
    # частица: «я же сделал», «я всё сделал».
    for совпадение in re.finditer(
            r"\b(?:я|мне)\s+(?:\w+\s+){0,2}?(\w+)", текст, re.IGNORECASE):
        слово = совпадение.group(1)
        нижний = слово.lower()
        if нижний in _MASCULINE and _MASCULINE[нижний] != слово:
            if _НЕ_ТРОГАТЬ.search(слово):
                continue
            плохие.append(слово)
    return плохие


def построить_правила(char_key: str) -> str:
    """Блок правил для конца подсказки: пол, затем язык.

    Порядок важен: пол — про форму ответа, язык — про то, на чём он
    написан. Сначала «в каком виде», потом «на чём».
    """
    return правило_пола(char_key) + "\n\n" + правило_языка(char_key)