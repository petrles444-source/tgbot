r"""База знаний: ответы из файлов, а не из головы модели.

Зачем
----
Модель отвечает из того, что видела при обучении. Про устройство
этого проекта, о командах бота, о принятых решениях она не знает
ничего и выдумывает правдоподобное: «контекст 4096 токенов»,
«память хранится в векторной базе», «модель gpt-4» — всё это
гладко и неверно.

Ответ, взятый из файла, правдив по построению: он написан здесь
и отсюда же прочитан. Поэтому точное — из файлов, спорное — у
модели.

Почему это не замедляет ответ
-----------------------------
Замер: чтение файла в 46 КБ стоит менее миллисекунды, один
запрос к модели — от 0,2 до 1,7 с. Разница в тысячу раз.

Поэтому поиск идёт обычными словами на Python, без запроса к
модели. Модель зовётся один раз и только если нужен её ответ.

Как устроено, чтобы не платить каждый раз
------------------------------------------
* `Индекс` строится один раз на процесс: список файлов, их
  заголовки и ключевые слова. Пересобирается, только если файлы
  изменились по времени правки.
* Открываются не все файлы, а два-три самых подходящих. В
  остальных поиск идёт по индексу, без чтения с диска.
* Из найденного вырезаются только совпавшие абзацы, и не больше
  заданного размера.
* Ответ кэшируется: повторный вопрос того же человека не ищет
  заново.

Что класть в папку
-------------------
Всё, на что бот должен отвечать точно: термины, рецепты, команды,
заметки о проекте. Файл — обычный текст с заголовком, первая
строка которого используется как название.
"""

from __future__ import annotations

import re
import time
from pathlib import Path
from typing import Any

#: Где лежат файлы базы. Папка внутри проекта: на сервер уезжает
#: вместе с кодом, и копировать её отдельно не нужно.
KNOWLEDGE_ROOT = Path(__file__).resolve().parent.parent / "знания"

#: Сколько файлов открывать за один запрос. Два-три: больше — уже
#: простыня, меньше — можно пропустить нужное.
MAX_FILES = 3

#: Сколько общих слов нужно, чтобы файл пошёл в ответ.
#:
#: Одного общего слова мало: вопрос «что такое контекст в этом
#: боте» пересекается с файлом про ботов по слову «бот», и файл
#: уезжал в запрос зря — время ответа росло, а пользы не было.
MIN_OVERLAP = 2

#: Сколько символов из одного файла уходит в запрос.
MAX_PER_FILE = 700

#: Всего символов базы в одном запросе. Этого хватает, чтобы
#: ответить точно, и мало, чтобы не мешать разговору.
MAX_TOTAL = 1200

#: Сколько ответов помнить. Кэш на одну сессию человека: он
#: спрашивает «что такое память», «а память у тебя своя?» — и второй
#: раз искать незачем.
CACHE_MAX = 60
_CACHE: dict[tuple[str, str], str] = {}

#: Индекс: путь -> (заголовок, ключевые слова, время правки).
_ИНдекс: dict[str, tuple[str, set[str], float]] = {}
_ИНдекс_время = 0.0

#: Слова-признаки вопроса о чём-то конкретном. Без них поиск
#: срабатывал бы на «привет» и «спасибо» и тащил в ответ базу
#: целиком.
_STOP = {
    "это", "как", "ты", "вы", "мне", "меня", "что", "для", "про",
    "но", "или", "если", "когда", "чтобы", "можешь", "может",
    "сделай", "напиши", "скажи", "ответь", "помоги", "давай",
    "привет", "здравствуй", "спасибо", "пока", "хорошо", "ок",
    "the", "and", "you", "your", "was", "were", "have", "has",
    "работает", "работать", "нужно", "надо", "есть", "быть",
}


#: Окончания, которые отбрасываются перед сравнением.
#:
#: Без этого поиск промахивался мимо нужного файла. Вопрос
#: «что делает кнопка» спрашивает про `кнопки.md`, но в заголовках
#: того файла лежат слова «кнопке» и «кнопки» — из других падежей.
#: Сравнение шло посимвольно, совпадения не было, и вместо файла
#: про кнопки приходил соседний — про ботов, потому что там нашлось
#: общее слово «делает».
#:
#: Это не морфология, а огрубление: режем хвост, оставляя основу.
#: Ложные совпадения возможны и не страшны — в файле всё равно
#: вырезаются только абзацы, пересекающиеся с вопросом.
_ОКОНЧАНИЯ = (
    "иями", "ями", "ами", "его", "ому", "ыми", "ими", "ей",
    "ой", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие",
    "ам", "ям", "ах", "ях", "ов", "ев", "ью", "ия", "ие",
    "а", "я", "о", "е", "у", "ю", "ы", "и", "ь", "й",
)


def _основа(слово: str) -> str:
    """Отрезать окончание: `кнопке` -> `кнопк`, `кнопка` -> `кнопк`."""
    if len(слово) <= 5:
        # Короткие слова резать опасно: «идея» превратится в «иде»,
        # а «ид» уже ни с чем не сравнить.
        return слово
    for окончание in _ОКОНЧАНИЯ:
        if слово.endswith(окончание):
            корень = слово[:-len(окончание)]
            if len(корень) >= 4:
                return корень
    return слово


def _слова(текст: str) -> set[str]:
    """Значимые слова в виде основ: не стоп-слова.

    Возвращаются основы, а не сами слова: и вопрос, и файлы
    приводятся к одному виду, иначе падеж мешает совпадению.

    Минимальная длина — три буквы, а не четыре, и имена ботов
    пропускаются в любом случае. С четырьмя буквами имя «Ада»
    отсекалось целиком: три буквы, и вопрос «кто такая ада»
    разбирался на пустое слово, база молчала на вопрос о самом
    боте.
    """
    основы: set[str] = set()
    for w in re.findall(r"[а-яёa-z0-9]{3,}", str(текст).lower()):
        if w in _STOP and w not in ИМЕНА:
            continue
        основы.add(_основа(w) if len(w) > 4 else w)
    return основы


def _разделы(текст: str) -> dict[str, set[str]]:
    """Разбить файл на разделы по заголовкам.

    Так точнее, чем искать по всему файлу: заголовок «Память» ведёт
    к разделу про память, а не к любому абзацу со словом «память».
    """
    out: dict[str, set[str]] = {}
    заголовок = ""
    накоплено: list[str] = []
    for строка in текст.splitlines():
        if строка.startswith("#"):
            if заголовок and накоплено:
                out[заголовок] = _слова("\n".join(накоплено))
            заголовок = строка.lstrip("# ").strip()
            накоплено = []
            continue
        накоплено.append(строка)
    if заголовок and накоплено:
        out[заголовок] = _слова("\n".join(накоплено))
    return out


def построить_индекс() -> dict[str, tuple[str, set[str], float]]:
    """Пересобрать индекс, если файлы изменились.

    Пересборка идёт по времени правки: пока файлы те же, индекс не
    трогается. Иначе он перечитывался бы на каждом сообщении, и
    весь выигрыш от кэша ушёл бы в никуда.
    """
    # Обе переменные — глобальные: индекс сохраняется между
    # вызовами, и пересобирать его на каждое сообщение незачем.
    # Без `global` присваивание внизу делает `_ИНДЕКС` локальной, и
    # чтение в начале падает с `UnboundLocalError`.
    global _ИНдекс, _ИНдекс_время
    if not KNOWLEDGE_ROOT.is_dir():
        return {}

    свежие: dict[str, tuple[str, set[str], float]] = {}
    самая_свежая = 0.0
    for path in sorted(KNOWLEDGE_ROOT.rglob("*.md")):
        try:
            правка = path.stat().st_mtime
        except OSError:
            continue
        самая_свежая = max(самая_свежая, правка)
        свежие[str(path)] = ("", set(), правка)

    if _ИНдекс and самая_свежая <= _ИНдекс_время:
        return _ИНдекс

    индекс: dict[str, tuple[str, set[str], float]] = {}
    for name, (_, _, правка) in свежие.items():
        try:
            текст = Path(name).read_text(encoding="utf-8")
        except OSError:
            continue
        строки = [s.strip() for s in текст.splitlines() if s.strip()]
        заголовок = ""
        for строка in строки:
            if строка.startswith("#"):
                заголовок = строка.lstrip("# ").strip()
                break
        if not заголовок and строки:
            заголовок = строки[0][:80]
        # Ключевые слова — из заголовка и всех заголовков разделов:
        # этого хватает, чтобы найти нужный файл, не читая его.
        ключи = _слова(заголовок)
        for подзаголовок in _разделы(текст):
            ключи |= _слова(подзаголовок)
        # Имена из текста целиком, без обрезания окончаний.
        #
        # Заголовок раздела может называть бота («Effy»), а в том же
        # файле он же может быть записан латиницей в `bots.json` и
        # кириллицей в тексте. Обрезанные основы туда не попадают:
        # из «Ада» получается «ад» в две буквы, и такой основы нет
        # ни в одном файле. Поэтому имена добавляются как есть.
        for слово in re.findall(r"[а-яёa-zA-Z]{3,}", текст.lower()):
            if слово in ИМЕНА:
                ключи.add(слово)
        индекс[name] = (заголовок, ключи, правка)

    _ИНдекс = индекс
    _ИНдекс_время = самая_свежая
    # Редкие слова — имена и термины — считаются здесь же: индекс
    # только что пересобран, лишний проход не нужен.
    _пересчитать_редкие(индекс)
    return индекс


#: С какого слова совпадение считается весомым.
#:
#: Длинное слово — редкое и предметное: «токен», «векторная»,
#: «память». Короткое — общее: «бот», «код», «файл». Одно длинное
#: совпадение показывает, что вопрос точно про это, а одно короткое
#: может совпасть с заголовком любого файла и ничего не значит.
SPECIFIC_LEN = 5


def _вес_совпадения(вопрос: str, ключи: set[str]) -> int:
    """Насколько вопрос совпадает с ключами файла.

    Считаем не количество, а вес: длинное слово весит два. Порог
    один и тот же, но смысл разный — это два весомых совпадения
    либо одно длинное. Раньше стоял простой счёт, и вопрос
    «что такое токен» — где значимых слов всего два, а совпадает
    одно — молчал, хотя попадание было точным.

    Короткие слова (4 буквы) весили одно, и порога в два не
    достигали. Из-за этого вопрос «кто такая effy» уходил в тишину:
    значимых слов два («кто», «effy»), совпадало только имя бота, а
    оно длиной четыре. База молчала на вопрос про самого Effy, и
    это самый обидный вид промаха.

    Поэтому короткое слово весит два, если оно встречается хотя бы
    где-то ещё: такие слова — имена и редкие термины, а не «бот» и
    «код». Проверяется по всему индексу, а не по текущему файлу, иначе
    решение зависело бы от того, какой файл смотрим.
    """
    общие = _слова(вопрос) & ключи
    вес = 0
    for слово in общие:
        if len(слово) >= SPECIFIC_LEN or слово in _РЕДКИЕ or слово in ИМЕНА:
            # Длинное — всегда предметное. Короткое, но нигде больше
            # не встречающееся, — тоже: значит, это имя или термин,
            # а не служебное слово вроде «бот».
            #
            # Имена ботов весят два независимо от того, сколько
            # файлов их упоминают. Проверка «встречается один раз»
            # тут ломалась: стоило описать Effy в файле про отказы —
            # и имя перестало быть редким, вопрос «кто такая Effy»
            # уходил в тишину. Имя собеседника находится всегда.
            вес += 2
        else:
            вес += 1
    return вес


#: Имена ботов. Весят два всегда.
#:
#: Список короткий и почти не меняется, поэтому берём его из
#: `bots.json` — там имена уже есть, и второй источник правды
#: со временем разошёлся бы с первым.
ИМЕНА: set[str] = {"ada", "anatoly", "effy", "mia", "lisa", "ада",
                   "анатолий", "эфф"}


#: Короткие слова, встречающиеся ровно в одном файле индекса.
#:
#: Считается вместе с индексом: иначе список либо пустовал бы при
#: первом обращении, либо устаревал бы после правки файлов.
_РЕДКИЕ: set[str] = set()


def _пересчитать_редкие(индекс: dict[str, tuple[str, set[str], float]]
                        ) -> None:
    """Найти слова, встречающиеся ровно в одном файле.

    Один проход по индексу, а не поиск по всему индексу на каждый
    вопрос. Делается только при пересборке индекса — а она и так
    случается редко.
    """
    global _РЕДКИЕ
    встречается: dict[str, int] = {}
    for _, ключи, _ in индекс.values():
        for слово in ключи:
            встречается[слово] = встречается.get(слово, 0) + 1
    _РЕДКИЕ = {с for с, число in встречается.items() if число == 1}
def _выбрать(вопрос: str, лимит: int = MAX_FILES) -> list[tuple[str, int]]:
    """Какие файлы почитать и в каком порядке."""
    искомое = _слова(вопрос)
    if not искомое:
        return []

    индекс = построить_индекс()
    оценки: list[tuple[float, str]] = []
    for путь, (заголовок, ключи, _) in индекс.items():
        совпадение = _вес_совпадения(вопрос, ключи)
        # Порог, а не «хоть одно общее слово». Вопрос «что такое
        # контекст в этом боте» пересекается с файлом про ботов по
        # слову «бот», и файл уезжал в запрос зря: время ответа
        # росло, а пользы не было.
        if совпадение < MIN_OVERLAP:
            continue

        # Совпадение с заголовком весит дороже, чем раскиданное по
        # подзаголовкам.
        #
        # Без этого два файла выходили вровень и оба съедали лимит
        # вступлениями: на вопрос «что умеет бот без нейросети» файл
        # с разделом «Арифметика» уступал соседнему файлу про ботов,
        # где то же было сказано словами. В запрос уезжало два
        # вступления, а конкретного ответа — «что именно умеет» —
        # не было нигде.
        бонус = max(
            (3.0 for слово in _слова(заголовок) if слово in искомое),
            default=0.0,
        )
        оценки.append((совпадение + бонус, путь))

    # Сортировка устойчивая по имени: при равной оценке порядок
    # не должен прыгать от запуска к запуску.
    оценки.sort(key=lambda строка: (-строка[0], строка[1]))
    return [(путь, оценка) for оценка, путь in оценки[:лимит]]


def _разделы_текстом(текст: str) -> list[tuple[str, str]]:
    """Файл как список пар «заголовок, текст под ним».

    Резать надо по заголовкам, а не по пустым строкам. Разрез по
    пустым строкам отделял «## термин» от определения под ним, и
    вопрос вроде «что такое токен» пересекался с заголовком, но не
    с текстом: слово «токен» там больше не повторяется. В запрос
    уезжал заголовок без сути, и модели было нечем отвечать.
    """
    пары: list[tuple[str, str]] = []
    заголовок = ""
    накоплено: list[str] = []

    for строка in текст.splitlines():
        if строка.startswith("#"):
            if заголовок or накоплено:
                пары.append((заголовок, "\n".join(накоплено).strip()))
            заголовок = строка.lstrip("# ").strip()
            накоплено = []
            continue
        накоплено.append(строка)

    if заголовок or накоплено:
        пары.append((заголовок, "\n".join(накоплено).strip()))
    return [(з, т) for з, т in пары if т]


def _вырезка(текст: str, вопрос: str, предел: int) -> str:
    """Из файла — только то, что относится к вопросу.

    Разделы целиком: заголовок вместе с текстом под ним. Разрез
    по пустым строкам разрывал связь, и в запрос уезжал заголовок
    без определения.
    """
    искомое = _слова(вопрос)
    разделы = _разделы_текстом(текст)
    if not разделы:
        return ""

    # Оценка раздела: заголовок весит больше текста под ним,
    # потому что вопрос «что такое токен» ищет именно в нём.
    оценки: list[tuple[int, str]] = []
    for заголовок, тело in разделы:
        вес = len(искомое & _слова(заголовок)) * 2
        вес += len(искомое & _слова(тело))
        if вес:
            оценки.append((вес, f"{заголовок}\n{тело}".strip()))

    # Совпало только само название файла, а разделы не задели.
    #
    # Вопрос «что умеет бот без нейросети» попадает в заголовок
    # `Что бот умеет без нейросети` и больше никуда: разделы
    # называются «Арифметика», «Время и дата», «Длина текста», и
    # общих слов с вопросом у них нет. В запрос уезжало вступление,
    # где перечисления нет — то есть на вопрос «что именно умеет»
    # модель получала текст без ответа.
    #
    # Проверка идёт по самому факту: совпал ровно один раздел и это
    # первый. Сравнивать вес с числом нельзя — тело вступления само
    # добавляет баллы, и сравнение с «вес заголовка» всегда
    # оказывалось ложным, то есть оглавление не добавлялось никогда.
    только_заголовок = len(оценки) == 1 and len(разделы) > 2
    if только_заголовок:
        оглавление = ", ".join(з for з, _ in разделы[1:] if з)
        if оглавление:
            верну = (оценки[0][1] + "\n\nВ этом файле есть разделы: "
                     + оглавление)
            if len(верну) <= предел:
                оценки[0] = (оценки[0][0], верну)

    # Ничего не нашлось — берём первый раздел: он обычно содержит
    # общее описание, и пустой ответ хуже, чем лишний абзац.
    if not оценки:
        первая = разделы[0]
        return f"{первая[0]}\n{первая[1]}"[:предел]

    оценки.sort(key=lambda строка: -строка[0])
    куски: list[str] = []
    занято = 0
    for вес, кусок in оценки:
        if занято + len(кусок) > предел:
            break
        куски.append(кусок)
        занято += len(кусок)
    return "\n\n".join(куски)

def найти(char_key: str, chat_id: int, вопрос: str) -> str:
    """Что из базы знаний относится к вопросу. Пустая строка, если ничего."""
    ключ = (str(char_key), str(int(chat_id)), str(вопрос)[:200])
    if ключ in _CACHE:
        return _CACHE[ключ]

    файлы = _выбрать(вопрос)
    if not файлы:
        return ""

    куски: list[str] = []
    занято = 0
    for путь, _оценка in файлы:
        if занято >= MAX_TOTAL:
            break
        try:
            текст = Path(путь).read_text(encoding="utf-8")
        except OSError:
            continue
        заголовок = _ИНдекс.get(путь, ("", set(), 0.0))[0] or Path(путь).stem
        предел = min(MAX_PER_FILE, MAX_TOTAL - занято)
        кусок = _вырезка(текст, вопрос, предел)
        if кусок:
            куски.append(f"[{заголовок}]\n{кусок}")
            занято += len(кусок)

    результат = "\n\n".join(куски)

    # Кэш ограничен: без него вопросы одного человека копились бы
    # вечно, а память на сервере не бесконечна.
    if len(_CACHE) >= CACHE_MAX:
        oldest = next(iter(_CACHE))
        _CACHE.pop(oldest, None)
    _CACHE[ключ] = результат
    return результат


def заметка(char_key: str, chat_id: int, вопрос: str) -> str:
    """Готовая строка для подсказки модели. Пустая, если нечего."""
    текст = найти(char_key, chat_id, вопрос)
    if not текст:
        return ""
    return ("ИЗ МОИХ ФАЙЛОВ, ПРОВЕРЕНО — ЭТО ТОЧНО, НЕ ВЫДУМЫВАЙ:\n"
            + текст_безопасный(текст))


def текст_безопасный(текст: str) -> str:
    """Ничего лишнего: без служебных пометок и очень длинных строк."""
    out = []
    for строка in текст.splitlines():
        строка = строка.strip()
        if строка.startswith("```"):
            continue
        out.append(строка[:300])
    return "\n".join(out).strip()


