# -*- coding: utf-8 -*-
"""SDC — тихий канал связи и расшифровка голосовых.

ЗАЧЕМ ЭТОТ БОТ
--------------
    Два дела, и они оба про одно: чтобы я мог говорить с владельцем,
    не дожидаясь, пока он откроет переписку.

    1. **Уведомления.** Я пишу в очередь или вызываю `/usr/local/bin/
       уведомить`, бот отправляет сообщение владельцу. Нужен срочный
       случай: сервер упал, кончились ключи, жду решения.

    2. **Расшифровка голосовых.** Владелец записывает голосовое сообщение
       — бот скачивает его, отдаёт движку распознавания, получает текст
       и КЛАДЁТ ЕГО В ФАЙЛ. Тот файл читаю я при следующей работе.

ПОЧЕМУ ГОЛОС ПРИХОДИТ В ФАЙЛ, А НЕ ПРОСТО В ЧАТ
----------------------------------------------
    Голосовое сообщение нельзя «прочитать» из переписки: я захожу в
    Telegram через бота, а не глазами человека. Текст, положенный в
    файл на сервере, я читаю обычной командой в любой момент. Это и
    есть «ты читал» — не фантазия, а файл, который можно открыть.

ПОЧЕМУ НЕ SBER
--------------
    Salute Speech от Сбера — отличный движок, но ключ к нему
    выдаётся в личном кабинете SberCloud на конкретного человека,
    и получить его без вас нельзя. Пока ключа нет — работает Whisper
    через Groq: ключ у нас уже есть, тариф бесплатный, а на русском
    он понимает речь не хуже. Когда дадите ключ Сбера, появится
    выбор: положить его в `sdc.json` рядом с ботом.

ПОЧЕМУ ТОЛЬКО СТАНДАРТНАЯ БИБЛИОТЕКА
--------------------------------------
    На сервере 708 МБ памяти, и ставить пакеты ради одной функции
    незачем. Распознавание отправляется файлом, склеивается вручную.

ЧТО БОТ НЕ ДЕЛАЕТ
-----------------
    Не отвечает на обычный текст. Это не собеседник, а канал: молчание
    на обычную реплику честнее, чем бот, который отвечает «принято» и
    больше ничего. Исключения перечислены в /помощь.

ЗАПУСК
------
    python3 sdc.py            работает
    python3 sdc.py --проверка самопроверка без сети
    python3 sdc.py --уведомить "текст"  разово отправить и выйти
"""

