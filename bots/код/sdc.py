def повтор(текст: str) -> bool:
    """Тот же текст уходит подряд второй раз? Тогда не отправляем.

    Без этого `/help` сразу после приветствия слал ту же простыню
    ещё раз: в чате это выглядит как дубль и выглядит поломкой.
    """
    return bool(текст) and текст.strip() == последний_текст()


