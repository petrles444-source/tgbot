def самопроверка() -> bool:
    import shutil
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    print("=== САМОПРОВЕРКА SDC ===")

    основа = HERE / ".проверка-sdc"
    shutil.rmtree(основа, ignore_errors=True)
    основа.mkdir(parents=True, exist_ok=True)
    старые = {имя: globals()[имя] for имя in
              ("ДАННЫЕ", "ВХОДЯЩИЕ", "НЕПРОЧИТАННЫЕ", "ПОДПИСЧИК",
               "ЖУРНАЛ", "СПИСОК", "РАЗРЕШЁННЫЕ", "ОТКАЗЫ", "ПОСЛЕДНЕЕ")}
    globals()["ДАННЫЕ"] = основа
    globals()["ВХОДЯЩИЕ"] = основа / "входящие"
    globals()["НЕПРОЧИТАННЫЕ"] = основа / "НЕПРОЧИТАННЫЕ.txt"
    globals()["ПОДПИСЧИК"] = основа / "подписчик.json"
    globals()["ЖУРНАЛ"] = основа / "sdc.log"
    globals()["СПИСОК"] = основа / "доступ.json"
    globals()["РАЗРЕШЁННЫЕ"] = основа / "разрешённые.json"
    globals()["ОТКАЗЫ"] = основа / "отказы.jsonl"
    globals()["ПОСЛЕДНЕЕ"] = основа / "последнее.txt"

    # Модуль управления тоже должен писать в черновик, а не в боевой
    # журнал: иначе прогон самопроверки засоряет историю команд.
    старые_упр = {}
    if упр is not None:
        for имя in ("ДАННЫЕ", "ЖУРНАЛ", "ПОСЛЕДНЯЯ_ОТПРАВКА"):
            старые_упр[имя] = getattr(упр, имя)
        упр.ДАННЫЕ = основа / "упр"
        упр.ЖУРНАЛ = основа / "упр" / "команды.jsonl"
        упр.ПОСЛЕДНЯЯ_ОТПРАВКА = основа / "упр" / "последние.json"

    # То же с очередью докладов. Про это забыли, и проверка «доклад от
    # сотрудника принят» положила настоящий доклад в боевую очередь:
    # четыре отчёта из повторяющихся слов ушли владельцу голосовыми.
    # Проверка не имеет права оставлять следы в рабочих данных.
    старые_докл = {}
    if докл is not None:
        for имя in ("ДАННЫЕ", "ОЧЕРЕДЬ", "ГОТОВЫ", "ЖУРНАЛ"):
            старые_докл[имя] = getattr(докл, имя)
        докл.ДАННЫЕ = основа / "докл"
        докл.ОЧЕРЕДЬ = основа / "докл" / "очередь"
        докл.ГОТОВЫ = основа / "докл" / "отправлено"
        докл.ЖУРНАЛ = основа / "докл" / "журнал.jsonl"
    try:
        _тело(чек)
    finally:
        globals().update(старые)
        for имя, значение in старые_упр.items():
            setattr(упр, имя, значение)
        for имя, значение in старые_докл.items():
            setattr(докл, имя, значение)
        shutil.rmtree(основа, ignore_errors=True)

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


