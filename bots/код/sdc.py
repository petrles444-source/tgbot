КЛЮЧИ_МОДЕЛЕЙ = Path("/opt/bots/.secret/ключи-моделей.json")
НАСТРОЙКИ = HERE / "sdc.json"
ДАННЫЕ = Path("/var/lib/sdc")
ВХОДЯЩИЕ = ДАННЫЕ / "входящие"
