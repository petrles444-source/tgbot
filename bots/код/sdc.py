# ─── Вход ───────────────────────────────────────────────────────────────────

def главная() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--проверка", action="store_true")
    ap.add_argument("--уведомить", metavar="ТЕКСТ")
    ap.add_argument("--проверить-токен", action="store_true")
    ap.add_argument("--добавить", nargs=2, metavar=("ИМЯ", "РОЛЬ"),
                    help="добавить в белый список: owners или staff")
    ap.add_argument("--завести", nargs=2, metavar=("ЮЗЕРНЕЙМ", "ПОЛ"),
                    help="завести сотрудника и назначить голос: "
                         "мужской или женский")
    args = ap.parse_args()

    if args.проверка:
        return 0 if самопроверка() else 2

    if args.завести:
        ok = завести_сотрудника(args.завести[0], args.завести[1])
        print("заведён" if ok else
              "отказ: нужен юзернейм без @ и пол — мужской или женский")
        return 0 if ok else 1

    if args.добавить:
        ok = добавить_в_список(args.добавить[0], args.добавить[1])
        print("добавлен" if ok else "не добавлен")
        return 0 if ok else 1

    if not TOKEN_FILE.exists():
        print(f"нет токена: {TOKEN_FILE}", file=sys.stderr)
        return 1
    токен = TOKEN_FILE.read_text(encoding="utf-8").strip()

    if args.проверить_токен:
        try:
            инфо = вызов(токен, "getMe")
            print(f"@{инфо.get('username')}")
            return 0
        except ОшибкаTelegram as e:
            print(f"токен не работает: {e}")
            return 1

    if args.уведомить:
        чат = подписчик()
        if not чат:
            print("подписчика нет", file=sys.stderr)
            return 1
        return 0 if сказать(токен, чат, args.уведомить) else 1

    try:
        цикл(токен)
    except KeyboardInterrupt:
        в_журнал("остановлен")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(главная())
