def отпечаток(значение: Any) -> str:
    return hashlib.sha256(str(значение).encode("utf-8")).hexdigest()[:12]


def _прочитать_json(path: Path, по_умолчанию: Any) -> Any:
    try:
        данные = json.loads(path.read_text(encoding="utf-8"))
        return данные
    except (ValueError, OSError):
        return по_умолчанию


def список() -> dict[str, Any]:
    данные = _прочитать_json(СПИСОК, {})
    if not isinstance(данные, dict):
        return {"owners": [], "staff": [], "пол": {}}
    пол = данные.get("пол") or {}
    if not isinstance(пол, dict):
        пол = {}
    return {
        "owners": [str(x).lower().lstrip("@") for x in данные.get("owners") or []],
        "staff": [str(x).lower().lstrip("@") for x in данные.get("staff") or []],
        "пол": {str(k).lower().lstrip("@"): str(v).lower()
                for k, v in пол.items() if str(v) in ("мужской", "женский")},
    }


def пол_человека(юзернейм: str | None, номер: Any = None) -> str | None:
    """Пол голоса сотрудника. None — голос не назначен.

    Пол назначает владелец при заведении сотрудника, а не угадывается.
    Правило проекта прямое: голос неправильного пола недопустим. Лучше
    не озвучить вовсе, чем озвучить чужим голосом, поэтому при отсутствии
    пола доклад не озвучивается, а владельцу уходит текстом.
    """
    данные = список()
    имя = str(юзернейм or "").lower().lstrip("@")
    пол = данные["пол"]
    if имя and имя in пол:
        return пол[имя]
    if номер is not None and номер != "":
        for запись in _прочитать_json(РАЗРЕШЁННЫЕ, []) or []:
            if (isinstance(запись, dict) and запись.get("роль") in
                    ("owners", "staff")):
                имя_из = str(запись.get("юзернейм") or "").lower().lstrip("@")
                if запись.get("отпечаток") == отпечаток(номер) and имя_из in пол:
                    return пол[имя_из]
    return None


def завести_сотрудника(юзернейм: str, пол: str, роль: str = "staff") -> bool:
    """Добавляет сотрудника в белый список и назначает ему голос."""
    роль = str(роль or "").lower()
    if роль not in ("owners", "staff"):
        return False
    имя = str(юзернейм or "").lower().lstrip("@")
    if not имя or "@" in имя or " " in имя:
        return False
    значение_пола = str(пол or "").strip().lower()
    if значение_пола not in ("мужской", "женский"):
        return False
    данные = список()
    if имя not in данные[роль]:
        данные[роль].append(имя)
    данные["пол"][имя] = значение_пола
    СПИСОК.parent.mkdir(parents=True, exist_ok=True)
    СПИСОК.write_text(json.dumps({
        "owners": sorted(set(данные["owners"])),
        "staff": sorted(set(данные["staff"])),
        "пол": dict(sorted(данные["пол"].items())),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return True


def добавить_в_список(имя: str, роль: str) -> bool:
    роль = str(роль or "").lower()
    if роль not in ("owners", "staff"):
        return False
    имя = str(имя or "").lower().lstrip("@")
    if not имя:
        return False
    данные = список()
    if имя not in данные[роль]:
        данные[роль].append(имя)
    СПИСОК.parent.mkdir(parents=True, exist_ok=True)
    СПИСОК.write_text(json.dumps({
        "owners": sorted(set(данные["owners"])),
        "staff": sorted(set(данные["staff"])),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return True


def роль_человека(юзернейм: str | None, номер: Any) -> str:
    """owners, staff, закрыт (список пуст) или никто."""
    данные = список()
    if not данные["owners"] and not данные["staff"]:
        return "закрыт"
    имя = str(юзернейм or "").lower().lstrip("@")
    if имя and имя in данные["owners"]:
        return "owners"
    if имя and имя in данные["staff"]:
        return "staff"
    if номер is not None and номер != "":
        отп = отпечаток(номер)
        for запись in _прочитать_json(РАЗРЕШЁННЫЕ, []) or []:
            if isinstance(запись, dict) and запись.get("отпечаток") == отп:
                if запись.get("роль") in ("owners", "staff"):
                    return str(запись["роль"])
    return "никто"


def запомнить(номер: Any, роль: str, юзернейм: str) -> None:
    записи = [з for з in (_прочитать_json(РАЗРЕШЁННЫЕ, []) or [])
              if isinstance(з, dict) and з.get("отпечаток") != отпечаток(номер)]
    записи.append({"отпечаток": отпечаток(номер), "роль": роль,
                    "юзернейм": юзернейм or None,
                    "когда": datetime.datetime.now().isoformat(timespec="seconds")})
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    РАЗРЕШЁННЫЕ.write_text(json.dumps(записи, ensure_ascii=False, indent=2),
                           encoding="utf-8")


