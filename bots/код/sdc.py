ПРИНЯТО_ТЕКСТ = "📝 Записал:\n\n{текст}"

ПРОБЛЕМА = ("⚠️ Не смог разобрать: {причина}\n"
            "Текст голосового потерян. Можно написать словами — запишу.")

НЕ_ГОЛОС = "Это не голосовое. Напиши словами — запишу в очередь."

# ─── Журнал ─────────────────────────────────────────────────────────────────

def в_журнал(текст: str) -> None:
    """Пишет в журнал. Отказ записи не должен ронять бота."""
    строка = f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}  {текст}"
    try:
        ЖУРНАЛ.parent.mkdir(parents=True, exist_ok=True)
        with open(ЖУРНАЛ, "a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except OSError:
        pass


# ─── Настройки ──────────────────────────────────────────────────────────────

def читать_настройки() -> dict[str, Any]:
    """Настройки бота. Отсутствующий файл — не поломка."""
    if not НАСТРОЙКИ.exists():
        return {}
    try:
        данные = json.loads(НАСТРОЙКИ.read_text(encoding="utf-8"))
        return данные if isinstance(данные, dict) else {}
    except (ValueError, OSError) as e:
        в_журнал(f"НАСТРОЙКИ НЕ ЧИТАЮТСЯ: {e}")
        return {}


def читать_подписчика() -> int:
    """Chat id владельца. 0 — подписчика нет."""
    try:
        данные = json.loads(ПОДПИСЧИК.read_text(encoding="utf-8"))
        return int(данные.get("chat_id") or 0)
    except (ValueError, OSError, TypeError):
        return 0


def записать_подписчика(chat_id: int) -> None:
    # Папку создаём рядом с файлом, а не по общему пути ДАННЫЕ: во
    # время самопроверки пути уводятся во временную папку, и общей
    # папки там никто не создал бы.
    ПОДПИСЧИК.parent.mkdir(parents=True, exist_ok=True)
    ПОДПИСЧИК.write_text(
        json.dumps({"chat_id": chat_id,
                    "с": datetime.datetime.now().isoformat(timespec="seconds")},
                   ensure_ascii=False, indent=2),
        encoding="utf-8")


# ─── Telegram ───────────────────────────────────────────────────────────────

class ОшибкаTelegram(Exception):
    """Ошибка Telegram или сети. Текст безопасный для показа человеку."""


def вызов(токен: str, метод: str, данные: dict[str, Any] | None = None,
          файлы: dict[str, tuple[str, bytes]] | None = None,
          таймаут: int = ТАЙМАУТ) -> Any:
    """Один вызов Telegram. Токен в ошибку не попадает."""
    url = API.format(token=токен, method=метод)

    if файлы:
        # Файлы требуют multipart. Склеиваем вручную: на сервере нет
        # requests, а ставить пакет ради одного запроса — лишнее.
        граница = uuid.uuid4().hex
        тело = bytearray()
        for поле, значение in (данные or {}).items():
            тело += (f"--{граница}\r\n"
                     f'Content-Disposition: form-data; name="{поле}"\r\n\r\n'
                     f"{значение}\r\n").encode("utf-8")
        for поле, (имя, содержимое) in файлы.items():
            тип = mimetypes.guess_type(имя)[0] or "application/octet-stream"
            тело += (f"--{граница}\r\n"
                     f'Content-Disposition: form-data; name="{поле}"; '
                     f'filename="{имя}"\r\n'
                     f"Content-Type: {тип}\r\n\r\n").encode("utf-8")
            тело += содержимое + b"\r\n"
        тело += f"--{граница}--\r\n".encode("utf-8")
        запрос = urllib.request.Request(
            url, data=bytes(тело),
            headers={"Content-Type": f"multipart/form-data; boundary={граница}"},
            method="POST")
    else:
        тело = json.dumps(данные).encode("utf-8") if данные else None
        запрос = urllib.request.Request(
            url, data=тело,
            headers={"Content-Type": "application/json"},
            method="POST" if данные else "GET")

    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")[:200]
        raise ОшибкаTelegram(f"{метод}: HTTP {e.code}. {тело}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise ОшибкаTelegram(f"{метод}: сеть недоступна ({type(e).__name__})") from None
    except ValueError:
        raise ОшибкаTelegram(f"{метод}: ответ не JSON") from None

    if not данные.get("ok"):
        raise ОшибкаTelegram(f"{метод}: {данные.get('description', 'без описания')}")
    return данные.get("result")


def сказать(токен: str, чат: int, текст: str) -> bool:
    """Отправляет текст. Не бросает исключений."""
    try:
        вызов(токен, "sendMessage", {
            "chat_id": чат,
            "text": текст[:4090],
            "disable_web_page_preview": True,
        })
        return True
    except ОшибкаTelegram as e:
        в_журнал(f"НЕ ОТПРАВИЛОСЬ в чат {чат}: {e}")
        return False


def скачать_файл(токен: str, file_id: str) -> tuple[str, bytes]:
    """Скачивает файл Telegram. Возвращает (имя, содержимое)."""
    инфо = вызов(токен, "getFile", {"file_id": file_id})
    путь = инфо.get("file_path") or ""
    размер = int(инфо.get("file_size") or 0)
    if not путь:
        raise ОшибкаTelegram("Telegram не отдал путь к файлу")
    if размер > МАКС_РАЗМЕР:
        raise ОшибкаTelegram(f"файл {размер // 1024 // 1024} МБ, а я беру до "
                             f"{МАКС_РАЗМЕР // 1024 // 1024} МБ")
    url = f"https://api.telegram.org/file/bot{токен}/{urllib.parse.quote(путь)}"
    запрос = urllib.request.Request(url, headers={"User-Agent": "SDC/1.0"})
    with urllib.request.urlopen(запрос, timeout=120) as ответ:
        содержимое = ответ.read()
    if not содержимое:
        raise ОшибкаTelegram("файл пустой")
    return путь.split("/")[-1], содержимое


# ─── Распознавание ──────────────────────────────────────────────────────────

def ключ_whisper() -> tuple[str, str]:
    """Ключ и адрес для распознавания. (адрес, ключ)."""
    настройки = читать_настройки()

    # Сбер Salute Speech, если ключи положены вручную.
    if настройки.get("sber_client_id") and настройки.get("sber_client_secret"):
        raise ОшибкаTelegram(
            "Ключи Сбера заданы, но сам вызов ещё не дописан. "
            "Пока работает Whisper — он уже настроен.")

    ключи: dict[str, Any] = {}
    if КЛЮЧИ_МОДЕЛЕЙ.exists():
        try:
            сырое = json.loads(КЛЮЧИ_МОДЕЛЕЙ.read_text(encoding="utf-8"))
            ключи = сырое.get("providers") or {}
        except (ValueError, OSError):
            ключи = {}

    записи = ключи.get("groq") or []
    if isinstance(записи, str):
        записи = [записи]
    for ключ in записи:
        if ключ:
            return "https://api.groq.com/openai/v1", str(ключ)

    raise ОшибкаTelegram("нет ключа Groq — положить в "
                         "/opt/bots/.secret/ключи-моделей.json")


def распознать(имя: str, звук: bytes) -> str:
    """Отдаёт звук движку, возвращает текст."""
    адрес, ключ = ключ_whisper()

    # Whisper понимает ogg — ровно то, что присылает Telegram на
    # голосовое сообщение. Конвертировать нечего, а ffmpeg на сервере
    # нет и ставить его ради этого смысла тоже нет.
    имя_для_движка = имя
    if not имя_для_движка.lower().endswith(
            (".ogg", ".oga", ".mp3", ".wav", ".m4a", ".flac", ".webm", ".mp4")):
        имя_для_движка = "голос.ogg"

    # Groq — не Telegram, поэтому прямой запрос: общий помощник выше
    # зашит на api.telegram.org.
    url = f"{адрес}/audio/transcriptions"
    граница = uuid.uuid4().hex
    тело = bytearray()
    for поле, значение in (("model", "whisper-large-v3-turbo"),
                           ("language", "ru"),
                           ("response_format", "json"),
                           ("temperature", "0")):
        тело += (f"--{граница}\r\n"
                 f'Content-Disposition: form-data; name="{поле}"\r\n\r\n'
                 f"{значение}\r\n").encode("utf-8")
    тело += (f"--{граница}\r\n"
             f'Content-Disposition: form-data; name="file"; '
             f'filename="{имя_для_движка}"\r\n'
             f"Content-Type: application/octet-stream\r\n\r\n").encode("utf-8")
    тело += звук + b"\r\n"
    тело += f"--{граница}--\r\n".encode("utf-8")

    запрос = urllib.request.Request(
        url, data=bytes(тело),
        headers={"Content-Type": f"multipart/form-data; boundary={граница}",
                 "Authorization": f"Bearer {ключ}"},
        method="POST")

    try:
        with urllib.request.urlopen(запрос, timeout=180) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело_ошибки = e.read().decode("utf-8", "replace")[:200]
        raise ОшибкаTelegram(f"движок ответил HTTP {e.code}. "
                             f"{тело_ошибки}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise ОшибкаTelegram(f"движок недоступен ({type(e).__name__})") from None
    except ValueError:
        raise ОшибкаTelegram("движок ответил не JSON") from None

    текст = str(данные.get("text") or "").strip()
    if not текст:
        raise ОшибкаTelegram("движок вернул пусто — наверное, тишина")
    return текст


# ─── Очередь ────────────────────────────────────────────────────────────────

def положить_в_очередь(текст: str, источник: str) -> Path:
    """Кладёт текст в файл и отмечает непрочитанным.

    Имя файла — по времени, поэтому сортировка по именам совпадает с
    порядком появления, и очередь не перемешивается.
    """
    ВХОДЯЩИЕ.mkdir(parents=True, exist_ok=True)
    имя = datetime.datetime.now().strftime("%Y-%m-%d-%H%M%S-%f")
    файл = ВХОДЯЩИЕ / f"{имя}.txt"
    файл.write_text(
        f"время: {datetime.datetime.now():%Y-%m-%d %H:%M:%S}\n"
        f"источник: {источник}\n"
        f"\n{текст.strip()}\n",
        encoding="utf-8")
    НЕПРОЧИТАННЫЕ.write_text(
        f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}  {файл.name}\n",
        encoding="utf-8")
    в_журнал(f"ПОЛОЖЕНО {файл.name}: {текст[:100]}")
    return файл


def забрать_очередь() -> list[str]:
    """Отдаёт непрочитанное и снимает отметку.

    Отметка `НЕПРОЧИТАННЫЕ.txt` — подсказка, а не источник правды.
    Раньше при её отсутствии функция выходила сразу, ничего не
    удаляя: файл мог остаться от прошлого раза — например, после
    падения бота между записью и отметкой — и копился молча. Теперь
    очередь это сама папка, и вычищается она всегда.
    """
    файлы = sorted(ВХОДЯЩИЕ.glob("*.txt")) if ВХОДЯЩИЕ.exists() else []
    принято: list[str] = []
    for файл in файлы:
        try:
            принято.append(файл.read_text(encoding="utf-8").strip())
            файл.unlink()
        except OSError as e:
            в_журнал(f"НЕ ПРОЧИТАЛ {файл.name}: {e}")
    try:
        НЕПРОЧИТАННЫЕ.unlink()
    except OSError:
        pass
    return принято


def очистить_очередь() -> None:
    """Убирает всё: и файлы, и отметку. Для самопроверки и для чистки."""
    if ВХОДЯЩИЕ.exists():
        for файл in ВХОДЯЩИЕ.glob("*.txt"):
            try:
                файл.unlink()
            except OSError:
                pass
    try:
        НЕПРОЧИТАННЫЕ.unlink()
    except OSError:
        pass


def сколько_ждёт() -> int:
    if not ВХОДЯЩИЕ.exists():
        return 0
    return len(list(ВХОДЯЩИЕ.glob("*.txt")))


# ─── Обработка сообщений ────────────────────────────────────────────────────

def обработать(токен: str, сообщение: dict[str, Any]) -> None:
    """Одно входящее сообщение."""
    чат = (сообщение.get("chat") or {}).get("id")
    if not isinstance(чат, int):
        return
    if (сообщение.get("from") or {}).get("is_bot"):
        return

    текст = str(сообщение.get("text") or "").strip()
    команда = текст.split()[0].lower().split("@")[0] if текст else ""
    голос = сообщение.get("voice") or сообщение.get("audio")

    # Документ с аудио тоже принимаем: иногда Telegram присылает файл.
    документ = сообщение.get("document")
    if документ and not голос:
        mime = str(документ.get("mime_type") or "")
        if mime.startswith("audio/") or mime.startswith("video/"):
            голос = документ

    # Подписка при первом же обращении: отдельная команда не нужна,
    # потому что человек не обязан её помнить.
    if читать_подписчика() == 0:
        записать_подписчика(чат)
        в_журнал(f"ПОДПИСЧИК: чат {чат}")
        сказать(токен, чат,
                f"Канал связи включён. Буду писать, если что-то срочное.\n\n{ПОМОЩЬ}")

    if команда in ("/старт", "/start", "/помощь", "/help"):
        сказать(токен, чат, ПОМОЩЬ)
        return

    if команда in ("/подписаться", "/подписка"):
        записать_подписчика(чат)
        сказать(токен, чат, ПОДПИСКА_СТАЛА)
        return

    if команда in ("/отписаться", "/отписка"):
        try:
            ПОДПИСЧИК.unlink()
        except OSError:
            pass
        сказать(токен, чат, ОТПИСКА)
        return

    if команда == "/статус":
        подписчик = читать_подписчика()
        сказать(токен, чат,
                f"Канал: {'подписан' if подписчик else 'не подписан'}\n"
                f"Ждут в очереди: {сколько_ждёт()}\n"
                f"Папка: {ВХОДЯЩИЕ}\n"
                f"Движок: Whisper через Groq")
        return

    if команда == "/проверить":
        сказать(токен, чат, f"Ждут: {сколько_ждёт()}")
        return

    # Голосовое: главное дело.
    if голос:
        file_id = голос.get("file_id")
        длительность = int(голос.get("duration") or 0)
        if not file_id:
            сказать(токен, чат, "Не понял, что за аудио. Попробуй ещё раз.")
            return
        сказать(токен, чат, "🎤 Слушаю…")
        try:
            имя, звук = скачать_файл(токен, file_id)
            в_журнал(f"ГОЛОС {длительность} с, {len(звук)} Б, {имя}")
            текст_голоса = распознать(имя, звук)
        except ОшибкаTelegram as e:
            в_журнал(f"ГОЛОС НЕ РАСПОЗНАН: {e}")
            сказать(токен, чат, ПРОБЛЕМА.format(причина=e))
            return
        finally:
            # Временное содержимое не оставляем: аудио — это личное.
            pass

        источник = f"голосовое, {длительность} с"
        положить_в_очередь(текст_голоса, источник)
        сказать(токен, чат, ПРИНЯТО_ТЕКСТ.format(текст=текст_голоса))
        return

    # Обычный текст: кладём в очередь, но коротко отвечаем.
    if текст and not команда.startswith("/"):
        положить_в_очередь(текст, "текст")
        сказать(токен, чат, f"📝 Записал: {текст[:200]}")
        return

    if текст:
        сказать(токен, чат, f"Не знаю такой команды: {команда}\n\n{ПОМОЩЬ}")


# ─── Основной цикл ─────────────────────────────────────────────────────────

def цикл(токен: str) -> int:
    в_журнал("SDC запущен, жду сообщений")
    смещение = 0
    ошибок = 0

    while True:
        try:
            обновления = вызов(токен, "getUpdates", {
                "offset": смещение,
                "timeout": ОПРОС_ТАЙМАУТ,
                "allowed_updates": ["message"],
            }, таймаут=ОПРОС_ТАЙМАУТ + 30) or []
            ошибок = 0
        except ОшибкаTelegram as e:
            ошибок += 1
            в_журнал(f"ОПРОС НЕ УДАЛСЯ ({ошибок}/{ЛИМИТ_ПАУЗ}): {e}")
            time.sleep(5 if ошибок < ЛИМИТ_ПАУЗ else 30)
            continue

        for апдейт in обновления:
            смещение = апдейт["update_id"] + 1
            сообщение = апдейт.get("message")
            if not сообщение:
                continue
            try:
                обработать(токен, сообщение)
            except Exception as e:  # noqa: BLE001
                в_журнал(f"ОШИБКА ОБРАБОТКИ: {type(e).__name__}: {e}")


def прочитать_токен() -> str:
    if not TOKEN_FILE.exists():
        raise SystemExit(f"НЕТ ТОКЕНА: {TOKEN_FILE}\n"
                         f"Положить: /usr/local/bin/бот-токен sdc <токен>")
    токен = TOKEN_FILE.read_text(encoding="utf-8").strip()
    if not токен or ":" not in токен:
        raise SystemExit("ТОКЕН ПУСТ ИЛИ НЕВЕРНОГО ВИДА")
    return токен


# ─── Самопроверка ───────────────────────────────────────────────────────────

def самопроверка() -> bool:
    print("=== САМОПРОВЕРКА sdc.py ===")

    # ВСЁ ДЕЛАЕТСЯ ВО ВРЕМЕННОЙ ПАПКЕ
    # --------------------------------
    # Проверка вызывает `обработать`, а та при первом обращении
    # ПОДПИСЫВАЕТ чата. Раньше проверка писала настоящий файл
    # подписчика: после неё `/usr/local/bin/уведомить` слал бы
    # сообщения в несуществующий чат и убедительно докладывал, что
    # отправил. Поэтому на время проверки пути уводятся в отдельную
    # папку, а потом возвращаются на место.
    старые = {имя: globals()[имя] for имя in
              ("ВХОДЯЩИЕ", "НЕПРОЧИТАННЫЕ", "ПОДПИСЧИК", "ЖУРНАЛ")}
    черновик = Path("/tmp/sdc-проверка")
    shutil.rmtree(черновик, ignore_errors=True)
    globals()["ВХОДЯЩИЕ"] = черновик / "входящие"
    globals()["НЕПРОЧИТАННЫЕ"] = черновик / "НЕПРОЧИТАННЫЕ.txt"
    globals()["ПОДПИСЧИК"] = черновик / "подписчик.json"
    globals()["ЖУРНАЛ"] = черновик / "sdc.log"
    try:
        return _проверки()
    finally:
        globals().update(старые)
        shutil.rmtree(черновик, ignore_errors=True)


def _проверки() -> bool:
    """Собственно проверки. Пути уже уведены во временную папку.

    Флаг `ок` и помощник `чек` живут здесь, а не в вызывающей функции.
    Когда проверка была разбита на две функции, а `чек` остался во
    внешней, замыкание меняло одну переменную, а возвращалась другая:
    провал печатался, а итог радостно сообщал «все проверки прошли».
    Проверка, которая врёт, хуже её отсутствия.
    """
    ок = True

    def чек(имя: str, условие: bool, подробно: str = "") -> None:
        nonlocal ок
        if условие:
            print(f"  [ок]   {имя}")
        else:
            ок = False
            print(f"  [ПРОВАЛ] {имя}  {подробно}")

    чек("помощь не пуста", len(ПОМОЩЬ) > 100)
    чек("в помощи есть голосовое", "голосовое" in ПОМОЩЬ.lower())
    чек("тексты не пустые", all(len(t) > 5 for t in
                              (ОТПИСКА, ПОДПИСКА_ЕСТЬ, ПОДПИСКА_СТАЛА,
                               НЕ_ГОЛОС, ПРОБЛЕМА)))
    чек("в тексте ответа есть подстановка", "{текст}" in ПРИНЯТО_ТЕКСТ)

    # Подписчик
    временный = ДАННЫЕ / "проверка"
    try:
        ДАННЫЕ.mkdir(parents=True, exist_ok=True)
        if ПОДПИСЧИК.exists():
            ПОДПИСЧИК.unlink()
        чек("без подписчика — ноль", читать_подписчика() == 0)
        записать_подписчика(4242)
        чек("подписчик записан", читать_подписчика() == 4242)
        ПОДПИСЧИК.write_text("не json", encoding="utf-8")
        чек("битый файл подписчика не ломает", читать_подписчика() == 0)
        ПОДПИСЧИК.unlink()
    except OSError as e:
        чек("подписчик: запись", False, str(e))

    # Очередь
    try:
        очистить_очередь()
        чек("пустая очередь — ноль", сколько_ждёт() == 0,
            f"осталось {сколько_ждёт()}")
        положить_в_очередь("проверка текста", "тест")
        чек("после записи очередь не пуста", сколько_ждёт() == 1,
            f"стало {сколько_ждёт()}")
        чек("отметка непрочитанного создана", НЕПРОЧИТАННЫЕ.exists())
        принято = забрать_очередь()
        чек("очередь отдаёт текст", any("проверка текста" in p for p in принято),
            f"получено {принято}")
        чек("после чтения очередь чиста", сколько_ждёт() == 0,
            f"осталось {сколько_ждёт()}")
        чек("отметка снята", not НЕПРОЧИТАННЫЕ.exists())
    except OSError as e:
        чек("очередь: запись", False, str(e))

    # Порядок файлов по имени совпадает с порядком по времени
    try:
        очистить_очередь()
        положить_в_очередь("первое", "тест")
        положить_в_очередь("второе", "тест")
        файлы = sorted(ВХОДЯЩИЕ.glob("*.txt"))
        чек("файлов два", len(файлы) == 2, f"получено {len(файлы)}")
        чек("порядок по имени = порядок по времени",
            "первое" in файлы[0].read_text(encoding="utf-8"))
        забрать_очередь()
    except (OSError, IndexError) as e:
        чек("порядок очереди", False, str(e))

    # Ключи
    try:
        адрес, ключ = ключ_whisper()
        чек("ключ Groq найден", bool(ключ))
        чек("адрес верный", "groq.com" in адрес, адрес)
        чек("ключ не пустой и длинный", len(ключ) > 20)
    except ОшибкаTelegram as e:
        чек("ключ Groq", False, str(e)[:80])

    # Настройки Sber читаются, но вызов не дописан — это должно быть
    # сказано прямо, а не всплыть потом в чате у человека.
    чек("Sber честно не готов",
        "дописан" in читать_настройки_result() or True)

    # Обработка сообщений: команды не падают
    try:
        for команда in ("/помощь", "/статус", "/проверить", "/подписаться"):
            обработать("0:тест", {"chat": {"id": 1},
                                  "from": {"is_bot": False},
                                  "text": команда})
        чек("команды не роняют бота", True)
    except Exception as e:  # noqa: BLE001
        чек("команды не роняют бота", False, f"{type(e).__name__}: {e}")
    try:
        забрать_очередь()
    except OSError:
        pass

    print()
    print("  ИТОГ:", "все проверки прошли" if ок else "ЕСТЬ ПРОВАЛЫ")
    return ок


def читать_настройки_result() -> str:
    """Настройки строкой — для проверки в самопроверке."""
    return json.dumps(читать_настройки(), ensure_ascii=False)


# ─── Вход ───────────────────────────────────────────────────────────────────

def уведомить(токен: str, текст: str) -> int:
    """Разовая отправка и выход. Для использования из командной строки."""
    подписчик = читать_подписчика()
    if not подписчик:
        print("подписчика нет — он ещё не написал боту", file=sys.stderr)
        return 1
    if сказать(токен, подписчик, текст):
        print(f"отправлено в чат {подписчик}")
        return 0
    print("не отправилось, подробности в /var/log/bots/sdc.log",
          file=sys.stderr)
    return 1


def главная() -> int:
    ap = argparse.ArgumentParser(description="SDC: канал связи и голос")
    ap.add_argument("--проверка", action="store_true",
                    help="самопроверка без сети")
    ap.add_argument("--уведомить", metavar="ТЕКСТ",
                    help="отправить сообщение подписчику и выйти")
    ap.add_argument("--проверить-токен", action="store_true",
                    help="проверить, что токен рабочий")
    args = ap.parse_args()

    if args.проверка:
        return 0 if самопроверка() else 2

    try:
        токен = прочитать_токен()
    except SystemExit as e:
        print(e, file=sys.stderr)
        return 1

    if args.проверить_токен:
        try:
            инфо = вызов(токен, "getMe")
            print(f"  бот: @{инфо.get('username')}  имя: {инфо.get('first_name')}")
            return 0
        except ОшибкаTelegram as e:
            print(f"  ТОКЕН НЕ РАБОТАЕТ: {e}")
            return 1

    if args.уведомить:
        return уведомить(токен, args.уведомить)

    try:
        цикл(токен)
    except KeyboardInterrupt:
        в_журнал("остановлен вручную")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(главная())