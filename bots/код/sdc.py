class ОшибкаTelegram(Exception):
    pass


def вызов(токен: str, метод: str, данные: dict[str, Any] | None = None,
          таймаут: int = ТАЙМАУТ) -> Any:
    url = API.format(token=токен, метод=метод)
    тело = json.dumps(данные).encode("utf-8") if данные else None
    запрос = urllib.request.Request(
        url, data=тело, headers={"Content-Type": "application/json"},
        method="POST" if данные else "GET")
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise ОшибкаTelegram(f"{метод}: HTTP {e.code}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise ОшибкаTelegram(f"{метод}: сеть ({type(e).__name__})") from None
    except ValueError:
        raise ОшибкаTelegram(f"{метод}: не JSON") from None
    if not данные.get("ok"):
        raise ОшибкаTelegram(f"{метод}: {данные.get('description', '')}")
    return данные.get("result")


def сказать(токен: str, чат: int, текст: str, тихо: bool = False) -> bool:
    """Отправляет текст. Молча отказывается слать дубль подряд."""
    if повтор(текст):
        в_журнал("ПРОПУЩЕН дубль: " + текст.strip()[:60])
        return False
    try:
        вызов(токен, "sendMessage",
              {"chat_id": чат, "text": текст[:4000],
               "disable_web_page_preview": True})
        запомнить_отправленное(текст)
        return True
    except ОшибкаTelegram as e:
        в_журнал(f"НЕ ОТПРАВИЛОСЬ: {e}")
        return False


