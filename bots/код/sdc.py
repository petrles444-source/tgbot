def цикл(токен: str) -> None:
    в_журнал("SDC запущен")
    смещение = 0
    ошибок = 0
    while True:
        try:
            обновления = вызов(токен, "getUpdates", {
                "offset": смещение, "timeout": ОПРОС_ТАЙМАУТ,
                "allowed_updates": ["message"]},
                таймаут=ОПРОС_ТАЙМАУТ + 30) or []
            ошибок = 0
        except ОшибкаTelegram as e:
            ошибок += 1
            в_журнал(f"ОПРОС ({ошибок}): {e}")
            time.sleep(5 if ошибок < 5 else 30)
            continue
        for апдейт in обновления:
            смещение = апдейт["update_id"] + 1
            сообщение = апдейт.get("message")
            if not сообщение:
                continue
            try:
                обработать(токен, сообщение)
            except Exception as e:  # noqa: BLE001
                в_журнал(f"ОШИБКА: {type(e).__name__}: {e}")


