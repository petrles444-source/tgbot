def _разобрать_хвост(хвост: str, сколько: int) -> list[str] | None:
    """Разобрать «ada -100123 текст со словами» на 3 части.

    Текст в конце может содержать пробелы, поэтому режем только первые
    сколько-1 разделителей: режем по пробелу, но не больше.
    """
    части = хвост.split(None, сколько - 1)
    if len(части) < сколько:
        return None
    return части


def выполнить_управление(команда: str, хвост: str, автор: dict[str, Any],
                         роль: str, чат: int) -> str:
    """Единая точка для команд управления. Всегда возвращает короткий текст."""
    имя_человека = автор.get("username") or f"id{автор.get('id')}"

    if команда == "/чат":
        return САМОПРОВЕРКА_ЧАТ.format(чат=чат)

    if упр is None:
        return НЕТ_УПРАВЛЕНИЯ

    if команда == "/боты":
        return упр.состояние()

    if команда == "/журнал":
        return упр.журнал()

    if команда == "/чаты":
        места = упр.где_боты(имя_человека)
        if not места:
            return "Пока никто нигде не писал."
        строки = ["Где писали:"]
        for м in места:
            строки.append(f"  {м['бот']} — чат {м['чат']}")
        return "\n".join(строки)

    if команда == "/помощь-боты":
        return ПОМОЩЬ_УПРАВЛЕНИЯ

    if команда == "/сказать":
        части = _разобрать_хвост(хвост, 3)
        if части is None:
            return ПОМОЩЬ_УПРАВЛЕНИЯ
        бот, чат_текст, речь = части
        if not _это_число(чат_текст):
            return ЧАТ_НЕ_ЧИСЛО
        р = упр.сказать(бот, int(чат_текст), речь, имя_человека)
        return (f"{бот} написал в {чат_текст}." if р["ok"]
                else НЕ_ВЫШЛО.format(причина=р["причина"]))

    if команда == "/ответить":
        части = _разобрать_хвост(хвост, 4)
        if части is None:
            return "Формат: /ответить БОТ ЧАТ СООБЩЕНИЕ текст"
        бот, чат_текст, номер_текст, речь = части
        if not _это_число(чат_текст):
            return ЧАТ_НЕ_ЧИСЛО
        if not _это_число(номер_текст):
            return "Номер сообщения — это число. Посмотри его в чате."
        р = упр.ответить(бот, int(чат_текст), int(номер_текст), речь,
                        имя_человека)
        return (f"{бот} ответил в {чат_текст}." if р["ok"]
                else НЕ_ВЫШЛО.format(причина=р["причина"]))

    return НЕТ_БОТА.format(боты=", ".join(упр.БОТЫ) if упр else "нет")


def _это_число(текст: str) -> bool:
    """Проверка без int(): число может быть со знаком и очень длинным."""
    тело = текст.strip().lstrip("-")
    return bool(тело) and тело.isdigit()


def состояние_очереди_докладов() -> list[Any]:
    """Что сейчас в очереди докладов. Пусто, если модуль не подключён."""
    if докл is None:
        return []
    try:
        return докл.состояние_очереди()
    except Exception:
        return []


def отправить_в_доклад(расшифровка: str, автор: dict[str, Any],
                      роль: str) -> str:
    """Кладёт доклад в очередь и говорит сотруднику, что вышло.

    Правило длины то же, что и у докладов: короче минуты — не доклад,
    а сообщение. Молча проглатывать короткое голосовое нельзя, человек
    должен понять, услышали его как доклад или как записку.
    """
    if докл is None:
        return "Доклады не подключены — голосовое записано."
    пол = пол_человека(автор.get("username"), автор.get("id"))
    имя = автор.get("username") or f"id{автор.get('id')}"
    р = докл.положить_в_очередь(расшифровка, пол or "мужской", имя)
    if not р["ok"]:
        # Короткое голосовое — это записка, и так и говорим.
        return ("Записал как сообщение, не доклад: "
                + р["причина"].split(":")[0].strip().capitalize() + ".")
    номер = р["запись"]["номер"]
    if пол:
        return (f"Доклад №{номер} в очереди. Озвучу голосом: {пол}.")
    return (f"Доклад №{номер} в очереди. Голос не назначен, поэтому уйдёт "
            f"текстом: владелец должен указать твой пол голоса.")


def обработать(токен: str, сообщение: dict[str, Any]) -> None:
    чат = (сообщение.get("chat") or {}).get("id")
    if not isinstance(чат, int):
        return
    автор = сообщение.get("from") or {}
    if автор.get("is_bot"):
        return

    # ДОСТУП — ПЕРВЫМ ДЕЛОМ
    роль = роль_человека(автор.get("username"), автор.get("id"))
    if роль not in ("owners", "staff"):
        if роль == "никто":
            записать_отказ(автор.get("username"), автор.get("id"))
            в_журнал(f"ОТКАЗ: отпечаток {отпечаток(автор.get('id'))}")
        return

    запомнить(автор.get("id"), роль, автор.get("username") or "")

    текст = str(сообщение.get("text") or "").strip()
    команда = текст.split()[0].lower().split("@")[0] if текст else ""
    хвост = текст[len(команда):].strip() if команда.startswith("/") else ""

    # ── Управление другими ботами ─────────────────────────────────────────
    # Здесь только для тех, кто в белом списке: проверка роли выше.
    if команда.startswith("/") and команда in УПРАВЛЕНИЕ_КОМАНДЫ:
        сказать(токен, чат, выполнить_управление(команда, хвост, автор,
                                                  роль, чат))
        return

    if подписчик() == 0:
        записать_подписчика(чат)
        в_журнал(f"ПОДПИСЧИК {чат}")
        сказать(токен, чат, ПРИВЕТ)

    if команда in ("/старт", "/start", "/помощь", "/help"):
        сказать(токен, чат, ПОМОЩЬ)
        return
    if команда in ("/статус", "/проверить"):
        сказать(токен, чат, СТАТУС.format(ждёт=сколько_ждёт()))
        return
    if команда == "/отписаться":
        try:
            ПОДПИСЧИК.unlink()
        except OSError:
            pass
        сказать(токен, чат, ОТПИСКА)
        return

    голос = сообщение.get("voice") or сообщение.get("audio")
    документ = сообщение.get("document")
    if документ and not голос:
        mime = str(документ.get("mime_type") or "")
        if mime.startswith("audio/"):
            голос = документ

    if голос:
        file_id = голос.get("file_id")
        if not file_id:
            сказать(токен, чат, ПРОБЛЕМА.format(причина="не понял аудио"))
            return
        сказать(токен, чат, "Слушаю…")
        try:
            имя, звук = скачать(токен, file_id)
            расшифровка = распознать(имя, звук)
        except ОшибкаTelegram as e:
            сказать(токен, чат, ПРОБЛЕМА.format(причина=str(e)))
            return
        положить(расшифровка, f"голосовое {голос.get('duration', 0)} с")
        сказать(токен, чат, ПРИНЯТО)
        # Голосовое от сотрудника — это доклад владельцу. Доклад
        # озвучивается голосом того же пола; если пол не назначен,
        # остаётся текстом, и это сказано прямо, а не молча.
        сказать(токен, чат, отправить_в_доклад(
            расшифровка, автор, роль))
        return

    if текст and not команда.startswith("/"):
        положить(текст, "текст")
        сказать(токен, чат, ПРИНЯТО)
        return

    сказать(токен, чат, НЕ_ГОЛОС)


