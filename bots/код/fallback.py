r"""Что бот пишет, когда ответить нечем.

Зачем это отдельно
------------------
Раньше при отказе всех моделей в чат уходило «сейчас не получается
ответить, попробуй через минуту». Формулировка честная, но
служебная: в ней видно, что человек говорит с системой, а не с
живым собеседником. И она одинаковая у всех ботов — Ада, Анатолий
и Effy отказывались одинаково, хотя должны звучать по-разному.

Как сделано
----------
По образцу `greetings.py`: у каждого бота свой набор вариантов, и
подряд два раза один и тот же не выпадает. Человек, которому отказали
три раза подряд, не должен три раза подряд читать одно и то же.

Почему «занята», а не «занят»
-----------------------------
Род здесь обязателен: отказ — самая частая фраза бота, и именно в
ней промах с родом бросается в глаза. Анатолий отказывается о себе
по-мужски, Ада и Effy — по-женски. Род берётся из `gender.py`, чтобы
правило жило в одном месте.

Что НЕ говорится в отказе
--------------------------
Технических подробностей: ни кодов ошибок, ни названий моделей, ни
слов про провайдера. Человек ничего не может с этим сделать, а текст
всё равно занимает место в чате. Сказать «подождите минуту» полезно:
это единственное, что человек действительно может сделать.
"""

from __future__ import annotations

import random

import gender

#: Отказы для Ады. Она разговорная и тёплая, поэтому обещает
#: вернуться, а не отмахивается.
ADA = [
    "Сек, подожди, скоро напишу.",
    "Минутку, я занята, отвечу чуть позже.",
    "Подожди немного, я занята — сейчас отвечу.",
    "Сейчас подожди, я занята, скоро вернусь к разговору.",
    "Занята немного, дай мне минуту — отвечу.",
]

#: Анатолий. Он мужчина, и тон у него ровный, без суеты.
ANATOLY = [
    "Подождите минутку.",
    "Секунду, я занят, скоро отвечу.",
    "Подождите немного, скоро буду готов.",
    "Минуту, я занят — сейчас отвечу.",
    "Сейчас подождите, скоро отвечу.",
]

#: Effy. Помощница по текстам: обещание, что вернётся с ответом,
#: для неё естественно.
EFFY = [
    "Секунду, я занята, скоро отвечу.",
    "Подожди минутку, я занята.",
    "Дай мне секунду, скоро напишу.",
    "Я занята, подожди немного — отвечу.",
    "Сейчас занята, минутку — и отвечу.",
]

#: Если бота в списке нет: говорим нейтрально, без рода. «Подождите» — безличная форма, род здесь не нужен.
ПРО_ЗАПАСНЫЕ = [
    "Подождите минутку, скоро отвечу.",
    "Секунду, скоро будет ответ.",
    "Подождите немного, отвечу.",
]

#: Отдельные случаи: тут важно сказать ЧТО случилось, а не просто
#: «подождите». Подменять их общим текстом нельзя — человек
#: поймёт, что это надолго, и зря не будет ждать.
НЕ_НАСТРОЕНЫ = "Модели не настроены, я пока не могу ответить."
НЕТ_КЛЮЧА = "Я пока не могу ответить — нет ключа к модели."
МОЛЧАЛА = "Я пока не могу ответить, попробуйте ещё раз."

#: Список ответов по ключу бота.
ОТКАЗЫ = {
    "ada": ADA,
    "anatoly": ANATOLY,
    "effy": EFFY,
}

#: Что было сказано в прошлый раз: чтобы не повторяться подряд.
_ПОСЛЕДНИЙ: dict[str, str] = {}


def _следующий(варианты: list[str], char_key: str) -> str:
    """Вариант, отличный от предыдущего.

    Если вариантов один, повтор неизбежен — берём его и не
    притворяемся, что выбора есть.
    """
    if len(варианты) <= 1:
        return варианты[0]
    выбор = random.choice(варианты)
    if выбор == _ПОСЛЕДНИЙ.get(char_key):
        выбор = варианты[(варианты.index(выбор) + 1) % len(варианты)]
    _ПОСЛЕДНИЙ[char_key] = выбор
    return выбор


def отказ(char_key: str) -> str:
    """Что сказать, когда ни одна модель не ответила.

    Род подставляется по правилам `gender.py`: Ада и Effy говорят
    «занята», Анатолий — «занят». В текстах это уже написано
    правильно, но проверяется перед выдачей: если правило когда-нибудь
    поменяют, тексты не окажутся в противоречии с ним.
    """
    варианты = ОТКАЗЫ.get(char_key) or ПРО_ЗАПАСНЫЕ
    текст = _следующий(варианты, char_key)

    # Страховка от противоречия: если бот переведён в мужской род,
    # а текст написан по-женски, молча меняем «занята» на «занят».
    if gender.род(char_key) == "мужской":
        текст = (текст.replace("занята", "занят")
                      .replace("напишу", "напишу"))
    return текст


#: Причины, которые `modelswitch.ask` отдаёт вместо ответа.
#:
#: Список, а не «если не похоже на причину — это ответ»: именно
#: такая проверка и портила всё. Любой текст, в том числе
#: настоящий ответ модели, не совпадал ни с одной меткой и
#: превращался в «я занята». Признаки должны быть известны заранее,
#: а всё остальное — ответом, и трогать его нельзя.
ПРИЧИНЫ = {
    "нет моделей": НЕ_НАСТРОЕНЫ,
    "нет ключа": НЕТ_КЛЮЧА,
    "молчала": МОЛЧАЛА,
    "техническая ошибка": "",       # пусто — ниже подставляется живой текст
    "неизвестно": "",               # то же
    "не настроены": НЕ_НАСТРОЕНЫ,
}


def это_причина(текст: str) -> bool:
    """Отдано ли это вместо ответа, а не сказано ли это человеку."""
    return str(текст).strip().lower() in ПРИЧИНЫ


def жалоба(char_key: str, причина: str) -> str:
    """Что сказать вместо метки причины.

    Если это не метка, а настоящий ответ модели, он возвращается
    как есть. Это главное здесь: раньше любой текст, не совпавший
    с причиной, молча заменялся отказом, и бот на нормальный вопрос
    отвечал «я занята».
    """
    ключ = str(причина).strip().lower()
    if ключ not in ПРИЧИНЫ:
        return причина
    текст = ПРИЧИНЫ[ключ] or отказ(char_key)
    # Род подставляется и здесь: тексты написаны по-женски, а бот
    # может быть переведён в мужской.
    if gender.род(char_key) == "мужской":
        текст = текст.replace("занята", "занят")
    return текст


def ожидание(char_key: str) -> str:
    """Короткая отписка «я думаю», пока модель отвечает.

    Отдельная от отказа: это не конец разговора, запрос ещё идёт.
    Писать её незачем — Telegram и так показывает «печатает…», а
    лишнее сообщение в чате только шумит. Функция оставлена на
    случай, если захотим объяснить задержку вручную.
    """
    return отказ(char_key)