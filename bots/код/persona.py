BAD_NAME_CHARS = re.compile(r"[^A-Za-z0-9_-]")


def safe_filename(name: str) -> str:
    """Имя файла аватара: только разрешённые символы.

    Токен сюда не попадает: имя собирается только из ключа лица. Но
    проверка всё равно нужна — ключ придёт из настроек, а настройки
    иногда правят руками и вместе с ними вносят точку с пробелом.
    """
    clean = BAD_NAME_CHARS.sub("", name).strip("_") or "avatar"
    return clean[:32] + ".png"


