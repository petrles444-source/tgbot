def _chunk(tag: bytes, data: bytes) -> bytes:
    """Один кусок PNG: длина, тип, содержимое, контрольная сумма."""
    body = tag + data
    return (struct.pack(">I", len(data)) + body
            + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF))


def avatar_png(persona: dict[str, object], size: int = 128) -> bytes:
    """Аватар лица: PNG без единой зависижки.

    Рисуется примитивами, а не шрифтом: текст в PNG пришлось бы тащить
    вместе с файлом шрифта, а круг с кольцом узнаётся и без букв.
    """
    dark, accent = persona["colors"]           # type: ignore[misc]
    dark_rgb = tuple(int(dark[i:i + 2], 16) for i in (1, 3, 5))
    accent_rgb = tuple(int(accent[i:i + 2], 16) for i in (1, 3, 5))
    # Угол узора — из ключа, чтобы аватар был узнаваем и не менялся
    # от запуска к запуску.
    seed = sum(ord(ch) for ch in str(persona["key"]))
    bars = 3 + seed % 4
    ring = size * (0.18 + (seed % 3) * 0.06)

    rows = bytearray()
    for y in range(size):
        rows.append(0)                        # фильтр строки: «None»
        for x in range(size):
            dx = x - size / 2 + 0.5
            dy = y - size / 2 + 0.5
            distance = (dx * dx + dy * dy) ** 0.5
            # Диагональные полосы как фон, кольцо — как знак.
            stripe = ((x + y) // max(2, size // bars)) % 2
            if ring <= distance <= ring + max(2, size // 12):
                rows.extend(accent_rgb)
            elif distance <= ring * 0.34:
                rows.extend(accent_rgb)
            else:
                shade = 0.75 if stripe else 1.0
                rows.extend(int(c * shade) for c in dark_rgb)

    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", header)
            + _chunk(b"IDAT", zlib.compress(bytes(rows), 9))
            + _chunk(b"IEND", b""))


def profile_photo_request(token: str, photo: bytes,
                          persona: dict[str, object]) -> tuple[str, bytes,
                                                              dict[str, str]]:
    """Адрес, тело и заголовки для смены аватара бота.

    Telegram принимает `multipart/form-data`, а библиотеки для этого в
    проекте нет: файл небольшой, и тело собирается напрямую. Токен уходит
    в адрес, а не в имя файла внутри тела — иначе он осел бы в мусорных
    дампах и логах на стороне сервера.
    """
    # Граница берётся из содержимого фото, а не из времени: одинаковое
    # фото даёт одинаковую границу, и это удобно при проверках.
    digest = zlib.crc32(photo) & 0xFFFFFFFF
    boundary = f"zagent{digest:08x}"
    # Имя файла — из ключа лица, а не жёсткое: у каждого бота своё имя,
    # и по нему видно в логах, чей это аватар.
    filename = safe_filename(str(persona["key"]))
    body = bytearray()
    body += f"--{boundary}\r\n".encode()
    body += (f'Content-Disposition: form-data; name="photo"; '
             f'filename="{filename}"\r\n').encode()
    body += b"Content-Type: image/png\r\n\r\n"
    body += photo
    body += f"\r\n--{boundary}--\r\n".encode()
    headers = {
        "Content-Type": f"multipart/form-data; boundary={boundary}",
        "Content-Length": str(len(body)),
    }
    # Именно `setMyProfilePic`, а не `setUserProfilePhoto`.
    #
    # Второй метод меняет аватар у обычного пользователя, и для токена
    # бота он не существует — Telegram отвечает 404. Именно этим
    # объяснялась строка `аватар не поставился: HTTP Error 404`, которую
    # видели при запуске все три бота: дело было не в персоне и не в
    # картинке, а в названии метода. У первого это проверялось на всех
    # трёх токенах, и 404 повторился одинаково — значит причина в коде,
    # а не в данных.
    url = f"https://api.telegram.org/bot{token}/setMyProfilePic"
    return url, bytes(body), headers


