def style_note() -> str:
    """Правило про иностранные слова вместе с готовым примером формата.

    Отдельной строкой, а не внутри STYLE: это не про тон, а про разбор
    слов, и проверяется оно иначе — по наличию скобки с
    произношением, а не по длине ответа.
    """
    return ("Иностранные слова: любое иностранное слово бери в кавычки "
            "и тут же разбери по трём пунктам — как читается, что "
            "значит, зачем оно здесь. Формат: «deploy» [дипло́й] — "
            "выложить файлы на сервере; здесь: файлы становятся доступны "
            "снаружи. Русские слова в кавычки не бери.")


