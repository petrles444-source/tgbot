r"""Общий голос помощников: имена, аватары и правила речи.

Зачем этот файл
---------------
Ада в телеграме, второй бот и помощник на сайте — три разных лица одного
проекта. Если правила речи написать в каждом файле отдельно, через месяц
они разъедутся: один начнёт отвечать коротко, другой — длинно, и
посетитель сайта получит не то, что человек в чате. Поэтому все общие
части лежат здесь, а боты только добавляют своё.

Уровни речи
-----------
Детализация 8 из 10 и научность 6 из 10 — это не украшение, а две разные
шкалы, и их легко перепутать:

* **детализация** — насколько полно раскрыт ответ. Восемь: есть суть,
  есть «почему», есть «как проверить», но без второй страницы мелочей.
* **научность** — насколько строгие термины и оговорки. Шесть: механизм
  называется своими именами, границы применимости проговариваются,
  но без ссылок на статьи и без формул ради впечатления.

Детализация отвечает за «сколько», научность — за «насколько строго».
Их можно менять независимо, поэтому в коде это две отдельные
константы, а не одно «качество ответа».

Иностранные слова
-----------------
Правило: любое иностранное слово берётся в кавычки и тут же
разбирается по трём пунктам — как читается, что значит, зачем здесь.
Правило не выполняется само: модель иногда забывает про него, поэтому
в `glossary_note` лежит проверка, а в подсказке — готовый формат.

Запуск модуля напрямую ничего не делает: это библиотека, а не программа.
"""
