def pick_persona(exclude: str | None = None,
                 rng: random.Random | None = None) -> dict[str, object]:
    """Выбрать лицо, не повторив `exclude`.

    Повтор при выборе ловится честно, а не через `random.choice` на весь
    список: если человек перезагрузит страницу несколько раз подряд,
    одно и то же имя выпадать не должно.
    """
    source = rng or random
    pool = [p for p in PERSONAS if p["key"] != exclude]
    return source.choice(pool)


def persona_by_key(key: str) -> dict[str, object] | None:
    """Лицо по ключу. None — такого ключа нет."""
    for item in PERSONAS:
        if item["key"] == key:
            return item
    return None


def persona_header(persona: dict[str, object]) -> str:
    """Строка представления: имя, роль и голос."""
    return (f"Меня зовут {persona['name']}. Я — {persona['role']}, "
            f"говорю {persona['voice']}.")


