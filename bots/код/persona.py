def glossary_note(text: str) -> list[str]:
    """Найти в тексте иностранные слова, которым не хватает разбора.

    Возвращает готовые строки только для тех слов, что встретились без
    кавычек или без скобки с произношением. Уже разобранные слова не
    трогаются: дописывать разбор к готовому объяснению — значит
    продублировать его и испортить вид ответа.
    """
    notes: list[str] = []
    for word, meaning in GLOSSARY.items():
        # Граница слова задаётся классом `\w`, а не диапазоном кириллицы
        # вида `[А-Яа-я]`. Диапазон в регулярке приводит к `bad character
        # range` и роняет импорт всего модуля: сначала ловит не ту букву,
        # потом не компилируется вовсе. Здесь буквы не перечисляются
        # вручную, и потому ломаться нечему.
        pattern = re.compile(rf"(?<!\w){re.escape(word)}(?!\w)",
                             re.IGNORECASE)
        match = pattern.search(text)
        if not match:
            continue
        # Разбор считается сделанным, если рядом со словом уже стоят
        # кавычки или квадратные скобки с произношением.
        window = text[max(0, match.start() - 2):match.end() + 40]
        if "«" in window or "[" in window:
            continue
        notes.append(f"«{word}» {meaning}")
    return notes


def strip_glossary_for_reply(text: str) -> str:
    """Убрать служебные пометки, если модель их всё-таки написала."""
    return re.sub(r"\n{3,}", "\n\n", text).strip()


