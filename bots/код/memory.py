r"""Память: что бот помнит о собеседнике, и как это попадает в запрос.

Зачем
----
Бот держал в памяти 12 последних сообщений и ничего больше. Закрыли
консоль — и он забыл всё, включая имя человека. Со стороны это
выглядит так, будто его не помнят, и никакая модель тут не поможет:
забывшего собеседника не спасёт длинный контекст.

Увеличение контекста не решение
-------------------------------
Больше сообщений в промпте — медленнее и дороже на каждом запросе.
Правильный путь другой: помнить **много**, но отправлять модели
**мало** — только то, что относится к текущему вопросу.

Что здесь три вещи
------------------
1. `remember()` — выбрать, что стоит запомнить, и записать на диск.
2. `recall()` — выбрать из памяти то, что относится к вопросу.
3. `summary()` — короткая выжимка из старых сообщений.

Почему память своя у каждого бота
---------------------------------
Так решил человек. И это верно: Ада не должна помнить то, что
человек рассказал Анатолию про код. Файлы лежат в отдельных папках
`память/<бота>/<чат>.md`, и один бот не видит память другого.

Почему без обращения к модели
----------------------------
Вытаскивать факты отдельным запросом к модели стоило бы второго
обращения на каждое сообщение — вдвое больше времени и квоты. Здесь
всё делается словами на Python: файлы маленькие, и обычный поиск по
ним быстрее и надёжнее, чем запрос за 0,3 с.

Как это попадает в запрос
-------------------------
В модель уходит не вся память, а три-пять строк. Проверено на
скорости: пять коротких строк не ощущаются, вся память чата —
ощущалась бы.
"""

from __future__ import annotations

import json
import re
import time
from pathlib import Path
from typing import Any

#: Где хранится память. Папка внутри проекта, рядом с кодом.
MEMORY_ROOT = Path(__file__).resolve().parent.parent / "память"

#: Сколько фактов о человеке держим. Больше — уже не память о
#: человеке, а архив разговора, и он начинает мешать.
MAX_FACTS = 60

#: Сколько строк выжимки отдаём в запрос. Три-четыре — достаточно,
#: чтобы модель понимала, о ком речь, не читая историю целиком.
RECALL_LINES = 4

#: Сколько символов занимает одна запись. Длинные фразы в памяти
#: не нужны: нужны факты.
FACT_LIMIT = 200

#: Слова, после которых в сообщении что-то говорят о человеке.
#: Не «слова-ключи» в строгом смысле, а признаки личных фактов.
_PERSONAL = (
    "меня зовут", "моё имя", "я работаю", "работаю в", "я живу",
    "мне нравится", "я люблю", "я не люблю", "ненавижу", "боюсь",
    "мечтаю", "хочу научиться", "учусь", "изучаю", "у меня есть",
    "у меня нет", "я делаю", "моя цель", "я привык", "я обычно",
    "зовут", "работа", "проект", "задача", "проблема", "дедлайн",
)

#: Слова, по которым ищем в памяти при ответе на вопрос.
_STOP = {
    "это", "как", "ты", "вы", "мне", "меня", "что", "для", "про",
    "но", "или", "если", "когда", "чтобы", "the", "and", "you",
    "your", "was", "were", "have", "has", "чтобы", "можешь", "может",
    "сделай", "напиши", "скажи", "ответь", "помоги", "давай", "если",
    "привет", "здравствуй", "спасибо", "пока", "хорошо", "ок",
}


def _words(text: str) -> set[str]:
    """Значимые слова текста: длиннее трёх, не стоп-слова."""
    return {
        w for w in re.findall(r"[а-яёa-z0-9]{4,}", str(text).lower())
        if w not in _STOP
    }


#: Начало сообщения, после которого это вопрос, а не факт.
#:
#: Слова-признаки личных фактов ловят и вопросы: в «а что я делаю»
#: есть «делаю». Без этой проверки память забивалась вопросами, и
#: через месяц настоящие факты тонули бы среди «а зачем», «а почему».
_QUESTION_START = (
    "а ", "а-то", "а если", "а как", "а что", "а где", "а когда",
    "что ", "как ", "почему", "зачем", "кто ", "где ", "когда ",
    "который", "сколько", "можно ", "нужно ", "ты ", "вы ",
    "а ты", "а вы", "а он", "а она",
)


#: Глаголы, по которым узнаётся факт о человеке.
#:
#: Перечисление выше конечно и всегда будет кого-то пропускать:
#: человек сказал «вчера купил велосипед», а слова «купил» в списке
#: нет, и фраза молча не запомнилась. Перечисление расширено до
#: основных глаголов прошедшего и будущего времени.
_VERB_MARKS = (
    "купил", "куплю", "написал", "напишу", "сделал", "сделаю",
    "работаю", "работал", "делаю", "делал", "хочу", "планирую",
    "учусь", "учился", "изучаю", "изучал", "живу", "жил",
    "понимаю", "понял", "знаю", "знал", "умею", "смог", "смогла",
    "пробую", "пробовал", "ищу", "искал", "жду", "ждал",
    "переехал", "переехала", "поменял", "начал", "начала",
    "закончил", "закончила", "поставил", "настроил", "создал",
    "делаю это", "над этим", "по этой", "по этому",
)


def _looks_like_statement(text: str) -> bool:
    """Фраза о человеке: есть действие, а не просто слово.

    Запасная проверка рядом с перечислением. Перечисление конечно и
    всегда пропустит чью-то фразу: человек сказал «вчера купил
    велосипед», а слова «купил» в списке признаков нет, и фраза молча
    не запомнилась — человек решил бы, что его не слушают.

    Требовать «я» в начале нельзя: человек говорит «вчера купил
    велосипед», а не «я вчера купил велосипед». Признак действия
    работает на целый класс фраз и потому не устаревает, в отличие
    от перечисления слов.
    """
    low = str(text).strip().lower()
    for mark in _VERB_MARKS:
        if mark in low:
            return True
    return False

#: Реакции на реплику, а не сведения о человеке.
#:
#: Проверка на глагол ловит и междометия: в «ага, понял» есть
#: «понял», и фраза проходила как факт. Междометия короткие и почти
#: всегда без содержания, поэтому их проще отсечь по началу фразы.
_INTERJECTIONS = (
    "ага", "ага ", "ок", "окей", "угу", "угу ", "да ", "нет ",
    "нет, ", "неа", "хм", "хмм", "ой", "эм", "понял", "поняла",
    "понятно", "ясно", "верно", "точно", "хорошо", "ладно", "согласен",
)


def _is_interjection(text: str) -> bool:
    """Реакция на реплику, а не факт о человеке."""
    low = str(text).strip().lower()
    return low.startswith(_INTERJECTIONS)

def _is_question(text: str) -> bool:
    """Похоже ли сообщение на вопрос, а не на факт о человеке."""
    low = str(text).strip().lower()
    if not low:
        return True
    # Знак вопроса — самый надёжный признак.
    if "?" in low:
        return True
    return low.startswith(_QUESTION_START)


def path_for(char_key: str, chat_id: int) -> Path:
    """Файл памяти конкретного бота и конкретного человека.

    Отдельный файл на бота: память Ады не должна попасть в Анатолия,
    даже когда они в одном чате.
    """
    return MEMORY_ROOT / str(char_key) / f"{int(chat_id)}.json"


def load(char_key: str, chat_id: int) -> dict[str, Any]:
    """Прочитать память. Пустая структура, если её нет.

    Битый файл не считается поломкой: человек ничего не теряет,
    кроме накопленного, а бот продолжает работать.
    """
    path = path_for(char_key, chat_id)
    if not path.is_file():
        return {"facts": [], "summary": "", "turns": 0}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return {"facts": [], "summary": "", "turns": 0}
    if not isinstance(data, dict):
        return {"facts": [], "summary": "", "turns": 0}
    data.setdefault("facts", [])
    data.setdefault("summary", "")
    data.setdefault("turns", 0)
    return data


def save(char_key: str, chat_id: int, data: dict[str, Any]) -> None:
    """Записать память. Ошибка записи не должна ронять бота."""
    path = path_for(char_key, chat_id)
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=1)[:200_000],
            encoding="utf-8")
    except OSError:
        pass


def remember(char_key: str, chat_id: int, text: str,
             sender: str = "") -> bool:
    """Запомнить, что в сообщении было сказано о человеке.

    Запоминается не всё подряд: только то, где есть признак
    личного факта. Иначе память забивается «ок» и «спасибо», и
    через месяц полезного в ней не останется.
    """
    text = str(text or "").strip()
    if not text or len(text) > FACT_LIMIT * 2:
        return False
    # Вопрос — не факт. «а что я делаю» содержит «делаю», и без
    # этой проверки память забивалась бы вопросами, вытесняя
    # настоящие сведения о человеке. Проверка идёт **до** отсева по
    # признакам: иначе фраза «а что я делаю?» ушла бы в память
    # раньше, чем успеет сюда дойти.
    if _is_question(text):
        return False
    if _is_interjection(text):
        return False
    low = text.lower()
    # Признак личного факта. Список конечен и кого-то всегда
    # пропустит, поэтому следом идёт проверка по форме фразы, а
    # не один только перебор слов.
    if not any(word in low for word in _PERSONAL) \
            and not _looks_like_statement(text):
        return False

    data = load(char_key, chat_id)
    fact = f"{sender}: {text}" if sender else text
    facts = data["facts"]
    # Дубли не копим: человек повторил то же самое — не новый факт.
    if any(existing == fact for existing in facts):
        return False
    facts.append(fact[:FACT_LIMIT])
    if len(facts) > MAX_FACTS:
        del facts[:len(facts) - MAX_FACTS]
    save(char_key, chat_id, data)
    return True


def recall(char_key: str, chat_id: int, question: str) -> list[str]:
    """Что из памяти относится к вопросу.

    Возвращает несколько строк, а не всю память: в запрос уходит
    только релевантное. Иначе память станет тем самым огромным
    контекстом, от которого мы уходили.
    """
    facts = load(char_key, chat_id).get("facts") or []
    if not facts:
        return []

    wanted = _words(question)
    if not wanted:
        # Вопрос из одних стоп-слов: берём последнее, что помним, но
        # именно несколько строк. Одна строка не даёт модели понять,
        # кто перед ней, и память перестаёт работать.
        return facts[-RECALL_LINES:]

    scored: list[tuple[int, str]] = []
    for fact in facts:
        overlap = len(wanted & _words(fact))
        if overlap:
            scored.append((overlap, fact))
    if not scored:
        return facts[-RECALL_LINES:]

    # Порядок в памяти хронологический. При равной релевантности
    # свежее важнее, поэтому сортируем по оценке, а внутри оценки
    # берём хвост — последнее сказанное.
    scored.sort(key=lambda row: row[0])
    chosen = [fact for _, fact in scored[-RECALL_LINES:]]
    return chosen


def summary_line(char_key: str, chat_id: int) -> str:
    """Строка о собеседнике для подсказки. Пустая, если нечего."""
    data = load(char_key, chat_id)
    parts = []
    if data.get("summary"):
        parts.append(str(data["summary"]))
    return " ".join(parts)


def update_summary(char_key: str, chat_id: int, text: str,
                   sender: str = "") -> None:
    """Обновить выжимку: последние сказанные о себе факты.

    Выжимка короткая намеренно. Она попадает в каждый запрос, и
    раздувать её нельзя: это ровно тот огромный контекст, которого
    мы избегаем.
    """
    text = str(text or "").strip()
    if not text:
        return
    data = load(char_key, chat_id)
    current = str(data.get("summary") or "")

    # Короткая выжимка: что человек сказал о себе, одной строкой.
    addition = f"{sender}: {text}" if sender else text
    addition = addition[:160]
    if addition in current:
        return

    # Держим две последние реплики-факта: больше не нужно, остальное
    # лежит в фактах и достаётся по запросу.
    kept = [part.strip() for part in current.split(" | ") if part.strip()]
    kept.append(addition)
    data["summary"] = " | ".join(kept[-2:])
    data["turns"] = int(data.get("turns") or 0) + 1
    save(char_key, chat_id, data)


def forget(char_key: str, chat_id: int) -> None:
    """Забыть всё о этом человеке."""
    path = path_for(char_key, chat_id)
    try:
        path.unlink()
    except OSError:
        pass


def memory_note(char_key: str, chat_id: int, question: str) -> str:
    """Готовая строка для подсказки модели. Пустая, если нечего."""
    lines = recall(char_key, chat_id, question)
    head = summary_line(char_key, chat_id)
    if head:
        lines = [head] + lines
    if not lines:
        return ""
    return ("ЧТО Я ПОМНЮ ОБ ЭТОМ ЧЕЛОВЕКЕ (мои собственные записи, "
            "не выдумки):\n" + "\n".join(f"— {line}" for line in lines))