r"""Общие настройки тестов: чистое состояние перед каждым тестом.

Зачем этот файл
---------------
Тесты грузят `ada_bot` и `linda_bot` как модули **дважды**: один
файл тестов свой экземпляр, другой — свой. При этом все экземпляры
пишут в общий `sys.modules`, поэтому подмена, сделанная одним
файлом, видна другому, а память о неудачных попытках — тем более.

Из-за этого тесты зависели от порядка запуска: поодиночке проходили,
а вместе падали. Здесь состояние сбрасывается перед каждым тестом,
и порядок перестаёт влиять на результат.

Что именно сбрасывается
-----------------------
* `CHATS` и `OWN_ID` — состояние чатов между тестами;
* память о заблокированных моделях — один неудачный тест иначе
  банит модель на минуту, и после него «сейчас не получается
  ответить» получают все следующие;
* счётчик ротации ключей — по той же причине.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parent.parent
BOTS = ROOT / "bots" / "код"
if str(BOTS) not in sys.path:
    sys.path.insert(0, str(BOTS))


@pytest.fixture(autouse=True)
def reset_model_memory() -> None:
    """Чистое состояние перебора моделей перед каждым тестом.

    Три вещи, и каждая нужна:

    * **память о заблокированных моделях** — один неудачный тест иначе
      банит модель на минуту, и после него «сейчас не получается
      ответить» получают все следующие;
    * **счётчик ротации ключей** — по той же причине;
    * **тестовые ключи** — настоящие ключи лежат в файле вне git, и
      тестам незачем их читать с диска. Подставляется фиктивный ключ,
      чтобы перебор дошёл до модели: без ключа он честно
      возвращает «ключ не задан» и модель не зовёт.
    """
    import modelswitch

    modelswitch._BLOCKED_UNTIL.clear()
    modelswitch._KEY_ROTATION.clear()
    # Именно `KEYS`, а не подмена функции: ключи нужны там, где
    # берутся по-настоящему, иначе тест проверял бы не тот путь.
    modelswitch.KEYS.clear()
    modelswitch.KEYS["p"] = ["тест-ключ"]