#!/usr/bin/env bash
# Прочитать, что владелец наговорил в голосовые.
#
#   что-нового              показать непрочитанное и снять отметку
#   что-нового --peek       показать, НЕ снимая отметку
#   что-нового --count      сколько всего ждёт
#
# ПОЧЕМУ СНЯТИЕ ОТМЕТКИ
# --------------------
# Очередь — это мои входящие. Если отметку не снимать, я буду
# перечитывать одно и то же сообщение при каждом заходе на сервер,
# и в ответе начнёт повторяться то, что уже разобрано. Снял — значит
# прочитал. `--peek` существует как раз для того, чтобы глянуть и
# решить, читаю я это сейчас или нет.
#
# ПОЧЕМУ БЕЗ КИРИЛЛИЦЫ В ИМЕНАХ
# ----------------------------
# Bash не признаёт кириллицу в именах переменных: `local список`
# он считает командой и отвечает «not a valid identifier». Русскими
# остаются комментарии и вывод. Первая версия этого скрипта с таким
# именем падала сразу при первом же чтении очереди.

set -euo pipefail

DIR=/opt/bots/sdc
INBOX=/var/lib/sdc/входящие

peek() {
    ls "$INBOX"/*.txt 2>/dev/null | sort || true
}

show() {
    local files
    files=$(peek)
    if [ -z "$files" ]; then
        echo "очередь пуста — непрочитанного нет"
        return 0
    fi
    echo "=== ЧТО НАГОВОРИЛ ЛЕВ (${INBOX}) ==="
    local count=0
    for f in $files; do
        count=$((count + 1))
        echo
        echo "--- сообщение $count: $(basename "$f") ---"
        cat "$f"
    done
    echo
    echo "=== всего сообщений: $count ==="
}

case "${1:-}" in
    --peek)
        show
        echo
        echo "отметка НЕ снята — прочитаю это ещё раз"
        ;;
    --count)
        echo "ждут: $(peek | wc -l)"
        ;;
    -h|--помощь)
        echo "  что-нового            показать и снять отметку"
        echo "  что-нового --peek     показать, не снимая"
        echo "  что-нового --count    сколько ждёт"
        ;;
    *)
        # Показ до снятия: если снять раньше, а вывод не удался —
        # сообщение потерялось бы молча.
        show
        if [ -n "$(peek)" ]; then
            rm -f "$INBOX"/*.txt
            echo
            echo "отметка снята — считаю, что прочитал"
        fi
        ;;
esac