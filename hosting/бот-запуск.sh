#!/usr/bin/env bash
# Обёртка запуска одного бота. Её зовёт служба systemd.
#
# ЗАЧЕМ ОБЁРТКА, А НЕ EnvironmentFile В ЮНИТЕ
# -------------------------------------------
# EnvironmentFile потребовал бы второй копии токена — рядом с тем
# файлом, где лежит настоящий. Две копии одного секрета расходятся:
# при перевыпуске обновят одну, вторую забудут, и бот молча перестанет
# отвечать на «поменяй токен». Обёртка читает единственный файл и
# подставляет токен в переменную окружения в момент старта, так что
# копия всегда одна и всегда свежая.
#
# ЧТО ЗДЕСЬ ЕЩЁ ПРОВЕРЯЕТСЯ
# ------------------------
# Токен без ведущей части «число:» — это не токен, а опечатка. Такое
# случается, если файл положили с кавычками или с подписью. Бот в
# этом случае стартует и молчит, а человек думает, что сломалось
# что-то другое. Поэтому проверяем вид и отказываем сразу, с текстом.

set -euo pipefail

BOT=${1:-}
SECRETS=/etc/sora/bots
ROOT=/opt/bots

case "$BOT" in
    ada|anatoly|effy) ;;
    *) echo "бот-запуск: имя должно быть ada, anatoly или effy" >&2; exit 1 ;;
esac

TOKEN_FILE=$SECRETS/$BOT.token
DIR=$ROOT/$BOT

[ -d "$DIR" ] || { echo "нет кода бота: $DIR" >&2; exit 1; }
[ -f "$TOKEN_FILE" ] || {
    echo "нет токена: $TOKEN_FILE" >&2
    echo "положить: /usr/local/bin/бот-токен $BOT <токен>" >&2
    exit 1
}

TOKEN=$(tr -d '\r\n' < "$TOKEN_FILE")

# Проверка вида. Кавычки вокруг токена — самая частая ошибка при
# копировании, и снаружи они не видны: файл выглядит занятым.
case "$TOKEN" in
    [0-9]*:[A-Za-z0-9_-]*) : ;;
    *)
        echo "токен в $TOKEN_FILE не похож на настоящий" >&2
        echo "возможно, вокруг него кавычки или пробелы" >&2
        exit 1
        ;;
esac

export TELEGRAM_TOKEN="$TOKEN"
export PYTHONUNBUFFERED=1
export PYTHONPATH="$DIR"

cd "$DIR"
exec python3 ada_bot.py