#!/usr/bin/env bash
# Отправить владельцу срочное сообщение через SDC.
#
#   уведомить "Текст сообщения"
#   уведомить -ф /tmp/текст.txt
#   уведомить --проверка          спросить, дошло ли, и показать статус
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ СКРИПТ, А НЕ ПРОСТО КОМАНДА
# --------------------------------------------
# Токен лежит в файле с правами 600, и класть его в командную строку
# нельзя: он останется в истории оболочки. Здесь он читается внутри
# python и в аргументах не светится.
#
# ПОЧЕМУ БЕЗ КИРИЛЛИЦЫ В ИМЕНАХ
# ----------------------------
# Bash не признаёт кириллицу в именах переменных: `ТЕКСТ=привет` он
# выполнит как команду. Русскими остаются комментарии и вывод.

set -euo pipefail

DIR=/opt/bots/sdc
LOG=/var/log/bots/sdc.log

usage() {
    echo "Как пользоваться:"
    echo "  уведомить \"текст\"          отправить это сообщение"
    echo "  уведомить -ф файл.txt       отправить содержимое файла"
    echo "  уведомить --проверка        показать статус, ничего не отправляя"
}

if [ $# -eq 0 ]; then
    usage
    exit 1
fi

cd "$DIR"

case "$1" in
    --проверка)
        python3 sdc.py --проверить-токен
        echo "  подписчик: $(cat /var/lib/sdc/подписчик.json 2>/dev/null || echo 'ещё не подписан')"
        echo "  ждут в очереди: $(ls /var/lib/sdc/входящие/*.txt 2>/dev/null | wc -l)"
        ;;
    -ф|--файл)
        if [ $# -lt 2 ]; then
            echo "нужен путь к файлу" >&2
            exit 1
        fi
        python3 sdc.py --уведомить "$(cat "$2")"
        ;;
    -h|--помощь)
        usage
        ;;
    *)
        python3 sdc.py --уведомить "$*"
        ;;
esac