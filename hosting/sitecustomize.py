"""Заставляет Python выбирать IPv4, а не IPv6.

ЗАЧЕМ
-----
На сервере есть адреса IPv6 и маршрут по умолчанию для них. По IPv6
пинг до Telegram идёт (44 мс), но **TCP по IPv6 наружу заблокирован**:
пакет SYN уходит, ответа нет, соединение не устанавливается никогда.
Проверено: `curl -6 https://api.telegram.org/` не соединяется, `curl -4`
работает за 0,18 с.

Python при разборе имени выбирает IPv6 первым, потому что у системы
есть рабочие адреса IPv6. Бот уходил в бесконечный `SYN-SENT`: процесс
жив, память на месте, `systemctl` говорит `active` — а бот при этом
молчал и не получал ни одного сообщения. Самое неприятное, что
выглядело как полная работоспособность.

ПОЧЕМУ ЗДЕСЬ, А НЕ В /etc/gai.conf
---------------------------------
`precedence ::ffff:0:0/96 100` в gai.conf решил бы задачу для всей
системы сразу. Но на этом же сервере крутится nginx с рабочим сайтом,
и менять порядок разрешения имён для всего подряд ради трёх ботов —
риск без нужды. Этот файл действует только на процессы, у которых в
`PYTHONPATH` лежит его папка, то есть ровно на наши боты.

ПОЧЕМУ ИМЕННО ТАК
------------------
Не «пробуем IPv6, потом откатываемся»: urllib не даёт контроля над
попытками, и обрыв по таймауту будет повторяться. Просто говорим
системе: когда имя разрешается для соединения, бери IPv4.
"""

import socket

_исходный_getaddrinfo = socket.getaddrinfo


def getaddrinfo(host, port, family=0, *args, **kwargs):
    """Как обычный, но IPv4 вместо IPv6, если не просили иначе.

    Явно запрошенный `AF_INET6` уважаем: если кто-то в коде really
    захотел IPv6, молча менять это нельзя.
    """
    if family == 0:
        family = socket.AF_INET
    return _исходный_getaddrinfo(host, port, family, *args, **kwargs)


socket.getaddrinfo = getaddrinfo