"""Пол, язык и отказы: то, что видно человеку сразу.

Три группы.

1. **Правило в подсказке.** Для Ады и Effy — женский род, для
   Анатолия — мужской, и ни одно правило не должно попасть к
   другому боту.
2. **Правка ответа.** Мужское «я» исправляется, а «ты» и цитаты
   не трогаются: пол собеседника и чужого человека тут не наш.
3. **Отказы.** Человечные, с правильным родом, и — главное — не
   съедающие настоящий ответ модели.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
BOTS = ROOT / "bots" / "код"
if str(BOTS) not in sys.path:
    sys.path.insert(0, str(BOTS))

import ada_bot  # noqa: E402
import chars  # noqa: E402
import fallback  # noqa: E402
import gender  # noqa: E402

FEMALE_BOTS = ["ada", "effy"]
MALE_BOTS = ["anatoly"]
ALL_BOTS = FEMALE_BOTS + MALE_BOTS


# ============================================ 1. правило в подсказке


@pytest.mark.parametrize("key", FEMALE_BOTS)
def test_женщины_получили_требование_о_женском_роде(key: str) -> None:
    """У Ады и Effy правило есть.

    У Adы оно было в начале подсказки, у Effy — нигде, и она
    отвечала как мужчина. Теперь правило одно и общее.
    """
    правило = gender.построить_правила(key)
    assert "ЖЕНЩИНА" in правило
    assert "женском роде" in правило


@pytest.mark.parametrize("key", FEMALE_BOTS)
def test_у_женщин_нет_мужского_требования(key: str) -> None:
    """Требования противоположного рода быть не должно.

    Иначе модель получит две взаимоисключающие инструкции и
    выберет ту, что напишет последней.
    """
    assert "МУЖЧИНА" not in gender.построить_правила(key)


def test_анатолий_мужчина() -> None:
    """У Анатолия обратное требование, и это намеренно."""
    правило = gender.построить_правила("anatoly")
    assert "МУЖЧИНА" in правило
    assert "ЖЕНЩИНА" not in правило


@pytest.mark.parametrize("key", ALL_BOTS)
def test_язык_русский_у_всех(key: str) -> None:
    """Каждый бот обязан отвечать по-русски."""
    assert "русском языке" in gender.построить_правила(key)


@pytest.mark.parametrize("key", ALL_BOTS)
def test_правило_реально_в_подсказке(key: str) -> None:
    """Правило не просто существует, а доходит до модели.

    Модуль может быть написан верно и при этом не подключён —
    тогда тесты на сам модуль зелёные, а бот по-прежнему отвечает
    как мужчина. Поэтому проверяем собранную подсказку.
    """
    подсказка = chars.prompt(key, 1)
    assert "ЖЕНЩИНА" in подсказка or "МУЖЧИНА" in подсказка, (
        f"у {key} в подсказке нет требования о роде")
    assert "русском языке" in подсказка, (
        f"у {key} в подсказке нет требования о языке")


def test_правило_в_конце_подсказки() -> None:
    """Род стоит последним, а не в начале.

    Модель сильнее всего влияет последнее прочитанное. Правило в
    начале задаёт роль, но к концу подсказки — за тысячи токенов
    до ответа — модель уже набирает текст и легче сбивается.
    """
    подсказка = chars.prompt("ada", 1).strip()
    хвост = подсказка[-160:]
    # Проверяем хвост, а не точное совпадение: `rstrip()` съедает
    # точку в конце, и проверка на `endswith("...ошибка.")`
    # падала бы на полностью верной подсказке.
    assert "английском — ошибка" in хвост, (
        f"правило о языке должно закрывать подсказку, а в хвосте: {хвост!r}")


# ================================================ 2. правка ответа


@pytest.mark.parametrize("было,стало", [
    ("Я сделал это.", "Я сделала это."),
    ("я решил помочь", "я решила помочь"),
    ("Я уверен в этом", "Я уверена в этом"),
    ("я готов помочь", "я готова помочь"),
    ("я объяснил", "я объяснила"),
    ("я помог", "я помогла"),
    ("я смог", "я смогла"),
])
def test_мужское_я_исправляется(было: str, стало: str) -> None:
    """Самое частое промахивание модели — «я» в мужском роде."""
    результат, правок = gender.поправить_род(было, "ada")
    assert результат == стало
    assert правок >= 1


@pytest.mark.parametrize("текст", [
    "Ты должен решить это сам.",
    "Вы должны ждать.",
    "Ты готов начать?",
])
def test_собеседник_не_переделывается(текст: str) -> None:
    """«Ты» — это человек, а не бот.

    Правило пола должно менять только то, что бот говорит о себе.
    Иначе бот переписывает то, что человек сказал сам себе.
    """
    результат, правок = gender.поправить_род(текст, "ada")
    assert результат == текст, f"испорчено: {текст!r} -> {результат!r}"
    assert правок == 0


@pytest.mark.parametrize("текст", [
    "Он объяснил задачу.",
    "Это было давно.",
    "Правило применяется ко всем.",
    "я должен был проверить",
])
def test_чужие_слова_не_трогаются(текст: str) -> None:
    """Цитаты и составные конструкции остаются как есть."""
    результат, правок = gender.поправить_род(текст, "ada")
    assert результат == текст


@pytest.mark.parametrize("key", MALE_BOTS)
def test_мужчине_правило_не_применяется(key: str) -> None:
    """Анатолий о себе говорит в мужском роде, и это правильно."""
    результат, правок = gender.поправить_род("Я сделал это.", key)
    assert результат == "Я сделал это."
    assert правок == 0


def test_пустой_ответ_не_ломает_правку() -> None:
    """Пустой ответ не должен давать исключение."""
    assert gender.поправить_род("", "ada") == ("", 0)


def test_уже_женский_род_не_трогается() -> None:
    """Правильный ответ не трогаем — лишних правок быть не должно."""
    результат, правок = gender.поправить_род("Я сделала это.", "ada")
    assert результат == "Я сделала это."
    assert правок == 0


# ====================================================== 3. отказы


@pytest.mark.parametrize("key", ALL_BOTS)
def test_отказ_не_пустой(key: str) -> None:
    """На отказ должен быть хоть какой-то текст."""
    assert fallback.отказ(key).strip()


@pytest.mark.parametrize("key", FEMALE_BOTS)
def test_отказ_женщины_по_женски(key: str) -> None:
    """«Занята», а не «занят».

    Отказ — самая частая фраза бота, и промах с родом в ней бросается
    в глаза сильнее всего.
    """
    for _ in range(10):
        текст = fallback.отказ(key)
        assert "занят" not in текст.lower().replace("занята", ""), (
            f"отказ по-мужски: {текст!r}")


def test_отказ_анатолия_по_мужски() -> None:
    """Обратная проверка: у Анатолия должно быть «занят»."""
    тексты = [fallback.отказ("anatoly") for _ in range(20)]
    assert any("занят" in т.lower() for т in тексты)


def test_отказ_не_повторяется_подряд() -> None:
    """Два одинаковых отказа подряд — это тоже раздражает.

    Как и с приветствиями: человек, которому отказали три раза
    подряд, не должен три раза читать одно и то же.
    """
    подряд = [fallback.отказ("ada") for _ in range(12)]
    for первое, второе in zip(подряд, подряд[1:]):
        assert первое != второе, f"повтор: {первое!r}"


def test_у_каждого_бота_свой_отказ() -> None:
    """Отказы не должны совпадать у разных ботов.

    Иначе три живых собеседника отказываются одинаково, и в чате
    видно, что это один код.
    """
    наборы = {key: {fallback.отказ(key) for _ in range(30)}
              for key in ALL_BOTS}
    ada, anatoly, effy = (наборы[k] for k in ALL_BOTS)
    assert ada and anatoly and effy
    assert not (ada & anatoly), "Ада и Анатолий говорят одно и то же"
    assert not (ada & effy), "Ада и Effy говорят одно и то же"
    assert not (anatoly & effy), "Анатолий и Effy говорят одно и то же"


def test_настоящий_ответ_не_съедается() -> None:
    """Главный тест этого модуля.

    Такая ошибка уже была: `жалоба()` превращала в отказ любой
    текст, не совпавший с меткой причины, — включая нормальный ответ
    модели. Бот на вопрос «что такое Ruffle» отвечал «я занята».
    """
    ответы = [
        "Ruffle — это компилятор Flash в WebAssembly.",
        "Да, конечно, вот подробности.",
        "Коротко: 42.",
    ]
    for ответ in ответы:
        assert fallback.жалоба("ada", ответ) == ответ
        assert not fallback.это_причина(ответ)


@pytest.mark.parametrize("причина", [
    "молчала", "нет ключа", "техническая ошибка", "неизвестно",
])
def test_метки_превращаются_в_текст(причина: str) -> None:
    """Метка от `modelswitch` — это не ответ, её надо заменить."""
    текст = fallback.жалоба("ada", причина)
    assert fallback.это_причина(причина)
    assert not fallback.это_причина(текст), f"метка утекла в чат: {текст!r}"
    assert текст.strip()


def test_в_отказе_нет_технических_слов() -> None:
    """Человек ничего не сделает с кодом ошибки.

    Значит, в отказе технических подробностей быть не должно:
    они только занимают место в чате.
    """
    for key in ALL_BOTS:
        for _ in range(20):
            текст = fallback.отказ(key).lower()
            for слово in ("http", "api", "key", "503", "timeout",
                          "provider", "провайдер", "токен"):
                assert слово not in текст, (
                    f"техническое слово «{слово}» в отказе {key}: {текст!r}")
