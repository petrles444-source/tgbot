"""Каждый файл базы знаний находится по своей теме.

Почему по одному тесту на файл
------------------------------
База знаний растёт по мере надобности, и на новый файл тест не
забывают написать. Тогда он лежит, называется как-то, и на вопрос
про него прилетает соседний: бот отвечает не тем, ошибки нет,
выглядит как «модель стала хуже». Тест на файл ловит это сразу.

Что именно проверяем
--------------------
1. По теме файла приходит именно он, а не сосед.
2. На междометии база молчит, сколько бы файлов ни было.
3. Заметка не выходит за лимит даже когда файлов много.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
BOTS = ROOT / "bots" / "код"
if str(BOTS) not in sys.path:
    sys.path.insert(0, str(BOTS))

import knowledge  # noqa: E402

CHAT = 424_242


@pytest.fixture(autouse=True)
def clear_cache() -> None:
    """Кэш чист: иначе тест зависит от порядка запуска."""
    knowledge._CACHE.clear()
    knowledge._ИНдекс.clear()
    knowledge._ИНдекс_время = 0.0


#: Вопрос — какой файл обязан прийти. Имя файла проверяется в ответе.
CASES = [
    ("что такое токен", "токен"),
    ("какие у вас команды", "/start"),
    ("как настроить характер", "характер"),
    ("почему пауза растёт", "пауза"),
    ("кто такая effy", "effy"),
    ("что умеет бот без нейросети", "арифметика"),
    ("какая модель первая", "groq"),
    ("сколько бот помнит", "факт"),
    ("что делает кнопка", "кнопк"),
]


@pytest.mark.parametrize("вопрос,ожидаем", CASES)
def test_файл_находится_по_своей_теме(вопрос: str, ожидаем: str) -> None:
    """Вопрос про тему приводит ответ по ней, а не по соседней.

    Проверяется содержание ответа, а не имя файла. Имя не годится:
    одна тема может лежать в двух файлах («что умеет без
    нейросети» есть и в словаре бота, и в отдельном файле), и
    требование пришло бы файлу чужой темой. Содержание же
    проверяет то, что важно человеку: ответил он по делу.
    """
    found = knowledge.найти("ada", CHAT, вопрос)
    assert found, f"на «{вопрос}» база промолчала"
    assert ожидаем in found.lower(), (
        f"на «{вопрос}» ждали ответ про «{ожидаем}», а пришло: "
        f"{found[:160]!r}")


def test_все_девять_файлов_на_месте() -> None:
    """Файлы не пропадали и не переименовались.

    Проверяем не список, а то, что на каждый ожидаемый файл приходится
    ответ по его теме: переименованный файл сделает тесты выше
    красными, а потерянный — молча уменьшит базу.
    """
    files = {p.stem for p in knowledge.KNOWLEDGE_ROOT.glob("*.md")}
    for имя in ("словарь", "боты", "решения", "как-пользоваться",
                "кто-такие-боты", "без-нейросети", "модели",
                "память-и-характер", "кнопки"):
        assert имя in files, f"файла {имя}.md нет: {sorted(files)}"


@pytest.mark.parametrize("вопрос", [
    "привет", "спасибо", "ок", "ага", "как дела", "пока", "хорошо",
])
def test_на_междометия_молчит(вопрос: str) -> None:
    """На «ок» из базы не должно уезжать ничего.

    Проверка особенно важна при росте базы: с каждым файлом растёт
    шанс, что короткое слово совпадёт с чужим заголовком.
    """
    assert knowledge.найти("ada", CHAT, вопрос) == "", (
        f"на «{вопрос}» уехало лишнее")


def test_лимит_не_превышен_на_широкий_вопрос() -> None:
    """Даже вопрос «про всё» не должен дать простыню.

    Ровно это было бы «огромным контекстом», которого мы избегали.
    """
    for вопрос in ("расскажи всё о проекте", "что ты вообще умеешь",
                   "объясни всё что можешь"):
        found = knowledge.найти("ada", CHAT, вопрос)
        assert len(found) <= knowledge.MAX_TOTAL, (
            f"на «{вопрос}» {len(found)} симв., лимит "
            f"{knowledge.MAX_TOTAL}")


def test_каждый_файл_доступен_по_своему_заголовку() -> None:
    """Файл находится и по слову из своего заголовка.

    Так проверяется весь файл целиком, а не отдельный раздел: если
    заголовок переименовать, тест сразу это покажет.
    """
    index = knowledge.построить_индекс()
    for path, (title, words, _) in index.items():
        имя_файла = Path(path).stem
        # Берём самое длинное слово заголовка — оно самое редкое
        # и потому самое надёжное как поисковый запрос.
        самое_редкое = max(words, key=len) if words else title
        found = knowledge.найти("ada", CHAT, самое_редкое)
        assert found, (
            f"{имя_файла}.md не находится по слову «{самое_редкое}»")
